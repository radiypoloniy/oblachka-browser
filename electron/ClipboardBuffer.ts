// Буфер скопированного СО СТРАНИЦ в этом браузере (не системный менеджер буфера обмена).
//
// ⚠️ Разница принципиальная, а не терминологическая. Системный менеджер опрашивает буфер ОС и
// записывает всё, что человек копирует в любых приложениях — включая пароли из менеджера паролей
// и чужую переписку. У нас в бэклоге безопасности прямо записано, что Windows Clipboard History
// это УГРОЗА для скопированного пароля (см. CLAUDE.md, раздел про пароли), и строить свою такую же
// было бы прямым противоречием.
//
// Поэтому источник ровно один: событие `copy` на гостевой странице (preload-content.ts). Из этого
// следует сразу всё:
//  • ничего, скопированного вне браузера, сюда не попадает в принципе;
//  • копирование пароля нашим же менеджером сюда не попадает — оно идёт мимо страницы;
//  • у каждой записи есть источник (сайт и время), и это главное, что делает список полезным:
//    «я это скопировал на Хабре полчаса назад», а не безымянная свалка строк.
//
// ⚠️ ТОЛЬКО В ПАМЯТИ и только на сеанс. Скопированное со страниц бывает чувствительным (адреса,
// номера заказов, куски переписки в веб-мессенджерах), и класть это на диск ради удобства нельзя.
// Закрыли браузер — буфера нет.
//
// ⚠️ ЕДИНСТВЕННОЕ исключение — ЗАКРЕПЛЁННОЕ (`pinned`), и оно не отменяет правила выше, а очерчивает
// его границу. «Браузер сам решил сохранить всё, что вы копировали» и «вы попросили сохранить вот
// это» — разные обещания, и на диск уходит только второе, зашифрованным (см. ClipboardPins.ts).
// Само закрепление — явный жест человека, а не наша догадка об удобстве.
import type { ClipboardEntry, ClipboardLink } from '../shared/ipc';
import { loadPinned, savePinned, dropPinned, MAX_PINNED } from './ClipboardPins';
// Порядок показа и вытеснение — чистые правила про закреплённое, живут в shared под
// scripts/clipboard-order-check.mjs: ломаются они молча, список при этом продолжает работать.
import { orderCopies, trimCopies } from '../shared/clipboardOrder';

// Сколько записей помним. Больше — уже не «последнее скопированное», а архив, которого мы не
// обещали и который тем опаснее, чем длиннее.
const MAX_ENTRIES = 60;
// Совсем короткое копируют не для переноса, а чтобы найти на странице (одно слово, число).
const MIN_CHARS = 2;
// Обрезаем гигантские копии: целая статья в памяти ни к чему, а показать мы всё равно показываем
// первые строки.
const MAX_CHARS = 20_000;

// Разметка и ссылки того же куска — см. ClipboardEntry.html/links в shared/ipc.
export interface RichCopy {
  html: string;
  links: ClipboardLink[];
}

let entries: ClipboardEntry[] = [];
let enabled = true;
let seq = 1;

export function isClipboardBufferEnabled(): boolean { return enabled; }

export function setClipboardBufferEnabled(on: boolean): void {
  enabled = on;
  // ⚠️ Выключение СТИРАЕТ уже собранное — И ЗАКРЕПЛЁННОЕ ТОЖЕ, вместе с файлом на диске. «Не веди
  // историю» с сохранением прежней — это половина обещания, и человек, нажавший выключатель,
  // ожидает не этого. Оставить закреплённое на диске после выключения буфера было бы ровно таким
  // же половинчатым обещанием, только хуже: оно пережило бы ещё и перезапуск.
  if (!on) { entries = []; dropPinned(); }
}

/**
 * Поднимает закреплённое с диска. Вызывать один раз при старте, ПОСЛЕ app.whenReady() (safeStorage
 * требует готовое приложение) и ДО первых копий.
 *
 * ⚠️ Счётчик id сдвигается за самый большой загруженный: он живёт только в памяти и после
 * перезапуска начинался бы с единицы, то есть новая копия получила бы id уже лежащей на полке
 * закреплённой записи. Дальше «скопировать» и «убрать» ходили бы не по той записи.
 */
export function loadPinnedFromDisk(): void {
  const loaded = loadPinned();
  if (loaded.length === 0) return;
  entries = [...loaded, ...entries];
  seq = Math.max(seq, ...loaded.map((e) => e.id)) + 1;
}

const persistPinned = (): void => savePinned(entries.filter((e) => e.pinned));

/**
 * Закрепить/открепить запись.
 *
 * ⚠️ Закрепление — единственное, что делает запись переживающей перезапуск, поэтому оно же
 * единственное, что пишет на диск. Возвращает false, когда полка полна: молча не закрепить хуже,
 * чем сказать об этом, — человек уверен, что запись сохранена, а её нет.
 */
export function setPinned(id: number, on: boolean): boolean {
  const entry = entries.find((e) => e.id === id);
  if (!entry) return false;
  if (on && !entry.pinned && entries.filter((e) => e.pinned).length >= MAX_PINNED) return false;
  if (on) entry.pinned = true; else delete entry.pinned;
  persistPinned();
  return true;
}

/**
 * Запомнить копию со страницы.
 *
 * ⚠️ Одинаковый текст подряд не дублируем, а поднимаем наверх: человек копирует одно и то же по
 * два-три раза (не сработала вставка, промахнулся), и список из повторов бесполезен.
 */
export function recordCopy(text: string, url: string, title: string, rich?: RichCopy): void {
  if (!enabled) return;
  // ⚠️ NUL ниже записан ESCAPE-последовательностью, а не сырым байтом. Сырой байт делал весь файл
  // бинарным для git: в статистике коммита стояло «Bin 0 -> 4867 bytes» вместо диффа — то есть
  // правку в самом чувствительном месте фичи (что именно мы запоминаем) нельзя прочитать в ревью.
  const value = text.replace(/\u0000/g, '').trim();
  if (value.length < MIN_CHARS) return;

  const clipped = value.length > MAX_CHARS ? value.slice(0, MAX_CHARS) : value;
  const host = (() => { try { return new URL(url).hostname.replace(/^www\./, ''); } catch { return ''; } })();

  // Пустые поля не пишем вовсе: у копии из поля ввода разметки нет, и `html: ''` в записи только
  // сбивал бы с толку того, кто её читает.
  const html = rich?.html || undefined;
  const links = rich?.links?.length ? rich.links : undefined;

  const same = entries.findIndex((e) => e.text === clipped);
  if (same !== -1) {
    // ⚠️ Повтор поднимается наверх ВМЕСТЕ со свежей разметкой: тот же текст можно скопировать во
    // второй раз уже со ссылкой (или наоборот, из голого поля), и запись должна описывать
    // последнее копирование, а не первое.
    const [existing] = entries.splice(same, 1);
    entries.unshift({ ...existing!, at: Date.now(), url, host, title, html, links });
    // Повтор мог оказаться закреплённым — тогда на диске лежит его прежняя версия, а мы только что
    // обновили источник и разметку. Спред выше сохранил сам флаг, файл дописываем здесь.
    if (existing!.pinned) persistPinned();
    return;
  }

  entries.unshift({ id: seq++, text: clipped, url, host, title, at: Date.now(), html, links });
  entries = trimCopies(entries, MAX_ENTRIES);
}

/** Список для поповера: закреплённое первым (правило — в shared/clipboardOrder.ts). */
export function listCopies(): ClipboardEntry[] {
  return orderCopies(entries);
}

/**
 * Уборка списка: стирает всё, КРОМЕ закреплённого.
 *
 * ⚠️ Здесь встречаются два разных намерения человека, и их нельзя обслуживать одной кнопкой.
 * «Очистить» — уборка: список зарос, уберите лишнее. «Не вести историю» (выключатель) — про
 * приватность: не хочу, чтобы это вообще где-то лежало. Закрепление — явный жест «не потеряй»,
 * и если уборка сносит защищённое, то защита не значит ничего.
 * Поэтому закреплённое переживает эту кнопку и НЕ переживает выключатель — там обещание другое
 * (см. setClipboardBufferEnabled). Первая версия стирала всё разом; исправлено по разбору с
 * пользователем, прецедент рядом — Windows Clipboard History чистит историю, не трогая
 * закреплённое.
 * Файл на диске трогать не нужно: в нём лежит ровно то, что остаётся.
 */
export function clearCopies(): void {
  entries = entries.filter((e) => e.pinned);
}

export function removeCopy(id: number): void {
  const wasPinned = entries.find((e) => e.id === id)?.pinned;
  entries = entries.filter((e) => e.id !== id);
  if (wasPinned) persistPinned();
}

/**
 * Запись целиком — она нужна всем оставшимся сценариям: переходу к источнику нужен адрес, а
 * повторному копированию — разметка со ссылками (см. обработчик CLIPBOARD_PUT). Прежний
 * `copyById`, отдававший один текст, после этого оказался не нужен и убран.
 */
export function entryById(id: number): ClipboardEntry | null {
  return entries.find((e) => e.id === id) ?? null;
}

/**
 * Строки-кандидаты для подсветки скопированного на странице, от длинной к короткой.
 *
 * ⚠️ Первым идёт ВЕСЬ скопированный кусок, и это главное отличие от `highlightCandidates` из
 * SmartFind. Там модель ВЫБИРАЕТ фрагмент, и лесенка сразу режет его до первого предложения и 90
 * символов; здесь же текст известен точно — человек сам его выделил, — и резать его заранее
 * означает подсветить одну фразу вместо всего абзаца (живая жалоба: «подсветка работает, но
 * только на одну фразу»).
 *
 * ⚠️ Второй ступенью — первый АБЗАЦ, а не следующий кусок по длине: findInPage не ищет через
 * границу блочного элемента, поэтому копия из двух абзацев не найдётся целиком никогда, сколько
 * её ни укорачивай с конца. Дальше — обычная лесенка SmartFind: вёрстка внутри абзаца тоже умеет
 * разорвать текст, и там она уже отработана.
 */
export function highlightSteps(text: string, ladder: (q: string) => string[]): string[] {
  const collapse = (s: string) => s.replace(/\s+/g, ' ').trim();
  const firstBlock = text.split(/\n+/, 1)[0] ?? '';
  const steps = [collapse(text), collapse(firstBlock), ...ladder(text)];
  // Дубли убираем: у однострочной копии первые две ступени совпадают, и вторая стоила бы лишнего
  // прохода по документу с ожиданием ответа Chromium.
  return steps.filter((s, i) => s.length >= 2 && steps.indexOf(s) === i);
}
