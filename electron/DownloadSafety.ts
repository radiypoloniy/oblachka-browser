// Защита скачанных файлов.
//
// ⚠️ Почему здесь НЕТ проверки файла через внешний сервис (VirusTotal и подобные). Любая такая
// проверка означает отправку наружу либо самого файла, либо его хэша — то есть сообщение чужому
// серверу о том, что человек скачал. Для браузера, который позиционируется как приватный, это
// прямое противоречие; за антивирус отвечает антивирус.
//
// Что делаем вместо этого — ровно то же, что Chrome, Edge и Firefox на Windows:
//
// 1. Метка зоны (Mark-of-the-Web). Рядом с файлом пишется альтернативный поток NTFS
//    «имя:Zone.Identifier» с ZoneId=3 («из интернета»). Это не украшение: по ней SmartScreen
//    предупреждает при запуске, Defender проверяет файл внимательнее, а Word и Excel открывают
//    документ в защищённом просмотре, где не выполняются макросы. Без метки всё это молчит —
//    скачанный файл выглядит для системы созданным на этом компьютере.
//    Работает только на NTFS; на флешке с FAT32 запись потока просто не удастся — это не ошибка.
//
// 2. Предупреждение о программах и скриптах — единственный вид файлов, где цена ошибки не
//    «лишний файл в Загрузках», а запущенный чужой код (см. DownloadManager).
//
// Платформенная часть заперта здесь: на macOS роль метки играет карантинный атрибут
// com.apple.quarantine, и меняться будет тело функции, а не её вызовы (см. CLAUDE.md).
import fs from 'node:fs';
import path from 'node:path';

// Расширения, которые Windows исполняет сама. Список — пересечение того, что помечают опасным
// Chrome и Microsoft; намеренно короткий: широкий список превращает предупреждение в шум,
// который перестают читать.
const RISKY_EXTENSIONS = new Set([
  '.exe', '.msi', '.msix', '.appx', '.bat', '.cmd', '.com', '.scr', '.pif',
  '.ps1', '.psm1', '.vbs', '.vbe', '.js', '.jse', '.wsf', '.wsh', '.hta',
  '.reg', '.cpl', '.dll', '.jar', '.lnk', '.inf', '.msc',
]);

export function isRiskyDownload(filename: string): boolean {
  return RISKY_EXTENSIONS.has(path.extname(filename).toLowerCase());
}

/**
 * Пометить файл как пришедший из интернета. Ошибки глушим намеренно: не-NTFS диск, файл уже
 * удалён или занят — всё это не повод показывать человеку сообщение о неудаче, файл он уже
 * получил. Молчаливый лог достаточен.
 */
export function markDownloadedFile(savePath: string, sourceUrl: string): void {
  if (process.platform !== 'win32') return;
  try {
    // ⚠️ HostUrl пишем без строки запроса: в ней бывают одноразовые токены и идентификаторы
    // сессии, а этот поток остаётся на диске рядом с файлом навсегда и читается кем угодно.
    let host = '';
    try {
      const u = new URL(sourceUrl);
      host = `${u.origin}${u.pathname}`;
    } catch { host = ''; }

    const content = ['[ZoneTransfer]', 'ZoneId=3', ...(host ? [`HostUrl=${host}`] : []), ''].join('\r\n');
    fs.writeFileSync(`${savePath}:Zone.Identifier`, content);
  } catch (e) {
    console.warn('[downloads] не удалось поставить метку зоны:', (e as Error).message);
  }
}
