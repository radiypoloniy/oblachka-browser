// Примерка уведомлений об изменении цены (OBLAKO_NOTIFY_PREVIEW=1).
//
// ⚠️ Идёт через ТОТ ЖЕ обработчик, что и настоящее уведомление, — иначе примерка показывала бы не
// то, что придёт человеку: очередь, «не беспокоить» и клик по тосту живут именно там.
//
// ⚠️ Вынесено из main.ts не ради красоты, а по правилу храповика структуры: main за порогом, и
// новая работа в нём оплачивается выносом, а не поднятием базы. Диагностический сценарий —
// первый кандидат на вынос: он не участвует в работе браузера ни одной строкой.

const SAMPLES = [
  { title: 'Ноутбук CHUWI Corebook Air 14"', text: 'Подешевело на 1 500 ₽ (-3%), сейчас 47 490 ₽' },
  { title: 'Биты для шуруповёрта IMPACT PH2', text: 'Больше нет в наличии' },
  { title: 'Умный выключатель Aqara H2', text: 'Снова в наличии — 4 592 ₽' },
];

/** Задержка перед первым тостом и шаг между ними: примерка идёт в ритме живых уведомлений. */
const FIRST_MS = 4000;
const STEP_MS = 4000;

export function previewTrackingToasts(
  show: (title: string, url: string, text: string) => void,
): void {
  setTimeout(() => {
    SAMPLES.forEach((s, i) => {
      setTimeout(() => show(s.title, 'https://example.com', s.text), i * STEP_MS);
    });
  }, FIRST_MS);
}
