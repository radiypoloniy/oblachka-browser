import { session, type Session } from 'electron';
import { INCOGNITO_PARTITION } from '../shared/ipc';
import { profilePartition, DEFAULT_PROFILE_ID } from '../shared/profiles';
import { getActiveProfile, getProfiles } from './ProfileStore';

// ЕДИНСТВЕННОЕ место, где приложение решает, «какой сессией ходить в сеть».
//
// ⚠️ Зачем этот модуль вообще существует. `net.fetch` — глобальная функция, и сессию она НЕ
// принимает: запрос уходит `session.defaultSession`. Значит каждый такой вызов молча привязан
// к профилю по умолчанию, а поиском по `defaultSession` его не найти — в коде там просто
// `net.fetch(url)`. Замер на 22.08.2026: 23 таких вызова в 16 файлах — погода, курсы, крипта,
// праздники, фавиконы, подсказки поиска, SearXNG, Gemini, загрузчик моделей, списки адблока,
// подписка VPN, фото новой вкладки, виджеты по ссылке. Ровно те места, которые обязаны идти
// через прокси профиля, и ровно те, которые поиском по `defaultSession` не находились.
//
// ⚠️ Чем это грозит, когда появятся профили и контейнеры: погода, курсы, крипта, праздники,
// фавиконы, подсказки поиска, SearXNG, Gemini, загрузчик моделей, обновление списков адблока и
// виджеты по ссылке продолжат ходить сессией ПЕРВОГО профиля — с его куками и его прокси.
// Для браузера, который обещает «свой VPN на профиль», это не косметика, а утечка того же
// класса, что закрывали волной 1 (см. шапки SearchSuggestFetcher.ts и VpnSubscription.ts:
// там ловили глобальный fetch, но сессия у net.fetch так и осталась неявной).
//
// ⚠️ Правило держит машина: `conventions-check.mjs` запрещает `net.fetch(` и
// `session.defaultSession` где угодно, кроме этого файла. Поэтому «проверить, все ли ходят
// правильно» перестало быть чтением 78 мест глазами.
//
// Сегодня профиль один, и все функции ниже возвращают дефолтную сессию — поведение НЕ
// изменилось ни на байт. Смысл в том, что появление второго профиля станет правкой здесь,
// а не ревизией всего main.

/**
 * Сессия конкретного профиля.
 *
 * ⚠️ У профиля по умолчанию партиции НЕТ — это `defaultSession`, где уже лежат куки и логины
 * человека (см. шапку shared/profiles.ts). Выдать ему собственную партицию значит разлогинить
 * его везде при первом же запуске.
 *
 * ⚠️ `session.fromPartition` идемпотентна: повторный вызов с тем же именем возвращает ТУ ЖЕ
 * сессию, а не новую. Поэтому кэшировать её здесь незачем, и незачем бояться лишних вызовов.
 */
export function sessionForProfile(profileId: string): Session {
  const partition = profilePartition(profileId);
  return partition === null ? session.defaultSession : session.fromPartition(partition);
}

/**
 * Сессия текущего профиля: обычные вкладки и служебные запросы приложения.
 *
 * ⚠️ Служебные запросы (погода, курсы, списки адблока) идут АКТИВНЫМ профилем — значит его
 * прокси и его VPN. Это осознанный выбор: человек, переключившийся в профиль «через VPN»,
 * не ждёт, что виджет погоды сходит мимо туннеля.
 * ⚠️ То, что вызвано конкретной вкладкой (её favicon), обязано идти сессией ЭТОЙ вкладки —
 * `wc.session.fetch`, а не отсюда: вкладка может принадлежать другому профилю, чем активный.
 */
export function profileSession(): Session {
  return sessionForProfile(getActiveProfile().id);
}

/**
 * Сессия приватных вкладок — своя, in-memory (см. INCOGNITO_PARTITION).
 *
 * ⚠️ Создаётся лениво и живёт здесь, а не в main.ts: список «сессий, по которым ходит
 * пользовательский трафик» нужен целиком в одном месте — на нём держится kill switch VPN.
 */
export function incognitoSession(): Session {
  return session.fromPartition(INCOGNITO_PARTITION);
}

/**
 * Все сессии, по которым идёт пользовательский трафик.
 *
 * ⚠️ Для того, что обязано применяться КО ВСЕМ сразу: прокси VPN, kill switch, адблок,
 * разрешения. Забыть одну сессию здесь — значит оставить дыру ровно того вида, который
 * закрывали в августе: приватный трафик мимо туннеля.
 */
export function allBrowsingSessions(): Session[] {
  // ⚠️ ВСЕ профили, а не только активный: вкладки неактивных профилей продолжают жить и
  // грузиться. Прокси и kill switch обязаны накрывать их тоже — иначе фоновая вкладка
  // соседнего профиля утечёт мимо туннеля, а это ровно та дыра, что закрывали в августе.
  const ids = getProfiles().profiles.map((p) => p.id);
  if (!ids.includes(DEFAULT_PROFILE_ID)) ids.push(DEFAULT_PROFILE_ID);
  return [...ids.map(sessionForProfile), incognitoSession()];
}

/**
 * Запрос от имени приложения (курсы, погода, фавиконы, обновление списков, виджеты по ссылке).
 *
 * ⚠️ Это `Session.fetch`, а не глобальный `net.fetch`: только у метода сессии запрос
 * действительно уходит нужной сессией, то есть через её прокси и её правила.
 *
 * ⚠️ Обёртка НАМЕРЕННО ничего не меняет в запросе — ни заголовков, ни политики кук. Этот
 * заход переводит 47 вызовов на одну сессию, и любое «заодно улучшим» здесь означало бы, что
 * при поломке нельзя отличить переезд от улучшения. Куки служебных запросов — отдельный
 * разговор и отдельная правка (сейчас `credentials: 'omit'` стоит на месте вызова там, где
 * это уже разобрано: FaviconService, favicon вкладок, GenWebSource).
 */
export function fetchInProfile(
  input: string | GlobalRequest,
  init?: RequestInit & { bypassCustomProtocolHandlers?: boolean },
): Promise<GlobalResponse> {
  return profileSession().fetch(input, init);
}
