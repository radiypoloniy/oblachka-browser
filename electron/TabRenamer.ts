// Умное имя вкладки: Qwen придумывает короткую подпись по СОДЕРЖИМОМУ страницы.
//
// Зачем. В вертикальном списке вкладок место под подпись узкое, а заголовки страниц под него не
// рассчитаны: у ролика это «(1) Как работают нейросети — простыми словами — YouTube», у поиска —
// сам запрос с хвостом параметров, у документа — «Untitled document». Через десять вкладок
// список перестаёт читаться. Модель отдаёт то, чем страница является для человека: «ролик про
// нейросети», а не «YouTube».
//
// Устройство — как у TabOrganizer: прямой промпт в Qwen через TranslationService (очередь
// withQwenQueue там уже есть, параллелить нечего — контекст один на приложение). Отличие в
// материале: организатору хватает заголовков, здесь нужен текст страницы, иначе имя будет
// пересказом того же заголовка.
import type { WebContents } from 'electron';
import { extractPageText } from './AiPanelManager';
import { runTabOrganizePrompt } from './TranslationService';

// Сколько текста страницы отдаём модели. Начало статьи описывает её лучше всего (заголовок,
// лид, первый абзац), а длинный кусок только разбавляет промпт и замедляет прогон.
const CONTEXT_CHARS = 1200;
// Потолок длины имени. ⚠️ Считан по факту, а не на глаз: в полосе вкладок помещается около
// двадцати знаков, дальше идёт многоточие. Прежние 34 давали имена, которые обрезались ровно
// так же, как исходные заголовки, — то есть смысла в переименовании не оставалось вовсе.
const MAX_TITLE_CHARS = 22;

function buildPrompt(title: string, url: string, text: string): string {
  return [
    'Ты придумываешь короткие названия для вкладок браузера.',
    '',
    'Правила:',
    '- ОЧЕНЬ коротко: 2–3 слова, не длиннее 20 символов вместе с пробелами.',
    '- По-русски, обычными словами, как сказал бы человек другому человеку.',
    '- Назови СУТЬ страницы, а не сайт: «ролик про ИИ», а не «YouTube».',
    '- Без кавычек, точки в конце, эмодзи и пояснений — только само название.',
    '',
    'Примеры хороших названий: «рецепт борща», «ставка ЦБ», «отзывы на дрель»,',
    '«вакансия в Яндексе», «билеты в Сочи».',
    '',
    `Адрес: ${url}`,
    `Заголовок: ${title}`,
    // У спящей вкладки текста нет — тогда и раздел не пишем, чтобы не звать модель придумывать
    // содержимое, которого мы ей не дали.
    ...(text ? ['Начало страницы:', text.slice(0, CONTEXT_CHARS)] : []),
    '',
    'Название:',
  ].join('\n');
}

// ⚠️ Модель охотно добавляет к ответу лишнее: кавычки, «Название:», точку, пояснение со второй
// строки. Чистим здесь, а не промптом — промпт уже просит об этом, но маленькая модель правило
// нарушает, и на это нельзя опираться (тот же урок, что с normalizeQuiz в NotebookStudio).
function cleanTitle(raw: string): string | null {
  let s = raw.trim().split(/\r?\n/)[0]?.trim() ?? '';
  s = s.replace(/^(название|title|имя)\s*[:—-]\s*/i, '');
  s = s.replace(/^["'«»„“]+|["'«»„“.]+$/g, '').trim();
  if (!s) return null;
  if (s.length > MAX_TITLE_CHARS) {
    // Режем по границе слова: обрубок посреди слова выглядит как ошибка, а не как сокращение.
    const cut = s.slice(0, MAX_TITLE_CHARS);
    const lastSpace = cut.lastIndexOf(' ');
    s = (lastSpace > 8 ? cut.slice(0, lastSpace) : cut).trim();
  }
  return s || null;
}

export async function suggestTabTitle(
  wc: WebContents | null,
  fallbackTitle: string,
  url: string,
): Promise<{ ok: true; title: string } | { ok: false; error: string }> {
  // ⚠️ Отсутствие живой вью — НЕ отказ: у спящей вкладки содержимого нет, но заголовок и адрес
  // есть, и по ним модель обычно даёт то же самое имя. Будить вкладку ради подписи нельзя —
  // «навести порядок» разом воскресил бы десятки страниц и съел бы память, ради которой их и
  // усыпили.
  let text = '';
  if (wc && !wc.isDestroyed()) {
    // Тот же слой фактов, что у истории, блокнота и графа (pageFacts → Readability): на карточке
    // товара он вернёт характеристики, а не отзывы.
    const page = await extractPageText(wc);
    text = page.text?.trim() ?? '';
  }
  if (text.length < 80 && !fallbackTitle && !url) {
    // Ни текста, ни заголовка, ни адреса — придумывать не из чего, а выдумка модели здесь была
    // бы хуже обычного заголовка.
    return { ok: false, error: 'Нечего назвать: страница пуста' };
  }

  const res = await runTabOrganizePrompt(buildPrompt(fallbackTitle, url, text));
  if (!res.ok) return { ok: false, error: res.error };

  const title = cleanTitle(res.out);
  if (!title) return { ok: false, error: 'Модель не дала названия' };
  return { ok: true, title };
}
