// Когда стирать приватную сессию.
//
// ⚠️ Партиция инкогнито ОДНА на приложение (INCOGNITO_PARTITION), а не на окно. Поэтому и
// «закрылась последняя приватная вкладка» считается по ВСЕМ окнам. Раньше флаг жил в TabManager
// каждого окна: закрытие последней приватной вкладки в окне A стирало куки живых приватных
// вкладок окна B, а перенос приватной вкладки оставлял флаг источнику — и первое же закрытие
// обычной вкладки там разлогинивало переехавшую страницу.
let pending = false;

// Создана приватная вкладка: после неё сессию будет что стирать.
export function noteIncognitoTab(): void { pending = true; }

// anyAlive — есть ли приватная вкладка хоть в одном окне. true — пора стирать (флаг гасится).
export function takeIncognitoClearIfDone(anyAlive: boolean): boolean {
  if (!pending || anyAlive) return false;
  pending = false;
  return true;
}
