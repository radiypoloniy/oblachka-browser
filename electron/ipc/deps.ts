// Контекст, который main.ts передаёт регистраторам IPC.
//
// Тип не написан руками, а выведен из самой фабрики в main.ts — иначе он разъедется с ней при
// первом же добавлении менеджера, и разъедется молча. `typeof import(...)` не создаёт настоящего
// импорта: конструкция чисто типовая и стирается при компиляции, поэтому цикла между main.ts и
// этими модулями в рантайме нет.
//
// ⚠️ Почему обработчики нарезаны НЕПРЕРЫВНЫМИ кусками, а не по доменам. `registerIpc` был одной
// функцией на 1666 строк, и обработчики в ней идут НЕ доменными группами: отслеживание товаров
// разорвано буфером обмена, пароли встречаются тремя разными местами. Доменная нарезка означала бы
// собирать каждый файл из десятка перемежающихся фрагментов — а это уже не перенос, а переписывание,
// с соответствующим шансом потерять обработчик по дороге. Поэтому границы взяты по существующим
// разрывам: тела обработчиков перенесены дословно, до единой строки. Отсюда и составные имена
// файлов вроде tracking.ts (товары И буфер) — они честно называют то, что внутри.
//
// Каждый регистратор начинается с деструктуризации нужной ему части контекста, поэтому строки
// внутри обработчиков не пришлось править вовсе.
export type IpcDeps = ReturnType<typeof import('../main').makeIpcDeps>;
