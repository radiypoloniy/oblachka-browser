// Локальный файл → адрес file://. Одна дверь на два входа: путь в аргументах запуска (двойной
// клик по .html, «Открыть с помощью») и путь, вставленный в омнибокс.
//
// ⚠️ Зачем вообще: установщик регистрирует за нами .htm/.html (build/installer.nsh), то есть
// система запускает `Oblako.exe "C:\...\page.html"`. Пока аргументы принимались только по схемам
// http/https, такой запуск не открывал НИЧЕГО — браузер поднимался с пустыми руками, и со стороны
// это выглядело как «html-файлы не открываются». В омнибоксе была вторая половина той же беды:
// строка вида `C:\...\page.html` кончается на `.html`, попадала под эвристику «похоже на хост» и
// уезжала на `https://C:/...`.
//
// ⚠️ СУЩЕСТВОВАНИЕ ФАЙЛА ПРОВЕРЯЕТСЯ ВСЕГДА, и это несущая часть, а не придирка. Иначе любая
// опечатка, похожая на путь, превращалась бы в file:// в никуда вместо честного поиска; а в
// аргументах запуска лежат ещё и ключи Chromium, и путь к самому приложению — принимать оттуда
// произвольную строку значит открывать что попало по чужой команде.
import fs from 'node:fs'
import { pathToFileURL } from 'node:url'

// Формы пути, которые вообще имеет смысл проверять на диске. Держим ОДНОЙ функцией под
// macOS-порт: на Windows это диск и UNC, на unix — просто корень.
function looksLikePath(s: string): boolean {
  return /^[a-zA-Z]:[\\/]/.test(s) // C:\… или C:/…
    || /^\\\\/.test(s)             // UNC: \\server\share
    || /^\//.test(s)               // /Users/…, /home/… (macOS и Linux)
}

/**
 * Путь к СУЩЕСТВУЮЩЕМУ файлу → `file://…`. Во всех остальных случаях null, и вызывающий волен
 * трактовать строку по-своему (поиск в омнибоксе, пропуск аргумента).
 * Каталог осознанно не принимаем: в аргументах запуска в dev-режиме лежит папка приложения, да и
 * листинга каталогов у нас нет — открылась бы пустота.
 */
export function localPathToFileUrl(input: string): string | null {
  const s = input.trim().replace(/^"(.*)"$/, '$1') // система умеет донести путь в кавычках
  if (!s || !looksLikePath(s)) return null
  try {
    if (!fs.statSync(s).isFile()) return null
    return pathToFileURL(s).href
  } catch {
    return null // нет такого файла или нет доступа — это не адрес
  }
}
