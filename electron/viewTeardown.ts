import type { WebContentsView } from 'electron';

// ⚠️ **Electron НЕ уничтожает дочерние WebContentsView вместе с окном.** Ни отложенные (прогретые
// заранее и ещё не добавленные в `contentView`), ни те, что реально лежат в окне на момент
// закрытия. Проверено замером (18.08.2026, изолированный профиль): лёгкое окно с одной вкладкой,
// закрытое как человеком (WM_CLOSE по его HWND), оставляет ЖИВЫМИ и свой слой хрома, и страницу
// своей вкладки — CDP-таргеты обоих остаются в списке, `Runtime.evaluate` в них отвечает и через
// шесть секунд после закрытия. То есть закрытое окно уносило с собой НОЛЬ рендереров.
//
// Ошибочная вера в обратное («вью Electron уничтожает сам вместе с contentView») была записана
// комментариями сразу в нескольких менеджерах, поэтому правило вынесено сюда одной функцией:
// у кого есть привязанная к окну вью — тот закрывает её сам в `win.once('closed')`.
//
// Почему `close()`, а не `destroy()`: это тот же путь, каким страница закрывает сама себя
// (`window.close()`), он корректно сносит рендерер и не спрашивает beforeunload — окна уже нет,
// и диалог «уверены, что хотите уйти?» показывать некому и негде.
export function closeWindowView(view: WebContentsView | null | undefined): void {
  if (!view || view.webContents.isDestroyed()) return;
  try {
    view.webContents.close();
  } catch (e) {
    // Гонка с уничтожением снаружи (страница закрыла себя сама в этот же момент) — не повод
    // ронять разбор окна: остальные вью обязаны закрыться в любом случае.
    console.warn('[teardown] вью не закрылась:', (e as Error).message);
  }
}
