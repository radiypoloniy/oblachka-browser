// Контекст, который main.ts передаёт сборщикам окна (window/*.ts).
//
// Тип выведен из самой фабрики в main.ts, а не написан руками, — иначе он разъедется с ней при
// первом же добавлении менеджера, и разъедется молча. `typeof import(...)` не создаёт настоящего
// импорта: конструкция чисто типовая и стирается при компиляции, поэтому цикла между main.ts и
// этими модулями в рантайме нет. Тот же приём, что у electron/ipc/deps.ts.
export type WindowDeps = ReturnType<typeof import('../main').makeWindowDeps>;
