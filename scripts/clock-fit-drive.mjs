// Ключевое число плитки не вылезает за её край. Не *-check.mjs — поднимает настоящее приложение.
//
// ⚠️ ЗАВЕДЕНО ПОТОМУ, ЧТО ОДНА И ТА ЖЕ ПОЛОМКА СЛУЧИЛАСЬ ДВАЖДЫ. Кегль времени считается не
// константой, а формулой: доступная ширина делится на ширину строки в единицах кегля. Ширина
// строки берётся из замеренных долей (DIGIT_EM и соседи в widgets.tsx), и оба раза ошибались
// именно в них — сперва при смене гарнитуры на дисплейную, потом при «уточнении» замера канвой.
// Симптом одинаковый и заметный: «14:34» упирается в правый край и обрезается.
//
// ⚠️ Канва тут и виновата: `measureText` НЕ ПРИМЕНЯЕТ `font-variant-numeric: tabular-nums`, а роль
// DISPLAY его включает. В Unbounded «0» это 0.917 em, а «1» — 0.507; канва меряет
// пропорциональные, интерфейс рисует табличные, и доля выходит заниженной почти вдвое. Никакая
// проверка чистой логики этого не увидит: числа-константы согласуются сами с собой, а расходятся
// они с НАСТОЯЩИМ шрифтом в НАСТОЯЩЕМ браузере.
//
// ⚠️ Меряем ПОЛЯ СЛЕВА И СПРАВА, а не «влезло ли». Строка, вплотную прижатая к краю, формально
// влезает, но читается как обрезанная — а композиция плитки задаёт поле около 9 % с каждой
// стороны (VALUE_SIDE). Поэтому порог не ноль: отрицательное поле — брак, нулевое — тоже.
//
// ⚠️ Часы есть в раскладке по умолчанию, профиль стенда чистый — ставить ничего не нужно.
//
// Запуск: npm run drive -- clock-fit
import { withStand, wait } from './isolated-stand.mjs';

let ok = 0;
let bad = 0;
const check = (what, cond, detail = '') => {
  if (cond) { ok++; console.log(`  ok   ${what}${detail ? ` — ${detail}` : ''}`); }
  else { bad++; console.log(` FAIL  ${what}${detail ? ` — ${detail}` : ''}`); }
};

// Время узнаём по тексту вида 19:44 в узле без детей-элементов: другой такой строки на столе нет.
const PROBE = `(() => {
  const nodes = [...document.querySelectorAll('div')].filter((d) =>
    d.children.length === 0 && /^\\d{1,2}:\\d{2}(:\\d{2})?$/.test((d.textContent || '').trim()));
  if (nodes.length === 0) return { ошибка: 'узел времени не найден' };
  return nodes.map((t) => {
    // Плитка — ближайший предок с высотой в пикселях (её задаёт сетка стола).
    let frame = t;
    for (let i = 0; i < 10 && frame && !/px/.test(frame.style.height || ''); i++) frame = frame.parentElement;
    const r = t.getBoundingClientRect();
    const f = frame ? frame.getBoundingClientRect() : null;
    const cs = getComputedStyle(t);
    return {
      text: (t.textContent || '').trim(),
      fontSize: Math.round(parseFloat(cs.fontSize)),
      textW: +r.width.toFixed(1),
      tile: f ? { w: Math.round(f.width), h: Math.round(f.height) } : null,
      left: f ? +(r.left - f.left).toFixed(1) : null,
      right: f ? +(f.right - r.right).toFixed(1) : null,
    };
  });
})()`;

await withStand(async (ctx) => {
  await wait(6000);
  const rows = await ctx.chrome.evaluate(PROBE);
  if (!Array.isArray(rows)) {
    check('часы найдены на столе', false, JSON.stringify(rows));
  } else {
    check('часы найдены на столе', rows.length > 0, `${rows.length} шт.`);
    for (const r of rows) {
      const where = `${r.text} кеглем ${r.fontSize} в плитке ${r.tile?.w}x${r.tile?.h}`;
      // ⚠️ Порог 6 px, а не 0: поле в 9 % от плитки даёт около 20 px, но на самой мелкой плитке
      // (одна клетка) оно законно меньше. Ноль означал бы «строка касается края» — это уже брак.
      check(`время не вылезает вправо (${where})`, (r.right ?? -1) >= 6, `справа ${r.right} px`);
      check(`время не вылезает влево (${where})`, (r.left ?? -1) >= 6, `слева ${r.left} px`);
      // ⚠️ Симметрии тут НЕ ТРЕБУЕМ, и это исправление собственного выдуманного ожидания: время
      // в плитке выключено ВЛЕВО, как заголовок дня над ним и дата под ним. Ассерт «стоит по
      // центру» краснел на исправном коде — то есть проверял не дизайн, а мою догадку о нём.
      //
      // ⚠️ Зато держим ВТОРОЙ КРАЙ. Ошибиться в долях можно в обе стороны: завысить — строка
      // вылезет (что и случалось дважды), занизить — часы съёжатся и потеряются в пустоте, а
      // заметить это глазом гораздо труднее. Доля ширины между 0.60 и 0.95 — то самое «ключевое
      // число во всю плитку», которое задаёт композиция (VALUE_SIDE = 0.82).
      const content = (r.tile?.w ?? 0) - 2 * (r.left ?? 0);
      const share = content > 0 ? r.textW / content : 0;
      check(`время занимает плитку, а не теряется в ней (${where})`,
        share >= 0.60 && share <= 0.95, `доля ширины ${share.toFixed(2)}`);
    }
  }
});

console.log(`\nИтого: ${ok} прошло, ${bad} не прошло\n`);
process.exit(bad === 0 ? 0 : 1);
