// Прогон очистки разметки, написанной моделью (shared/docMarkup.ts) — голым node, без electron.
//
// ⚠️ Это САМАЯ ответственная чистая логика в блокноте: через неё проходит текст, который модель
// написала по материалам ЧУЖИХ страниц, и он попадает прямиком в разметку документа, который
// человек потом кому-то отправит. Ошибка здесь тихая — страница выглядит целой, пока в
// источнике не встретится угловая скобка или пока модель не оборвётся на середине списка.
//
// ⚠️ Правило проверок ниже одно: НИЧЕГО НЕ ТЕРЯТЬ И НИЧЕГО ЛИШНЕГО НЕ ПРОПУСКАТЬ. Терять текст
// хуже, чем пропустить незнакомый тег (абзац не восстановишь), поэтому неизвестные теги
// разворачиваются, а не выбрасываются вместе с содержимым.
//
// Запуск: npm test -- doc-markup
import { sanitizeDocHtml, markupTextLength, PAGE_MIN_CHARS } from '../shared/docMarkup.ts';

let passed = 0;
let failed = 0;

function check(what, actual, expected) {
  const ok = JSON.stringify(actual) === JSON.stringify(expected);
  if (ok) passed++; else failed++;
  console.log(`${ok ? '  ok  ' : ' FAIL '} ${what}\n         получили ${JSON.stringify(actual)}, ждали ${JSON.stringify(expected)}`);
}

// ── обычная работа ──────────────────────────────────────────────────────────
check(
  'заголовок и абзац проходят как есть',
  sanitizeDocHtml('<h2>Раздел</h2><p>Текст абзаца.</p>'),
  '<h2>Раздел</h2><p>Текст абзаца.</p>',
);
check(
  'список сохраняется целиком',
  sanitizeDocHtml('<ul><li>Раз</li><li>Два</li></ul>'),
  '<ul><li>Раз</li><li>Два</li></ul>',
);
check(
  'таблица сохраняется',
  sanitizeDocHtml('<table><tr><td>Вектор</td><td>Обновление</td></tr></table>'),
  '<table><tr><td>Вектор</td><td>Обновление</td></tr></table>',
);
check(
  'выделения внутри абзаца живут',
  sanitizeDocHtml('<p>Это <strong>важно</strong> и <em>тонко</em>.</p>'),
  '<p>Это <strong>важно</strong> и <em>тонко</em>.</p>',
);

// ── АТРИБУТЫ НЕ ПЕРЕНОСЯТСЯ ВООБЩЕ ──────────────────────────────────────────
// ⚠️ Ни class, ни style, ни data-*. Вид принадлежит нашему CSS — это единственное, что не даёт
// документу разъезжаться от прогона к прогону. Заодно закрывает и обработчики событий.
check(
  'class от модели не проходит',
  sanitizeDocHtml('<p class="lede fancy">Текст</p>'),
  '<p>Текст</p>',
);
check(
  'style от модели не проходит',
  sanitizeDocHtml('<p style="color:red;font-size:99px">Текст</p>'),
  '<p>Текст</p>',
);
check(
  'обработчик события не проходит',
  sanitizeDocHtml('<p onclick="alert(1)">Текст</p>'),
  '<p>Текст</p>',
);
check(
  'ссылка разворачивается, текст остаётся',
  sanitizeDocHtml('<p>Читайте <a href="javascript:alert(1)">тут</a>.</p>'),
  '<p>Читайте тут.</p>',
);

// ── ОПАСНОЕ И МУСОРНОЕ ──────────────────────────────────────────────────────
check(
  'скрипт выбрасывается вместе с телом',
  sanitizeDocHtml('<p>До</p><script>alert(1)</script><p>После</p>'),
  '<p>До</p><p>После</p>',
);
check(
  'стиль выбрасывается вместе с телом',
  sanitizeDocHtml('<style>body{display:none}</style><p>Текст</p>'),
  '<p>Текст</p>',
);
check(
  'iframe выбрасывается',
  sanitizeDocHtml('<iframe src="http://evil"></iframe><p>Текст</p>'),
  '<p>Текст</p>',
);
check(
  'комментарий выбрасывается',
  sanitizeDocHtml('<!-- заметка модели --><p>Текст</p>'),
  '<p>Текст</p>',
);

// ── НИЧЕГО НЕ ТЕРЯТЬ ────────────────────────────────────────────────────────
// ⚠️ Неизвестный тег РАЗВОРАЧИВАЕТСЯ. Модель по привычке заворачивает всё в div и section;
// выбрасывать их вместе с содержимым значило бы терять целые разделы.
check(
  'неизвестная обёртка разворачивается, содержимое живёт',
  sanitizeDocHtml('<div><section><p>Абзац</p></section></div>'),
  '<p>Абзац</p>',
);
// ⚠️ h1 выбрасывается ВМЕСТЕ с текстом, в отличие от прочих незнакомых тегов. Название страницы
// ставим мы из плана, а модель почти всегда повторяет его первым заголовком — два одинаковых
// заголовка подряд читаются как поломка.
check(
  'h1 выбрасывается: заголовок страницы ставим мы',
  sanitizeDocHtml('<h1>Название</h1><p>Текст</p>'),
  '<p>Текст</p>',
);
// Правило настоящего HTML: следующий пункт закрывает предыдущий. Модель так пишет регулярно.
check(
  'новый пункт закрывает предыдущий, а не вкладывается',
  sanitizeDocHtml('<ul><li>Раз<li>Два</ul>'),
  '<ul><li>Раз</li><li>Два</li></ul>',
);
check(
  'новая ячейка закрывает предыдущую',
  sanitizeDocHtml('<table><tr><td>А<td>Б</tr></table>'),
  '<table><tr><td>А</td><td>Б</td></tr></table>',
);
check(
  'заголовок закрывает незакрытый абзац',
  sanitizeDocHtml('<p>Текст<h2>Раздел</h2>'),
  '<p>Текст</p><h2>Раздел</h2>',
);

// ── ОБОРВАННЫЙ ОТВЕТ ────────────────────────────────────────────────────────
// ⚠️ Живой случай, не выдуманный: генерация упирается в потолок токенов или её прерывают
// кнопкой. Незакрытый <ul> утаскивает за собой всю оставшуюся страницу.
check(
  'незакрытые теги закрываются сами',
  sanitizeDocHtml('<h2>Раздел</h2><ul><li>Раз<li>Два'),
  '<h2>Раздел</h2><ul><li>Раз</li><li>Два</li></ul>',
);
check(
  'оборванный абзац закрывается',
  sanitizeDocHtml('<p>Начало фразы, которая'),
  '<p>Начало фразы, которая</p>',
);
check(
  'закрывашка без открывашки не ломает поток',
  sanitizeDocHtml('</p><p>Текст</p>'),
  '<p>Текст</p>',
);

// ── ОБВЯЗКА ОТ МОДЕЛИ ───────────────────────────────────────────────────────
check(
  'ограждение ```html срезается',
  sanitizeDocHtml('```html\n<p>Текст</p>\n```'),
  '<p>Текст</p>',
);
check(
  'вводная фраза модели срезается',
  sanitizeDocHtml('Вот готовая страница:\n<h2>Раздел</h2><p>Текст</p>'),
  '<h2>Раздел</h2><p>Текст</p>',
);
check(
  'полный каркас страницы сводится к телу',
  sanitizeDocHtml('<html><head><title>Т</title></head><body><p>Текст</p></body></html>'),
  '<p>Текст</p>',
);
check(
  'article разворачивается до содержимого',
  sanitizeDocHtml('<article><p>Текст</p></article>'),
  '<p>Текст</p>',
);

// ── ЭКРАНИРОВАНИЕ ТЕКСТА ────────────────────────────────────────────────────
check(
  'угловые скобки в тексте экранируются',
  sanitizeDocHtml('<p>Условие a &lt; b и знак 5 > 3</p>'),
  '<p>Условие a &lt; b и знак 5 &gt; 3</p>',
);
check(
  'амперсанд экранируется',
  sanitizeDocHtml('<p>Procter &amp; Gamble</p>'),
  '<p>Procter &amp; Gamble</p>',
);

// ── мусор на входе ──────────────────────────────────────────────────────────
check('пустая строка даёт пустую разметку', sanitizeDocHtml(''), '');
check('не строка не роняет', sanitizeDocHtml(null), '');
check('текст без тегов остаётся текстом', sanitizeDocHtml('Просто фраза'), 'Просто фраза');

// ── длина текста ────────────────────────────────────────────────────────────
check('длина считается без тегов', markupTextLength('<p>Пять</p>'), 4);
check('порог страницы разумный', PAGE_MIN_CHARS >= 400, true);

console.log(`\nИтого: ${passed} прошло, ${failed} не прошло\n`);
process.exit(failed === 0 ? 0 : 1);
