// Отделение логотипа от подложки для скриптов сборки (иконка приложения, картинки установщика).
//
// ⚠️ Общий модуль, а не копия в каждом скрипте: маска логотипа — самое хрупкое место всей
// цепочки, и две её версии разъехались бы на первой же смене логотипа.
//
// ⚠️ ОДНОЙ ЗАЛИВКОЙ ПО ЦВЕТУ ЭТО НЕ РЕШАЕТСЯ, и вот почему. Заливка от краёв (а не «все белые
// пиксели прозрачные») нужна потому, что внутри облака тоже есть почти белые области. Но у нашего
// логотипа блики на облаках совпадают с подложкой ПОБАЙТОВО — (251,250,253) против (248,249,253),
// то есть разница 2–3 единицы при том, что сам фон гуляет на 3. Заливка честно протекает сквозь
// блик внутрь и выедает облаку широкую полосу: на иконке это выглядело рваным краем, будто
// картинку надорвали. Понижение порога не помогает (разница меньше шума фона), морфологическое
// размыкание тоже (полоса широкая, а не тонкий канал) — пробовали оба.
//
// ⚠️ Решает ГЕОМЕТРИЯ, а не цвет: знак — круг, и всё внутри круга принадлежит знаку по
// определению, чем бы оно ни было закрашено. Круг находится по НАСЫЩЕННЫМ пикселям (небо внутри
// круга заведомо далеко от почти-белой подложки), а заливка остаётся ровно для того, ради чего
// она и нужна, — для части облака, выходящей за круг снизу.
const TOL = 10;
// Порог «это точно не подложка»: небо внутри круга отличается от неё на десятки единиц, а любые
// блики и антиалиасинг — на единицы. Планка выбрана заведомо выше шума фона.
const STRONG = 25;

/**
 * Разбор логотипа: где подложка, какая у пикселя альфа и каковы габариты самого знака.
 * Возвращает { px, alphaAt, minX, minY, logoW, logoH }.
 */
export function extractLogo(src) {
  const { width, height, channels } = src;
  const px = (x, y) => { const o = (y * width + x) * channels; return [src.data[o], src.data[o + 1], src.data[o + 2]]; };
  const bg = px(0, 0);
  const dist = (c) => Math.max(Math.abs(c[0] - bg[0]), Math.abs(c[1] - bg[1]), Math.abs(c[2] - bg[2]));

  // ── круг знака по насыщенным пикселям ──────────────────────────────────────
  // Ширину берём именно у насыщенных: по высоте туда попадает и тень облака, вылезающего за круг
  // снизу, а по ширине круг — самое широкое, что есть.
  let sMinX = width, sMaxX = -1, sMinY = height;
  for (let y = 0; y < height; y++) for (let x = 0; x < width; x++) {
    if (dist(px(x, y)) > STRONG) {
      if (x < sMinX) sMinX = x;
      if (x > sMaxX) sMaxX = x;
      if (y < sMinY) sMinY = y;
    }
  }
  const hasCircle = sMaxX > sMinX;
  const r = hasCircle ? (sMaxX - sMinX + 1) / 2 : 0;
  const cx = (sMinX + sMaxX) / 2;
  const cy = sMinY + r;
  const insideCircle = (x, y) => hasCircle && Math.hypot(x - cx, y - cy) <= r - 0.5;

  // ── подложка заливкой от краёв ─────────────────────────────────────────────
  const isBg = new Uint8Array(width * height);
  const stack = [];
  const push = (x, y) => {
    const i = y * width + x;
    // ⚠️ Внутрь круга заливка не заходит вовсе — именно это и чинит выеденную полосу.
    if (isBg[i] || insideCircle(x, y) || dist(px(x, y)) > TOL) return;
    isBg[i] = 1; stack.push(i);
  };
  for (let x = 0; x < width; x++) { push(x, 0); push(x, height - 1); }
  for (let y = 0; y < height; y++) { push(0, y); push(width - 1, y); }
  while (stack.length) {
    const i = stack.pop(), x = i % width, y = (i / width) | 0;
    if (x > 0) push(x - 1, y);
    if (x < width - 1) push(x + 1, y);
    if (y > 0) push(x, y - 1);
    if (y < height - 1) push(x, y + 1);
  }

  // Мягкий край: у самой границы альфа берётся по удалённости от цвета подложки, иначе после
  // масштабирования вылезет «пила». Внутри круга знак непрозрачен всегда.
  const alphaAt = (x, y) => {
    if (insideCircle(x, y)) return 1;
    if (isBg[y * width + x]) return 0;
    return Math.min(1, dist(px(x, y)) / TOL);
  };

  // Габариты знака — центрируем по реальному содержимому, а не по центру исходника.
  let minX = width, minY = height, maxX = -1, maxY = -1;
  for (let y = 0; y < height; y++) for (let x = 0; x < width; x++) {
    if (alphaAt(x, y) > 0) {
      if (x < minX) minX = x; if (x > maxX) maxX = x;
      if (y < minY) minY = y; if (y > maxY) maxY = y;
    }
  }
  return { px, alphaAt, minX, minY, logoW: maxX - minX + 1, logoH: maxY - minY + 1 };
}
