// Отделение логотипа от подложки для скриптов сборки (иконка приложения, картинки установщика).
//
// ⚠️ Общий модуль, а не копия в каждом скрипте: маска логотипа — самое хрупкое место всей
// цепочки, и две её версии разъехались бы на первой же смене логотипа.
//
// ⚠️ ЗНАК ТЕПЕРЬ — СКРУГЛЁННАЯ ПЛИТКА, а не круг. Прежняя версия искала круг по насыщенным
// пикселям и заливкой добирала облако, вылезающее за него снизу; на плитке это не работает
// вовсе — у неё прямые стороны, и «круг по габаритам» съедал бы углы.
//
// ⚠️ ОДНОЙ ЗАЛИВКОЙ ПО ЦВЕТУ ЭТО ПО-ПРЕЖНЕМУ НЕ РЕШАЕТСЯ. Внутри плитки есть кремовое облако,
// побайтово близкое к подложке: (245,238,220) против (252,245,231). Заливка «всё, что похоже на
// фон» протекла бы внутрь через антиалиасинг края и выела бы облако.
//
// ⚠️ Решает ГЕОМЕТРИЯ, как и раньше, только другая: габариты насыщенных пикселей дают саму
// плитку, всё внутри неё принадлежит знаку по определению, а заливка работает ТОЛЬКО от четырёх
// углов габаритного прямоугольника — то есть ровно там, где за скруглением остаётся подложка.
// До облака она не достаёт: между углом и облаком всегда лежит цветная область.
const TOL = 10;
// Порог «это точно не подложка»: цвета плитки отличаются от неё на десятки единиц, а блики и
// антиалиасинг — на единицы. Планка заведомо выше шума фона.
const STRONG = 25;

export function extractLogo(src) {
  const { width, height, channels } = src;
  const px = (x, y) => { const o = (y * width + x) * channels; return [src.data[o], src.data[o + 1], src.data[o + 2]]; };
  const bg = px(0, 0);
  const dist = (c) => Math.max(Math.abs(c[0] - bg[0]), Math.abs(c[1] - bg[1]), Math.abs(c[2] - bg[2]));

  // ── габариты плитки по насыщенным пикселям ─────────────────────────────────
  let minX = width, maxX = -1, minY = height, maxY = -1;
  for (let y = 0; y < height; y++) for (let x = 0; x < width; x++) {
    if (dist(px(x, y)) > STRONG) {
      if (x < minX) minX = x;
      if (x > maxX) maxX = x;
      if (y < minY) minY = y;
      if (y > maxY) maxY = y;
    }
  }
  if (maxX < minX || maxY < minY) throw new Error('логотип не найден: подложка занимает весь кадр');
  const logoW = maxX - minX + 1;
  const logoH = maxY - minY + 1;

  // ── подложка в углах: заливка ТОЛЬКО от четырёх углов габаритов ────────────
  // ⚠️ Заливка ограничена габаритами плитки и стартует из её углов. Так она снимает подложку за
  // скруглением и физически не может дойти до кремового облака внутри: путь к нему перекрыт
  // цветными областями, а за пределы прямоугольника она не выходит.
  const outside = new Uint8Array(logoW * logoH);
  const stack = [];
  const push = (x, y) => {
    if (x < 0 || y < 0 || x >= logoW || y >= logoH) return;
    const i = y * logoW + x;
    if (outside[i]) return;
    if (dist(px(minX + x, minY + y)) > TOL) return;
    outside[i] = 1;
    stack.push(x, y);
  };
  push(0, 0); push(logoW - 1, 0); push(0, logoH - 1); push(logoW - 1, logoH - 1);
  while (stack.length) {
    const y = stack.pop(), x = stack.pop();
    push(x + 1, y); push(x - 1, y); push(x, y + 1); push(x, y - 1);
  }

  // ⚠️ Альфа МЯГКАЯ по краю: жёсткое «внутри/снаружи» на скруглении даёт лесенку, заметную уже
  // на 512 px. Полупрозрачность берётся из того, насколько пиксель ещё похож на подложку.
  const alphaAt = (x, y) => {
    if (x < minX || y < minY || x > maxX || y > maxY) return 0;
    const i = (y - minY) * logoW + (x - minX);
    if (!outside[i]) return 1;
    const d = dist(px(x, y));
    return d <= TOL ? 0 : Math.min(1, (d - TOL) / STRONG);
  };

  return { px, alphaAt, minX, minY, logoW, logoH };
}
