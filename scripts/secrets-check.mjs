// Сторож секретов: что уйдёт в публичный слепок вместе с исходниками.
//
// ⚠️ ЗАЧЕМ, и почему рабочего дерева МАЛО. Открытие репозитория публикует не текущий срез, а ВСЮ
// ИСТОРИЮ: 1400+ коммитов, каждый со своими версиями файлов. Ключ, добавленный по ошибке и убранный
// следующим коммитом, из рабочего дерева исчез, а из истории — нет, и лежит там навсегда. Поэтому
// проверка идёт по двум фронтам: файлы под гитом сейчас и все блобы во всех коммитах.
//
// ⚠️ Отзыв дешевле поиска. Если находка есть — правильный ход не «переписать историю», а ОТОЗВАТЬ
// ключ у того, кто его выдал: переписывание истории ненадёжно (клоны, кэши, форки), а отозванный
// ключ мёртв везде и сразу.
//
// ⚠️ Отдельная строка про VPN. Подписки Xray (vless://, vmess://, trojan://, ss://) — это НЕ
// адреса, а полноценные учётные данные: в них uuid и пароль сервера. Утечка такой строки означает,
// что чужой человек ходит через оплаченный туннель от вашего имени. В этом проекте они особенно
// вероятны: их вставляют руками при живой проверке VPN.
//
// Запуск: npm test -- secrets
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';

// ⚠️ Шаблоны намеренно узкие и «с формой»: широкие вроде /password/ дают сотни попаданий на
// обычном коде (имена полей, подписи в интерфейсе, комментарии), сторож тонет в шуме и его
// перестают читать. Здесь только то, у чего есть узнаваемая структура выданного ключа.
const PATTERNS = [
  { name: 'приватный ключ', re: /-----BEGIN (?:RSA |EC |OPENSSH |PGP )?PRIVATE KEY-----/ },
  { name: 'ключ OpenAI', re: /\bsk-[A-Za-z0-9]{32,}\b/ },
  { name: 'ключ Google/Gemini', re: /\bAIza[0-9A-Za-z_-]{35}\b/ },
  { name: 'токен GitHub', re: /\b(?:ghp|gho|ghu|ghs|ghr)_[A-Za-z0-9]{36}\b/ },
  { name: 'токен GitHub (fine-grained)', re: /\bgithub_pat_[A-Za-z0-9_]{22,}\b/ },
  { name: 'токен Slack', re: /\bxox[baprs]-[A-Za-z0-9-]{10,}\b/ },
  { name: 'ключ AWS', re: /\bAKIA[0-9A-Z]{16}\b/ },
  { name: 'ключ Anthropic', re: /\bsk-ant-[A-Za-z0-9_-]{20,}\b/ },
  // Подписка VPN: учётные данные сервера, а не адрес. Разбор — в шапке.
  { name: 'подписка VPN', re: /\b(?:vless|vmess|trojan|ss):\/\/[A-Za-z0-9+/=@:.-]{20,}/ },
];

/**
 * Что шаблонам показывать НЕ надо — именной и закрытый список.
 *
 * ⚠️ Каждая строка обязана иметь причину. Файл с примерами и файл с настоящим ключом выглядят
 * одинаково, и разница между ними — только в том, знает ли о ней человек.
 */
const ALLOW_PATHS = [
  // Сам сторож: шаблоны внутри него неизбежно похожи на то, что они ловят.
  'scripts/secrets-check.mjs',
  // Разборщик подписок: в комментариях и тестовых строках есть образцы формата vless://.
  'electron/VpnParser.ts',
];

let passed = 0;
let failed = 0;
const check = (what, ok, detail = '') => {
  if (ok) { passed++; console.log(`  ok   ${what}${detail ? ` — ${detail}` : ''}`); }
  else { failed++; console.log(` FAIL  ${what}${detail ? ` — ${detail}` : ''}`); }
};

const git = (args, max = 512 * 1024 * 1024) =>
  execFileSync('git', args, { encoding: 'utf8', maxBuffer: max });

function scan(text, where, hits) {
  for (const p of PATTERNS) {
    const m = p.re.exec(text);
    // ⚠️ Печатаем ТОЛЬКО название и место, никогда само значение: сторож, который выводит
    // найденный ключ в консоль и в лог CI, размножает утечку вместо того, чтобы её закрыть.
    if (m) hits.push({ where, name: p.name });
  }
}

// ── 1. Рабочее дерево: файлы, которые уйдут в слепок ──────────────────────────────────────────
console.log('\n— файлы под гитом чисты —');
const tracked = git(['ls-files']).split('\n').filter(Boolean);
const treeHits = [];
for (const f of tracked) {
  if (ALLOW_PATHS.includes(f)) continue;
  let text = '';
  try { text = fs.readFileSync(f, 'utf8'); } catch { continue; } // бинарники читаем и пропускаем
  scan(text, f, treeHits);
}
if (treeHits.length === 0) check('да', true, `${tracked.length} файлов`);
else for (const h of treeHits) check(`${h.where}: похоже на «${h.name}»`, false);

// ── 2. История: всё, что когда-либо было закоммичено ──────────────────────────────────────────
//
// ⚠️ Ищем ПО БЛОБАМ, а не `git log -p`: у diff-а нет полного содержимого файла, и ключ, лежавший
// в файле с самого его появления, в разнице может не показаться целиком. Блоб — это файл как он
// был, и его достаточно посмотреть один раз, даже если он встречается в сотне коммитов.
console.log('\n— история не содержит секретов —');
// ⚠️ Один процесс `git cat-file --batch` на всю историю, а не по вызову на блоб. Первая версия
// звала git на каждый объект: 7787 процессов, 205 секунд — и это в pre-commit, который до того
// укладывался в 19. Потоковый режим читает то же самое за секунды.
const objects = git(['rev-list', '--all', '--objects']).split('\n').filter(Boolean);
const blobs = new Map(); // sha -> путь (для сообщения)
for (const line of objects) {
  const sp = line.indexOf(' ');
  if (sp < 0) continue;
  const sha = line.slice(0, sp);
  const p = line.slice(sp + 1);
  if (!p || ALLOW_PATHS.includes(p)) continue;
  // ⚠️ Один и тот же sha — один и тот же файл: смотрим содержимое ровно раз, даже если он
  // встречается в сотне коммитов.
  if (!blobs.has(sha)) blobs.set(sha, p);
}

const histHits = [];
let read = 0;
if (blobs.size > 0) {
  const shas = [...blobs.keys()].join('\n') + '\n';
  const raw = execFileSync('git', ['cat-file', '--batch'], {
    input: shas, encoding: 'latin1', maxBuffer: 1024 * 1024 * 1024,
  });
  // Ответ идёт кадрами: заголовок «<sha> blob <размер>», перевод строки, содержимое, перевод строки.
  // ⚠️ Читаем latin1, а не utf8: размер в заголовке задан в БАЙТАХ, и на многобайтовых символах
  // посимвольная нарезка utf8 уехала бы — дальше разбор пошёл бы по мусору. Шаблоны ключей
  // состоят из ASCII, поэтому latin1 им ничем не мешает.
  let i = 0;
  while (i < raw.length) {
    const nl = raw.indexOf('\n', i);
    if (nl < 0) break;
    const head = raw.slice(i, nl).split(' ');
    const size = Number(head[2]);
    // Сломанный кадр — дальше читать нечего: смещения поехали, и всё последующее будет мусором.
    if (!Number.isFinite(size)) break;
    // ⚠️ Не-blob ПРОПУСКАЕМ, а не останавливаемся. `rev-list --objects` перечисляет и деревья
    // (у них тоже есть путь), и первым же кадром обычно идёт дерево корня. Первая версия здесь
    // выходила из цикла — и прогон честно рапортовал «1 версия файлов» вместо 7787, то есть
    // проверял историю ровно на один блоб. Ошибка тихая: зелёное получалось и так, и так.
    if (head[1] === 'blob') {
      scan(raw.slice(nl + 1, nl + 1 + size), `${blobs.get(head[0])} (в истории, ${head[0].slice(0, 8)})`, histHits);
      read++;
    }
    i = nl + 1 + size + 1;
  }
}
if (histHits.length === 0) check('да', true, `${read} версий файлов`);
else {
  for (const h of histHits) check(`${h.where}: похоже на «${h.name}»`, false);
  console.log('\n  ⚠️ Находка в ИСТОРИИ. Переписывать историю — не первый ход: клоны, форки и');
  console.log('     кэши GitHub её всё равно помнят. Первый ход — ОТОЗВАТЬ ключ у того, кто его');
  console.log('     выдал: отозванный ключ мёртв везде и сразу, где бы его копия ни лежала.');
}

console.log(`\nИтого: ${passed} ок, ${failed} провалено\n`);
process.exit(failed === 0 ? 0 : 1);
