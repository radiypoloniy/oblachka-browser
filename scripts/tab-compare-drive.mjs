import assert from 'node:assert/strict';
import fs from 'node:fs';
import { withStand, wait, connectCdp } from './isolated-stand.mjs';

await withStand(async ctx => {
  await ctx.chrome.evaluate(`window.oblako.setTheme('light','paper')`);
  const until = async (fn, label, timeout=25000) => {
    const end=Date.now()+timeout; while(Date.now()<end){if(await fn()){console.log('ok',label);return;}await wait(200);}throw new Error(label);
  };
  const make = async (id,ram,structured) => {
    const url=ctx.echoUrl('/product/'+id);
    const tabId=await ctx.chrome.evaluate(`window.oblako.createTab(${JSON.stringify(url)})`);
    const target=await ctx.findTarget(t=>t.url===url), page=connectCdp(target);await page.ready;
    await until(()=>page.evaluate('!!document.body'),'Страница готова к проверке');
    const ld={'@type':'Product',name:'Ноутбук '+id,category:'Ноутбуки',offers:{price:50000,priceCurrency:'RUB'},additionalProperty:[{name:'ОЗУ',value:ram},{name:'SSD',value:'512 ГБ'}]};
    const html=`<main itemscope itemtype="https://schema.org/Product"><h1>Ноутбук ${id}</h1><div> <span itemprop="price">45 000 ₽</span> с кошельком</div><table><tr><th>Оперативная память</th><td>${ram}</td></tr><tr><th>SSD</th><td>512 ГБ</td></tr></table><form><input value="SECRET"/></form>${structured?'<script type="application/ld+json">'+JSON.stringify(ld)+'</script>':''}</main>`;
    await page.evaluate(`document.body.innerHTML=${JSON.stringify(html)}`);
    return {tabId,url,page};
  };
  const a=await make('A','16 ГБ',true),b=await make('B','8 ГБ',false);
  await until(()=>ctx.chrome.evaluate(`window.oblako.tabCompareState().then(s=>s.candidates.length===2)`),'Автоматическое обнаружение без модели');
  await until(async()=>{const target=await ctx.findTarget(t=>t.url.includes('compareoffer.html'),1).catch(()=>null);return !!target;},'Нативный поповер предложения');
  const offer=connectCdp(await ctx.findTarget(t=>t.url.includes('compareoffer.html')));await offer.ready;
  await until(()=>offer.evaluate(`document.querySelectorAll('select option').length>0`),'Общий поповер загрузился');
  assert.ok((await offer.evaluate('document.body.innerText')).includes('Сравнить товары?'));
  assert.equal(await offer.evaluate(`document.querySelector('select').value`),'');
  await b.page.send('Input.dispatchMouseEvent',{type:'mousePressed',x:30,y:200,button:'left',clickCount:1});
  await b.page.send('Input.dispatchMouseEvent',{type:'mouseReleased',x:30,y:200,button:'left',clickCount:1});
  await wait(300);
  assert.equal(await ctx.evalMain(`(()=>{const req=process.mainModule.require,root=req('electron').app.getAppPath(),c=req(req('path').join(root,'dist-electron/electron/WindowRegistry.js')).mainContext();return c.win.contentView.children.some(v=>v.webContents?.getURL().includes('compareoffer.html'))})()`),false);
  await ctx.chrome.evaluate(`window.oblako.showTabCompareOffer({x:900,y:50,width:32,height:32})`);
  console.log('ok Закрытие кликом на страницу и повторное открытие');
  const shot=await offer.send('Page.captureScreenshot',{format:'png'});fs.mkdirSync('scripts/shots',{recursive:true});fs.writeFileSync('scripts/shots/tab-compare-offer.png',Buffer.from(shot.result.data,'base64'));
  await offer.evaluate(`[...document.querySelectorAll('button')].find(b=>b.textContent==='Сравнить').click()`);
  await until(()=>ctx.chrome.evaluate(`document.querySelectorAll('.compare-view tbody tr').length>=3`),'Таблица без модели: JSON-LD и видимая карточка');
  const state=await ctx.chrome.evaluate('window.oblako.tabCompareState()');
  assert.equal(state.phase,'ready');assert.equal(state.products.length,2);assert.ok(!JSON.stringify(state).includes('SECRET'));
  assert.ok(state.rows.find(r=>r.label==='Цена и условия').cells.every(f=>f.value.includes('кошельком')));
  await ctx.chrome.evaluate(`document.querySelector('.compare-controls input').click()`);
  assert.ok(!await ctx.chrome.evaluate(`[...document.querySelectorAll('.compare-view tbody th')].some(e=>e.textContent==='SSD')`));
  const tableShot=await ctx.chrome.send('Page.captureScreenshot',{format:'png'});fs.writeFileSync('scripts/shots/tab-compare-table.png',Buffer.from(tableShot.result.data,'base64'));
  const fact=state.products[0].facts.find(f=>f.label==='Оперативная память');
  assert.equal(await ctx.chrome.evaluate(`window.oblako.tabCompareSource(${JSON.stringify(state.products[0].tabId)},${fact.id})`),true);
  console.log('ok Переход к источнику и фильтр различий');
  await ctx.evalMain(`(()=>{const req=process.mainModule.require,root=req('electron').app.getAppPath(),mod=n=>req(req('path').join(root,'dist-electron/electron',n));
    const conn={id:'compare-test-cloud',label:'Тестовое облако',kind:'openai-compatible',baseUrl:'https://example.org/v1',model:'test',concurrency:1};
    mod('ai/ConnectionStore.js').upsert(conn);globalThis.compareCalls=0;globalThis.compareFail=false;
    mod('ai/registry.js').providerById=id=>({connection:conn,generateStructured:async()=>{globalThis.compareCalls++;if(globalThis.compareFail)throw new Error('Тест: модель недоступна');return {rows:[{label:'Выдуманная строка',refs:[9999,9999]}]};}});
  })()`);
  assert.equal(await ctx.evalMain('globalThis.compareCalls'),0);
  await ctx.chrome.evaluate(`window.oblako.startTabCompare(${JSON.stringify(state.products.map(p=>p.tabId))},'compare-test-cloud')`);
  const cloud=await ctx.chrome.evaluate('window.oblako.tabCompareState()');
  assert.equal(cloud.phase,'ready');assert.equal(cloud.via,'Тестовое облако');assert.equal(await ctx.evalMain('globalThis.compareCalls'),1);
  assert.ok(!cloud.rows.some(r=>r.label==='Выдуманная строка'));
  assert.deepEqual(cloud.rows.map(r=>r.cells.map(f=>f?.value)),state.rows.map(r=>r.cells.map(f=>f?.value)));
  await ctx.evalMain('globalThis.compareFail=true');
  await ctx.chrome.evaluate('window.oblako.refreshTabCompare()');
  const fallback=await ctx.chrome.evaluate('window.oblako.tabCompareState()');
  assert.equal(fallback.phase,'ready');assert.ok(fallback.rows.length>=3);assert.ok(fallback.note.includes('модель недоступна'));
  console.log('ok Один облачный вызов по кнопке, защита значений, таблица при ошибке модели');
  await ctx.chrome.evaluate('window.oblako.setTabCompareEnabled(false)');
  assert.equal((await ctx.chrome.evaluate('window.oblako.tabCompareState()')).enabled,false);
  console.log('ok Отдельное выключение');
  a.page.close();b.page.close();offer.close();
  await ctx.restart();
  await until(()=>ctx.chrome.evaluate('window.oblako?.tabCompareState().then(s=>s.enabled===false)'),'Настройка переживает перезапуск');
}, {main:true});
