// Прогон сравнения текста страницы (shared/textDiff.ts) — без electron, обычным node.
//
// Проверяется ОТСЕВ ШУМА: diff кодом получается всегда, вся ценность фичи в том, что мы
// показываем цену и срок доставки, а не двести изменившихся счётчиков и дат. Глазами это не
// проверить — только вопросами вида «что человек увидит на такой паре страниц».
//
// Запуск: npm run text-diff-check

import { diffPageText } from '../shared/textDiff.ts';

let passed = 0;
let failed = 0;

function check(what, actual, expected) {
  const a = JSON.stringify(actual);
  const b = JSON.stringify(expected);
  const ok = a === b;
  if (ok) passed++; else failed++;
  console.log(`${ok ? '  ok  ' : ' FAIL '} ${what}\n         получили ${a}\n         ждали    ${b}`);
}

// Куски в компактном виде: «было → стало», пустое обозначаем прочерком.
const pieces = (before, after) =>
  diffPageText(before, after).pieces.map((p) => `${p.before || '—'} → ${p.after || '—'}`);
const changed = (before, after) => diffPageText(before, after).changed;

// Живая страница товара: полезное вперемешку с шумом.
const CARD_BEFORE = [
  'Смартфон Умный Телефон 12 Pro, 256 ГБ, чёрный — характеристики и отзывы покупателей',
  'Цена: 79 990 ₽ с учётом скидки по промокоду до конца недели',
  'Доставка курьером по Москве завтра, 14 августа, бесплатно при заказе от 3000 ₽',
  '2 часа назад обновлено предложение продавца на этой витрине',
  '1 245 просмотров этого товара за сегодня по данным площадки',
  'Гарантия производителя 12 месяцев, сервисные центры в 40 городах России',
].join('\n');

const CARD_AFTER = [
  'Смартфон Умный Телефон 12 Pro, 256 ГБ, чёрный — характеристики и отзывы покупателей',
  'Цена: 84 990 ₽ с учётом скидки по промокоду до конца недели',
  'Доставка курьером по Москве послезавтра, 16 августа, бесплатно при заказе от 3000 ₽',
  '11 минут назад обновлено предложение продавца на этой витрине',
  '3 981 просмотр этого товара за сегодня по данным площадки',
  'Гарантия производителя 12 месяцев, сервисные центры в 40 городах России',
].join('\n');

console.log('\n— карточка товара: видим цену и срок, не видим счётчики —');
check('изменение числа в той же фразе даёт пару «было → стало»',
  pieces(CARD_BEFORE, CARD_AFTER),
  ['Цена: 79 990 ₽ с учётом скидки по промокоду до конца недели → Цена: 84 990 ₽ с учётом скидки по промокоду до конца недели',
   'Доставка курьером по Москве завтра, 14 августа, бесплатно при заказе от 3000 ₽ → Доставка курьером по Москве послезавтра, 16 августа, бесплатно при заказе от 3000 ₽']);

console.log('\n— шум сам по себе изменением не считается —');
const NOISE_ONLY_BEFORE = [
  'Условия оказания услуг и порядок возврата денежных средств покупателю',
  '2 часа назад этот материал был обновлён редакцией нашего издания',
  '1 245 просмотров у этой страницы за последние сутки по счётчику',
].join('\n');
const NOISE_ONLY_AFTER = [
  'Условия оказания услуг и порядок возврата денежных средств покупателю',
  '5 дней назад этот материал был обновлён редакцией нашего издания',
  '9 999 просмотров у этой страницы за последние сутки по счётчику',
].join('\n');
check('поменялись только счётчик и «столько-то назад» — молчим',
  changed(NOISE_ONLY_BEFORE, NOISE_ONLY_AFTER), false);

console.log('\n— страница не менялась —');
check('тот же текст — молчим', changed(CARD_BEFORE, CARD_BEFORE), false);
check('лишние пробелы и переносы не считаются изменением',
  changed('Условия оказания услуг и порядок возврата денежных средств\n\nГарантия 12 месяцев на весь модельный ряд',
          '  Условия   оказания услуг и порядок возврата денежных средств  \nГарантия 12 месяцев на весь модельный ряд'),
  false);

console.log('\n— слишком много изменений это другая страница, а не «что изменилось» —');
const FEED_BEFORE = Array.from({ length: 10 }, (_, i) =>
  `Новость номер ${i} про важные события сегодняшнего дня в стране и мире`).join('\n');
const FEED_AFTER = Array.from({ length: 10 }, (_, i) =>
  `Совершенно другая новость ${i} о погоде, спорте и городских происшествиях`).join('\n');
check('лента, где сменилось почти всё — молчим', changed(FEED_BEFORE, FEED_AFTER), false);

console.log('\n— появление и исчезновение кусков —');
check('новый абзац показывается как добавленный',
  pieces('Условия оказания услуг и порядок возврата денежных средств покупателю',
         'Условия оказания услуг и порядок возврата денежных средств покупателю\nТовара временно нет в наличии, ожидается поступление в сентябре'),
  ['— → Товара временно нет в наличии, ожидается поступление в сентябре']);
check('исчезнувший абзац показывается как убранный',
  pieces('Условия оказания услуг и порядок возврата денежных средств покупателю\nБесплатная доставка действует до конца текущего месяца включительно',
         'Условия оказания услуг и порядок возврата денежных средств покупателю'),
  ['Бесплатная доставка действует до конца текущего месяца включительно → —']);

console.log('\n— короткие строки не участвуют —');
check('кнопки и пункты меню меняются от перевёрстки и в счёт не идут',
  changed('Купить\nВ корзину\nУсловия оказания услуг и порядок возврата денежных средств покупателю',
          'Заказать\nОтложить\nУсловия оказания услуг и порядок возврата денежных средств покупателю'),
  false);

console.log('\n— пустой снимок —');
check('сравнивать не с чем — молчим', changed('', CARD_AFTER), false);

console.log(`\nИтого: ${passed} прошло, ${failed} не прошло\n`);
process.exit(failed === 0 ? 0 : 1);
