// Прогон сопоставления слов (shared/wordMatch.ts) — без electron, обычным node.
//
// Все случаи ниже, кроме помеченных, взяты с ЖИВОГО профиля: поиск «везде» не находил файл
// «отчет по исследованию.docx» ни по «исследования», ни по «исследование», а закладка со словом
// «Документы» обгоняла то, что человек искал.
//
// Запуск: npm run word-match-check
import { countMatches, queryTokens } from '../shared/wordMatch.ts';

let passed = 0;
let failed = 0;

function check(what, actual, expected) {
  const ok = JSON.stringify(actual) === JSON.stringify(expected);
  if (ok) passed++; else failed++;
  console.log(`${ok ? '  ok  ' : ' FAIL '} ${what}\n         получили ${JSON.stringify(actual)}, ждали ${JSON.stringify(expected)}`);
}

const score = (hay, q) => countMatches(hay, queryTokens(q));

console.log('\n— склонения: ровно то, из-за чего файл не находился —');
const FILE = 'отчет по исследованию.docx';
check('«исследования» находит «исследованию»', score(FILE, 'исследования') > 0, true);
check('«исследование» находит «исследованию»', score(FILE, 'исследование') > 0, true);
check('«исследованию» находит само себя', score(FILE, 'исследованию') > 0, true);
check('«отчет» находит «отчет»', score(FILE, 'отчет') > 0, true);

console.log('\n— сколько слов совпало, а не просто «да/нет» —');
check('оба слова запроса найдены', score(FILE, 'исследования отчет'), 2);
check('одно слово из двух', score(FILE, 'исследования договор'), 1);
check('совпавшее двумя словами сильнее совпавшего одним',
  score('Отчет по исследованию — документ.docx', 'исследования документ')
    > score('Новости 2001 - Google Документы', 'исследования документ'),
  true);
// ⚠️ Граница ответственности этого слоя, записанная сознательно. На запросе «исследования
// документ» файл «отчет по исследованию.docx» и закладка «Новости 2001 — Google Документы»
// набирают ПО ОДНОМУ совпадению каждый, просто по разным словам, — и различить их здесь нечем:
// «какое из слов важнее» это уже смысл, а не сопоставление строк. Задача кода — чтобы нужное
// вообще ПОПАЛО в кандидаты (ровно это и было сломано); порядок между источниками решает реранк.
check('оба остаются кандидатами, и это нормально',
  [score(FILE, 'исследования документ'), score('Новости 2001 - Google Документы', 'исследования документ')],
  [1, 1]);

console.log('\n— ложных совпадений быть не должно —');
check('короткое слово не цепляется за начало длинного чужого',
  score('видеопамять и требования к железу', 'вид'), 0);
check('чужое слово не находится', score(FILE, 'ипотека'), 0);
check('слова короче трёх букв в запрос не берутся', queryTokens('по на до'), []);

console.log('\n— ё и регистр —');
check('«елка» находит «Ёлка»', score('Ёлка новогодняя', 'елка') > 0, true);
check('регистр не важен', score('ОТЧЕТ ПО ИССЛЕДОВАНИЮ', 'отчет') > 0, true);

console.log('\n— латиница —');
check('латиница работает так же', score('DDX Fitness FEST 2025.docx', 'ddx') > 0, true);
check('расширение файла — обычное слово', score('договор.pdf', 'pdf') > 0, true);

console.log(`\nИтого: ${passed} прошло, ${failed} не прошло\n`);
process.exit(failed === 0 ? 0 : 1);
