// Кто что считает: роль → подключение.
//
// ⚠️ РОЛИ, А НЕ ФУНКЦИИ — это главное решение файла, и первая версия его провалила. Роли были
// выведены из экспортов TranslationService, а это ТРАНСПОРТ, а не смысл: один только
// runTabOrganizePrompt зовут СЕМНАДЦАТЬ разных мест — адресная строка, разбор форм, папки
// закладок, имена загрузок, итоги дня, правила из фразы, поиск по настройкам, умный поиск на
// странице, переименование вкладок, блокнот, изменения страницы, товары, виджеты. Назвать это
// «порядком во вкладках», как было сначала, значит спрятать пятнадцать функций браузера за
// названием шестнадцатой — и человек, отдавший «вкладки» облаку, незаметно отдал бы туда же разбор
// своих форм. Поэтому роль объявляет ВЫЗЫВАЮЩИЙ, а не та функция, через которую он идёт.
//
// ⚠️ ОБЛАКО ПРЕДЛАГАЕТСЯ НЕ ВЕЗДЕ, и решает это не приватность, а ПОТОЛОК ЗАДАЧИ — разбор см. у
// cloudFit ниже. Из десяти ролей открытый ответ только у трёх; остальным семи облако не даёт
// ничего, а стоит денег и задержки. Побочный, но важный итог этого решения: механизм «согласия на
// облако для приватной роли» оказался не нужен вовсе — история, вкладки и итоги дня просто не
// имеют облачного варианта, а запрет надёжнее подтверждения.
//
// ⚠️ ТАБЛИЦА ОГРАНИЧИВАЕТ АВТОМАТИКУ БРАУЗЕРА, А НЕ ЧЕЛОВЕКА. В AI-панели он выбирает модель под
// любую задачу и просит её о чём угодно — перевести кусок, пересказать, объяснить; роль chat
// свободна по построению. Закрытые семь ролей — это места, где браузер пошёл бы в сеть САМ, без
// нажатия. Смешивать эти два вопроса нельзя: первый про деньги и скорость, второй про свободу.
//
// ⚠️ ОТКАТ НА ЛОКАЛЬНУЮ НЕ БЫВАЕТ МОЛЧАЛИВЫМ. Если выбранное подключение отвалилось, человек
// получит ответ хуже привычного и решит, что испортился браузер. Поэтому resolveRoute отдаёт не
// только адресата, но и причину со словами для интерфейса.
//
// Значимых импортов нет — модуль под проверкой (scripts/ai-routing-check.mjs), она гоняется голым
// node (см. правило про shared/ в CLAUDE.md).

import type { Connection } from './aiProviders';

export const AI_ROLES = [
  'translate', 'page', 'chat', 'notebook', 'search', 'organize', 'forms', 'digest', 'rules', 'widgets',
] as const;
export type AiRole = (typeof AI_ROLES)[number];

/**
 * Что именно уходит в запросе этой роли.
 *
 * ⚠️ На маршрут БОЛЬШЕ НЕ ВЛИЯЕТ — его решает cloudFit. Осталось как материал для интерфейса:
 * строка выбора должна говорить, что именно покинет машину, и группировать роли по этому признаку.
 * Держать приватность вторым решающим правилом было бы удвоением: роли с `profile` и так не имеют
 * облачного варианта.
 */
export type Sensitivity =
  | 'typed'    // только то, что человек сам написал
  | 'page'     // текст открытой страницы, выделение, разметка формы
  | 'profile'; // картина работы человека: история, вкладки, закладки, загрузки

export interface RoleInfo {
  role: AiRole;
  label: string;
  /** Что уходит наружу, если роль отдать облаку. Текст показывается человеку при выборе. */
  leaves: string;
  sensitivity: Sensitivity;
  /**
   * Работает, пока человек печатает или ждёт на месте.
   *
   * ⚠️ Отдельное измерение, и без него таблица врёт. Адресная строка и разбор формы считаются
   * ПОКА ЧЕЛОВЕК НАБИРАЕТ: там круг до чужого сервера дороже любой прибавки к качеству — ответ
   * приходит после того, как он стал не нужен. То есть облако здесь не «приватнее или нет», а
   * просто ХУЖЕ, и сказать это надо прямо, а не оставлять человеку выяснять опытом.
   */
  interactive: boolean;
}

