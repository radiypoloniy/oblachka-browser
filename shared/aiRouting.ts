/**
 * Предлагается ли облако этой роли вообще.
 *
 * ⚠️ РАЗДЕЛИТЕЛЬ — ОТКРЫТЫЙ ОТВЕТ ПРОТИВ ЗАКРЫТОГО ВЫБОРА, а не «чат против кнопки» и не
 * приватность. Там, где модель ВЫБИРАЕТ из закрытого набора — разложить вкладки по кучкам, назвать
 * файл загрузки, положить закладку в папку, понять, что за поле в форме, — потолок задачи взят уже
 * сейчас: сильная модель разложит вкладки так же, просто за деньги и лишние 800 мс. Там, где ответ
 * СОЧИНЯЮТ — беседа, конспект, объяснение чужого текста, — потолок задаёт модель, и разрыв виден
 * глазом.
 *
 * ⚠️ Проверка этого правила лежит в самом проекте: генератор виджетов чинился именно тем, что
 * открытую задачу («напиши код плитки») превратили в закрытую («выбери тип из каталога и заполни
 * поля») — и локальной 4B сразу хватило (см. shared/genSpec.ts). Подключить туда облако значило бы
 * заново ОТКРЫТЬ задачу, которую закрыли намеренно. То же с каталогом правил.
 *
 * ⚠️ И следствие, ради которого это стоит держать машиной, а не соглашением: незаметная работа
 * браузера обязана быть бесплатной, мгновенной и работать без сети. Итоги дня, разбор форм и
 * переименование вкладок, ходящие в облако на каждой странице, — это счёт за то, чего человек не
 * просил, и поломка фичи у всех, кто ключ не подключал.
 */
export type CloudFit =
  | 'offered'   // ответ сочиняют — облако осмысленно
  | 'no-gain'   // ответ выбирают из закрытого набора: потолок задачи уже взят локально
  | 'too-slow'; // считается, пока человек набирает: круг до сервера дороже любой прибавки

export function cloudFit(role: AiRole): CloudFit {
  const info = ROLE_INFO[role];
  if (info.interactive) return 'too-slow';
  return OPEN_ANSWER.includes(role) ? 'offered' : 'no-gain';
}

/**
 * Роли с открытым ответом. ⚠️ Список ЗАКРЫТЫЙ и короткий намеренно: каждая новая строка здесь —
 * это ещё одно место, где браузер может начать тратить чужие деньги, и добавлять её надо с тем же
 * разбором, что заведён выше, а не потому, что «облако же лучше».
 */
const OPEN_ANSWER: readonly AiRole[] = ['page', 'chat', 'notebook'];

export function cloudAllowed(role: AiRole): boolean {
  return cloudFit(role) === 'offered';
}

/**
 * ⚠️ ЗАПАСНОЙ ВЫХОД ЕСТЬ, И ОН ОДИН — AI-панель. Закрывая облако семи ролям, мы отнимаем не
 * возможность, а АВТОМАТИЗМ: попросить облачную модель о чём угодно человек может всегда, просто
 * руками и по своему решению. Перевод — самый наглядный случай: страница у панели уже под рукой,
 * то есть «переведи это облачной моделью» делается в три нажатия и не требует, чтобы браузер
 * ходил в сеть за каждой страницей сам. Разница между «нельзя» и «не само» здесь и проходит.
 */
const SPECIFIC_NOTE: Partial<Record<AiRole, string>> = {
  translate: 'Страницу целиком переводит движок перевода — Bergamot или локальная Qwen, выбор в настройках. Перевести отдельный фрагмент любой подключённой моделью можно в поповере над выделением и в AI-панели.',
};

/** Почему облако не предлагается — словами, для строки под выбором. */
export function cloudFitNote(role: AiRole): string | null {
  const fit = cloudFit(role);
  if (fit === 'offered') return null;
  const specific = SPECIFIC_NOTE[role];
  if (specific !== undefined) return specific;
  return fit === 'too-slow'
    ? 'Считается, пока вы набираете, — ответ из облака придёт позже, чем нужен.'
    : 'Модель выбирает из готового набора: облако сделает то же самое, но за деньги.';
}

/** Роль → id подключения. Отсутствующая запись означает «локально». */
export type RoutingTable = Partial<Record<AiRole, string>>;

export const LOCAL_ID = 'local';

/** Пустая таблица: всё считается здесь. Это и есть состояние чистой установки. */
export const DEFAULT_ROUTING: RoutingTable = {};

export type RouteReason =
  | 'default'               // выбора не делали — локальная модель
  | 'chosen'                // работает выбранное подключение
  | 'fallback-unknown'      // подключение из таблицы больше не существует
  | 'fallback-unavailable'  // подключение есть, но сейчас непригодно (нет ключа, не отвечает)
  | 'fallback-not-offered'; // облаку эта роль не отдаётся в принципе (см. cloudFit)

export interface Route {
  connectionId: string;
  reason: RouteReason;
  /** Что сказать человеку. null — говорить нечего, всё идёт как он выбрал. */
  notice: string | null;
}

export interface RoutingContext {
  /** Заведённые подключения. Локальное среди них тоже. */
  connections: readonly Connection[];
  /** Подключения, готовые отвечать прямо сейчас (ключ на месте, endpoint жив). */
  ready: readonly string[];
  /**
   * Подключения, которые считаются НА ЭТОЙ МАШИНЕ.
   *
   * ⚠️ Список приходит снаружи, а не выводится здесь по `kind`, и это не лишний параметр:
   * «локально» решает не тип подключения, а адрес — Ollama на localhost такое же «здесь», как
   * встроенная Qwen. Считает это capsFor() из aiProviders.ts, но тянуть её сюда значимым импортом
   * нельзя (модуль под проверкой, см. шапку), поэтому ответ передаётся готовым.
   */
  localIds: readonly string[];
}

/**
 * Кому адресовать запрос этой роли.
 *
 * Порядок проверок обратный привычному — сначала причины ОТКАЗАТЬ выбранному, и только потом сам
 * выбор. Так короче и, главное, ни один откат не проходит без причины и слов.
 */
export function resolveRoute(role: AiRole, table: RoutingTable, ctx: RoutingContext): Route {
  const chosen = table[role];
  if (chosen === undefined || chosen === LOCAL_ID) {
    return { connectionId: LOCAL_ID, reason: 'default', notice: null };
  }

  const conn = ctx.connections.find((c) => c.id === chosen);
  if (!conn) {
    return {
      connectionId: LOCAL_ID,
      reason: 'fallback-unknown',
      notice: 'Выбранное подключение удалено — считает модель на этой машине.',
    };
  }

  // ⚠️ Проверка стоит РАНЬШЕ доступности подключения намеренно. Роль, которой облако не положено,
  // не должна зависеть от того, жив ли сейчас чужой сервер: «не отдаём» — это решение продукта, а
  // «не отвечает» — случайность, и путать их в объяснении человеку нельзя.
  if (!cloudAllowed(role)) {
    return {
      connectionId: LOCAL_ID,
      reason: 'fallback-not-offered',
      notice: `«${ROLE_INFO[role].label}» всегда считается на этой машине. ${cloudFitNote(role) ?? ''}`.trim(),
    };
  }

  if (!ctx.ready.includes(conn.id)) {
    return {
      connectionId: LOCAL_ID,
      reason: 'fallback-unavailable',
      notice: `«${conn.label}» сейчас недоступно — ответила модель на этой машине.`,
    };
  }

  return { connectionId: conn.id, reason: 'chosen', notice: null };
}

/**
 * Сводка для шапки раздела настроек: сколько ролей считается здесь, сколько в облаке.
 *
 * ⚠️ Считается по РАЗРЕШЁННОМУ маршруту, а не по записи в таблице. Иначе шапка обещала бы облако
 * там, где на деле работает откат, — то есть врала бы ровно в ту сторону, в которую врать нельзя.
 */
export function routingSummary(table: RoutingTable, ctx: RoutingContext): { local: number; cloud: number } {
  let local = 0;
  let cloud = 0;
  for (const role of AI_ROLES) {
    const route = resolveRoute(role, table, ctx);
    // Подключение к Ollama на localhost — это «здесь»: решает не тип, а адрес (см. localIds).
    const isLocal = route.connectionId === LOCAL_ID || ctx.localIds.includes(route.connectionId);
    if (isLocal) local++; else cloud++;
  }
  return { local, cloud };
}
