// Чистая логика калькулятора из AI-панели (см. CalcApp в src/components/aiApps.tsx).
//
// Здесь всё, что можно посчитать без React: сама арифметика, формат числа, правило процента и
// разбор ВСТАВЛЕННОГО числа. В компоненте остаётся только автомат состояний и отрисовка.
// Вынесено сюда не ради чистоты: и правило процента, и разбор вставки ломаются на реальных
// случаях («50 + 10 %», «1 234,56 ₽») и чинятся проверкой, а не глазами.
//
// ⚠️ Значимых импортов тут быть НЕ должно, только типовые — scripts/calc-check.mjs гоняет этот
// модуль голым node (та же причина, что в shared/sessionTree.ts и shared/nodeTree.ts).

export type CalcOp = '÷' | '×' | '−' | '+';

export const computeCalc = (a: number, b: number, op: CalcOp): number =>
  op === '+' ? a + b : op === '−' ? a - b : op === '×' ? a * b : a / b;

// toPrecision(12) вместо сырого результата — гасит хвосты двоичной арифметики (0.1+0.2),
// parseFloat срезает завершающие нули записи.
export const fmtCalc = (n: number): string =>
  (isFinite(n) ? parseFloat(n.toPrecision(12)).toString() : 'Ошибка');

// Число для строки выражения/дисплея — с русской запятой, как и основной дисплей.
export const calcDisp = (n: number): string => fmtCalc(n).replace('.', ',');

/**
 * Во что превращается набранный процент, когда приходит время считать.
 *
 * ⚠️ Процент считается ОТ ПЕРВОГО ОПЕРАНДА, когда идёт сложение или вычитание: «50 + 10 %» это
 * 55, а не 50,1. Когда-то здесь было безусловное деление на 100, из-за чего единственный ходовой
 * сценарий процента давал бессмыслицу — жалоба «проценты не работают» ровно про это.
 * При умножении/делении и без начатого действия процент остаётся долей (10 % → 0,1): «50 × 10 %»
 * это половина от пятидесяти. Так же ведут себя калькуляторы iOS и Windows.
 */
export function resolvePercent(value: number, acc: number | null, op: CalcOp | null): number {
  const share = value / 100;
  return acc !== null && (op === '+' || op === '−') ? acc * share : share;
}

// Пробелы всех сортов, которыми на сайтах разделяют разряды. Достаточно \s: в JS он включает и
// неразрывный U+00A0, и узкий неразрывный U+202F, и тонкий U+2009 — а «1 234,56» почти никогда
// не приходит с простым пробелом.
const SPACES = /\s/g;

/**
 * Число из вставленного текста или null, если числа там нет.
 *
 * ⚠️ Разделителей два вида, и десятичным считается ПОСЛЕДНИЙ: «1,234.56» — тысячи запятой,
 * «1.234,56» — тысячи точкой. Если такой разделитель в строке не один («1,234,567»), значит все
 * они разрядные и дробной части нет вовсе.
 *
 * ⚠️ Одиночная запятая — ДЕСЯТИЧНАЯ: «1,234» это 1,234, а не 1234. Случай «1,234» как английской
 * записи тысяч разобрать нельзя в принципе (обе трактовки корректны), и в русском интерфейсе
 * запятая-разделитель дробной части встречается несравнимо чаще.
 */
export function parsePastedNumber(raw: string): number | null {
  const trimmed = raw.trim().replace(SPACES, '');
  if (!trimmed) return null;
  // Минус бывает и типографским (U+2212) — его ставят на страницах вместо дефиса.
  const negative = /^[-−]/.test(trimmed);
  // Всё, что не цифра и не разделитель, выбрасываем: копируют вместе с валютой и процентом.
  const s = trimmed.replace(/[^\d.,]/g, '');
  if (!/\d/.test(s)) return null;

  const sepAt = Math.max(s.lastIndexOf('.'), s.lastIndexOf(','));
  let intPart: string;
  let fracPart: string;
  if (sepAt < 0) {
    intPart = s;
    fracPart = '';
  } else {
    const sep = s[sepAt];
    const sepCount = s.split(sep).length - 1;
    if (sepCount > 1) {
      // Разделитель повторяется — он разрядный: «1,234,567», «1.234.567».
      intPart = s.replace(/[.,]/g, '');
      fracPart = '';
    } else {
      intPart = s.slice(0, sepAt).replace(/[.,]/g, '');
      fracPart = s.slice(sepAt + 1).replace(/[.,]/g, '');
    }
  }

  const n = parseFloat(`${intPart || '0'}.${fracPart || '0'}`);
  if (!isFinite(n)) return null;
  return negative ? -n : n;
}
