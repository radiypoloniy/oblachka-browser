// не трогать — по ним уже мог лежать прогресс в localStorage. Обороты внутри колоды уникальны:
// сцена 4×2 берёт чужие переводы как варианты.

export type DeckId = 'en' | 'ja' | 'fr' | 'vi';
/** 0 новые, 1 учу, 2 знаю. */
export type CardBox = 0 | 1 | 2;

export interface CardPair {
  id: string;
  front: string;
  back: string;
}

export interface Deck {
  id: DeckId;
  /** Короткий ярлык на бумаге карточки. */
  label: string;
  /** Имя языка — в настройках стола и на плитке выбирают им, не кодом. */
  title: string;
  cards: CardPair[];
}

export const DECK_IDS: readonly DeckId[] = ['en', 'ja', 'fr', 'vi'];

/** Сколько пар в стартовом словаре. Не длина «на глаз» — её держит проверка. */
export const STARTER_DECK_SIZE = 80;

function deck(id: DeckId, label: string, title: string, pairs: [string, string][]): Deck {
  return {
    id, label, title,
    cards: pairs.map(([front, back]) => ({ id: `${id}-${front}`, front, back })),
  };
}

