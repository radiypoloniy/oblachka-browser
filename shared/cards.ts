export function isDeckId(value: string): value is DeckId {
  return (DECK_IDS as readonly string[]).includes(value);
}

export function nextDeckId(id: DeckId): DeckId {
  const i = DECK_IDS.indexOf(id);
  return DECK_IDS[(i + 1) % DECK_IDS.length]!;
}

/**
 * Какую игру рисует плитка. Память 4×4 в этом заходе не делается — высота не участвует.
 * Шире трёх клеток появляется сцена «слово слева, ответы справа»; иначе колода в руке.
 */
export function cardsMode(size: { w: number; h: number }): 'review' | 'choice' {
  return size.w >= 4 ? 'choice' : 'review';
}

/** Коробки по умолчанию — все новые. */
export function boxOf(boxes: Record<string, CardBox> | undefined, id: string): CardBox {
  const n = boxes?.[id];
  return n === 1 || n === 2 ? n : 0;
}

/** Ещё не выученные. Пустой круг = все в «знаю». */
export function reviewQueue(cards: CardPair[], boxes: Record<string, CardBox> | undefined): CardPair[] {
  return cards.filter((c) => boxOf(boxes, c.id) < 2);
}

/**
 * Ответ двигает коробку. «Знаю» — сразу выучено. «Не знаю» всегда в «учу»:
 * промах с полки выученных тоже возвращает слово в круг.
 */
export function applyAnswer(know: boolean): CardBox {
  return know ? 2 : 1;
}

export function shuffle<T>(items: readonly T[], rand: () => number = Math.random): T[] {
  const a = items.slice();
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1));
    const t = a[i]!;
    a[i] = a[j]!;
    a[j] = t;
  }
  return a;
}

/**
 * Три подписи для выбора: верный оборот и до двух чужих из той же колоды.
 * Короткой колоде меньше трёх не выдумываем — столько, сколько есть разных оборотов.
 */
export function choiceOptions(card: CardPair, deck: readonly CardPair[], rand: () => number = Math.random): string[] {
  const others = deck
    .filter((c) => c.id !== card.id && c.back !== card.back)
    .map((c) => c.back);
  const unique: string[] = [];
  for (const b of others) {
    if (!unique.includes(b)) unique.push(b);
  }
  const picks = shuffle(unique, rand).slice(0, 2);
  return shuffle([card.back, ...picks], rand);
}
