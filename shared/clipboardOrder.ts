// Порядок и вытеснение записей буфера обмена (см. electron/ClipboardBuffer.ts).
//
// Здесь ровно два правила, и оба про ЗАКРЕПЛЁННОЕ. Оба ломаются молча: список продолжает работать,
// просто закреплённая запись однажды оказывается не там, где человек её оставил, или исчезает
// совсем — то есть делает ровно то, от чего её закрепляли. Поэтому логика вынесена сюда, под
// scripts/clipboard-order-check.mjs, а владелец состояния остаётся в main.
//
// ⚠️ Значимых импортов тут быть НЕ должно, только типовые — проверка гоняет модуль голым node
// (та же причина, что в shared/sessionTree.ts и shared/nodeTree.ts).

/** Всё, что этим правилам нужно знать о записи. */
export interface Pinnable {
  pinned?: boolean;
}

/**
 * Порядок показа: закреплённое первым, остальное — как лежало (свежие сверху).
 *
 * ⚠️ Порядок задаётся ЗДЕСЬ, а не хранением. В самом массиве новая копия встаёт в начало, и
 * закреплённая запись иначе уезжала бы вниз от каждой следующей копии.
 */
export function orderCopies<T extends Pinnable>(entries: T[]): T[] {
  return [...entries.filter((e) => e.pinned), ...entries.filter((e) => !e.pinned)];
}

/**
 * Обрезает список до предела, ВЫТЕСНЯЯ ТОЛЬКО НЕЗАКРЕПЛЁННОЕ, с конца (самое старое).
 *
 * ⚠️ Простое `entries.length = max` тут неверно: закреплённая запись, дожившая до хвоста, исчезла
 * бы именно тем способом, от которого её закрепляли.
 * ⚠️ Закреплённых может оказаться больше предела (предел на них свой, и он другой) — тогда список
 * ЗАКОННО длиннее max. Обрезать в этом случае нечего, и попытка «дожать» вычистила бы как раз то,
 * что вычищать нельзя.
 */
export function trimCopies<T extends Pinnable>(entries: T[], max: number): T[] {
  if (entries.length <= max) return entries;
  const kept: T[] = [];
  let dropsLeft = entries.length - max;
  // Идём С КОНЦА: вытесняется самое старое, а старое лежит в хвосте.
  for (let i = entries.length - 1; i >= 0; i--) {
    const entry = entries[i]!;
    if (!entry.pinned && dropsLeft > 0) { dropsLeft--; continue; }
    kept.unshift(entry);
  }
  return kept;
}

/**
 * Самая свежая ИМЕННО СКОПИРОВАННАЯ запись — герой карточки поповера.
 *
 * ⚠️ Закреплённые пропускаются, и это не мелочь, а починка живой ошибки. `orderCopies` ставит
 * закреплённое ПЕРВЫМ, поэтому «просто первый элемент списка» — это всегда закреплённая запись,
 * как только хоть одна закреплена. Поповер в таком виде показывал закреплённое под подписью
 * «последнее» и заодно убирал его из раздела «Закреплённое»: функционально всё работало,
 * а на экране запись пропадала оттуда, где человек её оставил.
 *
 * ⚠️ «Последнее» здесь про НЕДАВНОСТЬ КОПИРОВАНИЯ, а не про положение в списке. Закреплённое
 * могло быть скопировано неделю назад и держится наверху по другой причине.
 */
export function latestCopy<T extends Pinnable>(entries: T[]): T | null {
  return entries.find((e) => !e.pinned) ?? null;
}
