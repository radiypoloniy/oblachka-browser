// Разметка страницы, написанная моделью: очистка по белому списку.
//
// ⚠️ Здесь МОДЕЛЬ ПИШЕТ HTML — и это осознанный разворот прежнего правила, а не забывчивость.
// Правило «модель не пишет HTML» выведено из двух случаев, и ни один не про статью: виджет
// «змейка» требовал ПРОГРАММЫ на JS (4B выдавала 250 пустых div), а @antv/infographic был
// борьбой с чужим DSL. Обратный опыт тоже есть и он прямой: та же 4B без всякой грамматики
// пишет цельную страницу с переменными в :root, сеткой и медиазапросами. Проза в разметке —
// её родной жанр.
//
// ⚠️ А вот попытка получить ту же статью СТРУКТУРОЙ под грамматикой провалилась трижды. Разбор
// живого прогона: модель хочет написать свой JSON, грамматика не даёт и обрезает поток по
// ближайшей разрешённой ячейке — на выходе «{"id": 1, "title": "…"}» в заголовке и обломки
// «],» вместо абзацев. Синтаксически валидный мусор, то есть худший из возможных исходов:
// он проходит все проверки.
//
// ⚠️ Отсюда разделение ролей, на котором всё держится: модель пишет ТОЛЬКО тело — теги и текст.
// Ни одного цвета, ни одного отступа, ни одного класса от неё не принимается. Весь вид — наш
// CSS поверх её разметки, поэтому «красиво» по-прежнему не зависит от того, как она сверстала.
//
// ⚠️ Чистая логика без импортов: гоняется голым node из scripts/doc-markup-check.mjs.

/** Теги, которые доживают до страницы. Всё, что не здесь, — разворачивается или выбрасывается. */
const ALLOWED = new Set([
  'h2', 'h3', 'p', 'ul', 'ol', 'li', 'blockquote',
  'table', 'tr', 'td', 'th', 'thead', 'tbody',
  'strong', 'em', 'b', 'i', 'br', 'hr', 'code',
]);

/**
 * Теги, которые выбрасываются ВМЕСТЕ С СОДЕРЖИМЫМ.
 *
 * ⚠️ Отдельный набор, потому что для них «развернуть, оставив текст» — неверно: тело скрипта
 * или стиля, вывалившееся в страницу текстом, это мусор на видном месте. Опасности они не
 * представляют (предпросмотр в sandbox="", а выгруженный файл наших скриптов не содержит),
 * но и показывать их незачем.
 */
const DROPPED = new Set([
  'script', 'style', 'iframe', 'object', 'embed', 'svg', 'head', 'meta', 'link', 'title',
  // ⚠️ h1 — ОСОЗНАННО здесь. Модель почти всегда повторяет название статьи первым заголовком,
  // а название страницы ставим мы из плана: два одинаковых заголовка подряд выглядят поломкой.
  'h1',
]);

/** Пустые теги: закрывать их не надо и в стек они не кладутся. */
const VOID = new Set(['br', 'hr']);

/**
 * Что закрывается САМО при открытии следующего тега.
 *
 * ⚠️ Правило настоящего HTML, а не наша выдумка: `<li>Раз<li>Два` — законная разметка, браузер
 * закрывает первый пункт сам. Модель пишет так регулярно (в обучающих данных этого полно), и
 * без этих правил вложенность росла бы вглубь: пункт внутри пункта внутри пункта.
 */
const CLOSED_BY: Record<string, string[]> = {
  li: ['li'],
  td: ['td', 'th'],
  th: ['td', 'th'],
  tr: ['td', 'th', 'tr'],
  p: ['p'],
  h2: ['p'],
  h3: ['p'],
  ul: ['p'],
  ol: ['p'],
  blockquote: ['p'],
  table: ['p'],
};

/**
 * Теги, внутри которых текст не живёт сам по себе.
 *
 * ⚠️ Нужны, чтобы не плодить пустые строки между ячейками таблицы: перевод строки между
 * `</td>` и `<td>` — это текстовый узел, и без этого списка он превратился бы в мусорный
 * пробел, ломающий раскладку строки.
 */
const NO_TEXT = new Set(['ul', 'ol', 'table', 'thead', 'tbody', 'tr']);

/**
 * ⚠️ Амперсанд экранируется ТОЛЬКО когда он не начинает уже готовую сущность. Модель пишет
 * `&lt;` и `&amp;` сама (в обучающих данных это норма), и слепая замена превращала бы их в
 * `&amp;lt;` — на странице человек читал бы «&lt;» вместо «<».
 */
function escapeText(s: string): string {
  return s
    .replace(/&(?!#?[a-zA-Z0-9]{1,8};)/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;');
}

/**
 * Достаёт разметку из ответа модели.
 *
 * ⚠️ Модель почти всегда добавляет что-то от себя: ограждение ```html, фразу «Вот страница:»,
 * иногда целый каркас <html><body>. Это не повод считать ответ битым — это повод отрезать
 * лишнее, что здесь и делается.
 */
function extractBody(raw: string): string {
  let s = raw.replace(/```[a-z]*\n?/gi, '');
  const body = /<body[^>]*>([\s\S]*?)<\/body>/i.exec(s);
  if (body) s = body[1]!;
  const article = /<article[^>]*>([\s\S]*?)<\/article>/i.exec(s);
  if (article) s = article[1]!;
  // Всё до первого тега — вводная фраза модели, не часть страницы.
  const first = s.search(/<(h2|h3|p|ul|ol|blockquote|table)[\s>]/i);
  return first > 0 ? s.slice(first) : s;
}

/**
 * Приводит ответ модели к разметке, которую можно показать.
 *
 * ⚠️ Строка не ФИЛЬТРУЕТСЯ, а СОБИРАЕТСЯ ЗАНОВО: мы читаем поток по токенам и переизлучаем
 * только то, что узнали. Фильтрация чёрным списком здесь была бы дырой по построению — каждый
 * незнакомый тег и каждый неучтённый атрибут проходили бы насквозь. Атрибуты не переносятся
 * НИКАКИЕ, включая class и style: вид принадлежит нашему CSS, и это единственное, что не даёт
 * документу разъезжаться от прогона к прогону.
 */
export function sanitizeDocHtml(raw: string): string {
  const src = extractBody(typeof raw === 'string' ? raw : '');
  const out: string[] = [];
  const stack: string[] = [];
  // Регулярка режет поток на теги и всё, что между ними. Комментарии <!-- --> сюда попадают
  // как «тег», у которого имя не разбирается, — и выбрасываются вместе с содержимым.
  const re = /<!--[\s\S]*?-->|<\/?([a-zA-Z][a-zA-Z0-9]*)\b[^>]*>/g;
  let last = 0;
  let skipUntil: string | null = null;
  let m: RegExpExecArray | null;

  const text = (chunk: string) => {
    if (skipUntil) return;
    const top = stack[stack.length - 1];
    if (top && NO_TEXT.has(top)) return;      // между ячейками текст не нужен
    const t = chunk.replace(/\s+/g, ' ');
    if (t.trim().length === 0) return;
    out.push(escapeText(t));
  };

  while ((m = re.exec(src)) !== null) {
    text(src.slice(last, m.index));
    last = re.lastIndex;
    const name = m[1]?.toLowerCase();
    if (!name) continue;                       // комментарий
    const closing = m[0].startsWith('</');

    if (skipUntil) {
      if (closing && name === skipUntil) skipUntil = null;
      continue;
    }
    if (DROPPED.has(name)) {
      if (!closing) skipUntil = name;
      continue;
    }
    // Неизвестный тег РАЗВОРАЧИВАЕТСЯ: сам он уходит, текст внутри остаётся. Терять абзац
    // из-за <div>, который модель добавила по привычке, — худший из возможных исходов.
    if (!ALLOWED.has(name)) continue;

    if (VOID.has(name)) { if (!closing) out.push(`<${name}>`); continue; }

    if (closing) {
      const at = stack.lastIndexOf(name);
      if (at < 0) continue;                    // закрывашка без открывашки — просто мусор
      // Закрываем всё, что модель забыла закрыть внутри.
      for (let i = stack.length - 1; i >= at; i--) out.push(`</${stack[i]}>`);
      stack.length = at;
    } else {
      // Сначала закрываем то, что этот тег закрывает собой (см. CLOSED_BY).
      const closes = CLOSED_BY[name];
      if (closes) {
        while (stack.length > 0 && closes.includes(stack[stack.length - 1]!)) {
          out.push(`</${stack.pop()}>`);
        }
      }
      out.push(`<${name}>`);
      stack.push(name);
    }
  }
  text(src.slice(last));
  // ⚠️ Хвост закрываем САМИ. Модель обрывается на середине чаще, чем хотелось бы (упёрлась в
  // потолок токенов, прервали кнопкой), и незакрытый <ul> утаскивает за собой всю страницу.
  for (let i = stack.length - 1; i >= 0; i--) out.push(`</${stack[i]}>`);
  return out.join('');
}

/**
 * Готовая страница: разметка от модели плюс то, что подставляем мы.
 *
 * ⚠️ Живёт в shared/, а не рядом с генерацией в electron/: тип нужен обеим сторонам, а renderer
 * в electron/ ходить нельзя — этот импорт утащил бы в бандл node-модули.
 */
export interface PageSpec {
  title: string;
  lede: string;
  /** Тело статьи: разметка, уже прошедшая sanitizeDocHtml. */
  html: string;
  /** Числа: короткий прогон под грамматикой, единственный из структурных, что себя оправдал. */
  stats: { label: string; value: string }[];
  /** Источники — наши, у модели не спрашиваем. */
  sources: { title: string; url: string }[];
}

/**
 * Оборачивает каждый раздел в <section>: заголовок и его абзацы становятся одним блоком.
 *
 * ⚠️ Без этого «Издание» превращалось в кашу, и это стоило живой жалобы. Модель отдаёт ПЛОСКУЮ
 * последовательность — h2, p, p, h2, p… Раскладка «заголовок слева, текст справа» делается
 * сеткой, а сетка расставляет плоские элементы по строкам сама: заголовок второго раздела
 * оказывался в одной строке с абзацем первого, липкие заголовки наезжали друг на друга.
 *
 * ⚠️ Группировка — НАША работа, ровно как нумерация разделов. Просить модель писать <section>
 * бессмысленно: она их и так не пишет, а если напишет — санитайзер их не пропустит, потому что
 * структура страницы не должна зависеть от того, вспомнила ли модель про обёртку.
 *
 * Всё, что идёт до первого заголовка, остаётся снаружи: это вводка, у неё своё место.
 */
export function groupSections(html: string): string {
  // ⚠️ Условие — «нет заголовков вовсе», а НЕ «получилась одна часть»: статья из единственного
  // раздела даёт ровно одну часть, и её тоже надо обернуть, иначе сетка стиля к ней не применится.
  if (!html.includes('<h2>')) return html;
  const parts = html.split(/(?=<h2>)/);
  const out: string[] = [];
  for (const part of parts) {
    if (!part) continue;
    if (part.startsWith('<h2>')) out.push(`<section>${part}</section>`);
    else out.push(part);
  }
  return out.join('');
}

/** Сколько в разметке текста: по нему решаем, состоялась ли страница вообще. */
export function markupTextLength(html: string): number {
  return html.replace(/<[^>]*>/g, ' ').replace(/&[a-z]+;/gi, 'x').replace(/\s+/g, ' ').trim().length;
}

