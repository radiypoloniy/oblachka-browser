// Раскладка списка загрузок по ярусам для поповера (см. src/downloadspopover.tsx).
//
// ⚠️ ЗАЧЕМ ЭТО ВООБЩЕ ЕСТЬ. Поповер показывал десять последних записей одним плоским потоком, в
// котором смешаны три разные вещи: что качается сейчас, что скачано только что и что скачано
// когда-то. Живая формулировка: «просто каша из завершённых загрузок». Крупный шрифт кашу не
// разбирает — он делает её крупной кашей, поэтому чинится тут модель списка, а не набор.
//
// ⚠️ Поповер — НЕ АРХИВ, за архивом есть отдельная страница «Все загрузки». Из этого следует
// всё остальное: развёрнуто ровно то, ради чего сюда заходят («дай то, что я только что
// скачал»), а всё старое сворачивается в одну строку с числом.
//
// ⚠️ Значимых импортов тут быть НЕ должно, только типовые — проверка гоняет модуль голым node
// (та же причина, что в shared/sessionTree.ts, nodeTree.ts и clipboardOrder.ts).

/** Всё, что раскладке нужно знать о записи. Форма совместима с DownloadEntry. */
export interface Groupable {
  id: string;
  url: string;
  state: string;
  startedAt: number;
  fileMissing?: boolean;
}

/** Пачка файлов, приехавших с одного сайта подряд: первый показывается, остальные сворачиваются. */
export interface DownloadPack<T> {
  /** Первая (самая свежая) запись пачки — она и стоит строкой. */
  head: T;
  /** Остальные записи пачки. Пусто — значит это одиночная загрузка, а не пачка. */
  rest: T[];
}

export interface DownloadTiers<T> {
  /** Идущая загрузка — герой карточки. Только ОДНА: две геройских — это снова список. */
  active: T | null;
  /** Скачанное за последние сутки, уже свёрнутое в пачки. */
  today: DownloadPack<T>[];
  /** Всё, что старше суток и не влезло в потолок «сегодня». Показывается числом. */
  older: T[];
  /** Прервано, отменено, пропало с диска. Свой ярус со своим действием. */
  failed: T[];
}

/**
 * Сколько строк «сегодня» показываем развёрнуто.
 *
 * ⚠️ Не десять. Поповер ограничен по высоте, и честнее показать три строки с ярлыком «ещё 12»,
 * чем десять с обрезанным низом: обрезанная строка выглядит сбоем, а ярлык — решением.
 */
export const TODAY_LIMIT = 3;

/** Сутки в миллисекундах — граница между «сегодня» и «раньше». */
const DAY_MS = 24 * 60 * 60 * 1000;

/**
 * Промежуток, внутри которого записи одного сайта считаются ОДНОЙ пачкой.
 *
 * ⚠️ Две минуты, а не «подряд в списке»: пачка — это когда человек нажал «скачать всё» или
 * страница отдала архив картинок, и десять одинаковых строк с одного домена и есть та самая
 * каша. Через полчаса тот же сайт — уже отдельная загрузка, а не продолжение пачки.
 */
const PACK_GAP_MS = 2 * 60 * 1000;

/** Хост без www. ⚠️ Разбор свой и терпимый: на негодном адресе просто нет группировки, не сбой. */
function hostOf(url: string): string {
  const m = /^[a-z]+:\/\/([^/?#]+)/i.exec(url);
  return m ? m[1]!.replace(/^www\./, '').toLowerCase() : '';
}

/** Запись «не получилась»: прервана, отменена или файла на диске уже нет. */
function isFailed(e: Groupable): boolean {
  return e.state === 'interrupted' || e.state === 'cancelled'
    || (e.state === 'completed' && e.fileMissing === true);
}

/**
 * Свернуть подряд идущие записи одного сайта в пачки.
 *
 * ⚠️ Идём ПО ПОРЯДКУ СПИСКА (свежие сверху) и склеиваем только СОСЕДЕЙ. Группировать по хосту
 * вообще, невзирая на соседство, нельзя: тогда вчерашний файл с того же сайта уехал бы под
 * сегодняшний и список перестал бы читаться по времени.
 */
export function packBySite<T extends Groupable>(entries: T[]): DownloadPack<T>[] {
  const packs: DownloadPack<T>[] = [];
  for (const entry of entries) {
    const last = packs[packs.length - 1];
    const host = hostOf(entry.url);
    const sameSite = last !== undefined && host !== '' && hostOf(last.head.url) === host;
    // Считаем от ГОЛОВЫ пачки, а не от предыдущего соседа: иначе цепочка из десяти файлов по
    // две минуты каждый склеилась бы в одну пачку длиной в двадцать минут.
    const closeInTime = last !== undefined && Math.abs(last.head.startedAt - entry.startedAt) <= PACK_GAP_MS;
    if (sameSite && closeInTime) last.rest.push(entry);
    else packs.push({ head: entry, rest: [] });
  }
  return packs;
}

/**
 * Разложить список по ярусам.
 *
 * `now` приходит аргументом, а не берётся из Date.now(): иначе проверку нельзя было бы написать
 * без подмены времени, а граница «сутки» — ровно то место, где ошибаются.
 */
export function groupDownloads<T extends Groupable>(entries: T[], now: number): DownloadTiers<T> {
  // ⚠️ Идущая ищется ПО ВСЕМУ списку, а не среди «сегодняшних»: загрузка на два гигабайта живёт
  // дольше суток, и провалиться из героя в «раньше» она не должна.
  const active = entries.find((e) => e.state === 'progressing') ?? null;
  const failed: T[] = [];
  const done: T[] = [];
  for (const e of entries) {
    if (e.id === active?.id) continue;
    if (isFailed(e)) failed.push(e);
    else done.push(e);
  }
  const fresh = done.filter((e) => now - e.startedAt <= DAY_MS);
  const stale = done.filter((e) => now - e.startedAt > DAY_MS);
  const packs = packBySite(fresh);
  // Потолок считается в ПАЧКАХ, а не в записях: пачка занимает одну строку, и мерить её
  // содержимым значило бы прятать одиночные загрузки из-за чужого архива в двадцать файлов.
  const today = packs.slice(0, TODAY_LIMIT);
  const overflow = packs.slice(TODAY_LIMIT).flatMap((p) => [p.head, ...p.rest]);
  return { active, today, older: [...overflow, ...stale], failed };
}
