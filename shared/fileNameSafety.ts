// Приведение придуманного моделью имени к безопасному имени файла.
//
// ⚠️ Живёт ОТДЕЛЬНО и БЕЗ единого импорта — намеренно, тем же приёмом, что electron/bookmarksSchema.ts.
// Это единственный код в цепочке переименования, который решает, что именно ляжет на диск, а такой
// код обязан проверяться прогоном, а не чтением: ошибка здесь — испорченный или затёртый файл
// человека. Без зависимостей его гоняет обычный node (npm run filename-check).

// Потолок ИМЕНИ (без расширения). Не про красоту: длинный путь на Windows упирается в MAX_PATH,
// а имя, которое не помещается в строку списка, не помогает файл узнать.
const MAX_NAME_CHARS = 70;
// Ниже этого имя перестаёт что-либо называть — отказываемся, а не показываем огрызок
// (тот же вывод, что в TabRenamer.cleanTitle).
const MIN_NAME_CHARS = 4;

// ⚠️ Запрещённые в имени файла символы Windows. Модель охотно ставит двоеточие («Договор: аренда»)
// и слеш в датах — с ними fs.rename просто падает, а человек увидел бы невнятную ошибку.
// Слеши тут же закрывают и путь наружу («../../»): каталогов в имени не остаётся вовсе.
const FORBIDDEN = /[\\/:*?"<>|]/g;
// ⚠️ Зарезервированные имена устройств DOS: файл с таким именем Windows не создаст ни в каком
// регистре и ни с каким расширением. Модели ничего не стоит выдать «AUX» или «CON».
const RESERVED = /^(con|prn|aux|nul|com[1-9]|lpt[1-9])$/i;

// Управляющие символы проверяем КОДОМ, а не регуляркой: писать такой диапазон литералом в
// исходнике значит класть в файл сами управляющие байты.
// ⚠️ Меняем на ПРОБЕЛ, а не выбрасываем: таб между словами разделяет их, и выброшенный склеил бы
// соседей в «Счёт№12» (поймано прогоном). Лишние пробелы схлопнет общая чистка ниже.
function stripControlChars(s: string): string {
  return Array.from(s)
    .map((ch) => {
      const code = ch.codePointAt(0) ?? 0;
      return code < 32 || code === 127 ? ' ' : ch;
    })
    .join('');
}

/**
 * Чистит ответ модели до имени файла БЕЗ расширения. null — «такое имя не годится»:
 * отказ честнее, чем подставленный огрызок.
 *
 * @param ext расширение с точкой («.pdf») — снимается с конца, если модель его дописала.
 */
export function sanitizeFileNameBase(raw: string, ext: string): string | null {
  // Только первая строка: пояснение со второй — частая вольность маленькой модели.
  let s = raw.trim().split(/\r?\n/)[0]?.trim() ?? '';
  s = s.replace(/^(имя файла|имя|название|filename|name)\s*[:—-]\s*/i, '');
  s = s.replace(/^["'«»„“]+|["'«»„“]+$/g, '').trim();
  // Расширение, дописанное вопреки запрету в промпте, снимаем: своё мы добавим сами.
  if (ext) s = s.replace(new RegExp(`\\${ext}$`, 'i'), '').trim();
  s = stripControlChars(s).replace(FORBIDDEN, ' ').replace(/\s+/g, ' ').trim();
  // ⚠️ Точки и пробелы в конце Windows молча срезает при создании файла — имя на диске тогда
  // разошлось бы с тем, что мы показали человеку и записали в список загрузок.
  // Спереди — по своей причине: от «../../» после вычистки слешей остаются точки, и имя вида
  // «.. .. Отчёт» ни на что не годится (поймано прогоном). Плюс имя с точки — скрытый файл.
  s = s.replace(/^[.\s]+/, '').replace(/[.\s]+$/, '').trim();
  if (!s) return null;
  if (RESERVED.test(s)) return null;
  // Длинное имя не режем, а отказываемся: обрезка по последнему пробелу даёт формально имя,
  // фактически обрывок фразы (урок TabRenamer).
  if (s.length > MAX_NAME_CHARS || s.length < MIN_NAME_CHARS) return null;
  return s;
}
