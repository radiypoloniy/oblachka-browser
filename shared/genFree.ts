// Виджет, который модель пишет РАЗМЕТКОЙ — ярус 2 генератора.
//
// ⚠️ ЭТО ВОЗВРАТ ОТБРОШЕННОГО ПУТИ, и он законен ровно по одной причине. В шапке shared/genSpec.ts
// записано, почему код от модели выбросили: локальная 4B на «змейку» выдавала 250 пустых <div>.
// Но там же сказано главное — провал был не только в силе модели, а в ПОСТАНОВКЕ: её просили
// изобрести интерфейс и написать код, самое трудное, что можно поручить. Сильная облачная модель
// первую половину умеет. Поэтому ярусов два, и они не спорят:
//
//   • ярус 1 — закрытый каталог под грамматикой (shared/genSpec.ts). Работает всегда, на любой
//     модели, без сети. Остаётся дефолтом.
//   • ярус 2 — свободная разметка. Только когда роль «Генератор виджетов» отдана облаку.
//
// ⚠️ СВОБОДА ДАЁТСЯ НА РИСОВАНИЕ, А НЕ НА ДАННЫЕ. Разметка исполняется в песочнице
// (shared/genWidget.ts: iframe без allow-same-origin, CSP `default-src 'none'`, сети нет,
// window.oblako недостижим), а факты о браузере отдаёт ХОСТ через postMessage. Находка 22.08
// остаётся в силе: модель про браузер не знает ничего и историю посещений выдумывает.
//
// ⚠️ Стиль задаётся ТОКЕНАМИ, а не уговорами в промпте (см. GEN_TOKEN_VARS). Модель пишет обычный
// CSS с var(--accent) и var(--card) — и виджет попадает в палитру человека сам, включая смену
// темы. Это надёжнее любой инструкции и заодно закрывает цветовой закон машинно.
//
// Значимых импортов нет — проверка scripts/gen-free-check.mjs гоняет модуль голым node.

/** Потолок ответа. Виджет крупнее этого — не виджет, а страница. */
export const GEN_FREE_MAX_CHARS = 12_000;

/**
 * Снять обёртку markdown-фенса.
 *
 * ⚠️ Обязательно, и это не косметика. Сильные модели почти всегда оборачивают код в ```html —
 * инструкция «отвечай только разметкой» этого не отменяет. Без снятия обёртки в песочницу уезжают
 * три обратных апострофа и слово html как ТЕКСТ: виджет собирается «успешно» и показывает мусор.
 *
 * ⚠️ Снимаем ТОЛЬКО когда фенс обрамляет ответ целиком. Фенс в середине — это часть содержимого
 * (модель показывает пример кода внутри виджета), и трогать его нельзя.
 */
export function stripCodeFence(raw: string): string {
  const s = raw.trim();
  const m = /^```[a-z]*\s*\n([\s\S]*?)\n?```$/i.exec(s);
  return m ? m[1].trim() : s;
}

/**
 * Годится ли ответ к показу.
 *
 * ⚠️ Порог существует потому, что пустая плитка неотличима от рабочей, пока на неё не посмотришь.
 * Проверяем не «красиво ли», а есть ли вообще из чего рисовать: хоть один тег и хоть сколько-то
 * содержимого между тегами. Слово «нет» в ответ на просьбу — тоже частый исход, и он не разметка.
 *
 * ⚠️ Это НЕ замена доклада песочницы о том, что она ничего не нарисовала (см. GenWidget.tsx).
 * Там ловится другое: разметка есть, но скрипт упал. Одно без другого дырявое.
 */
export function freeWidgetUsable(html: string): boolean {
  const s = html.trim();
  if (s.length < 40 || s.length > GEN_FREE_MAX_CHARS) return false;
  if (!/<[a-z][\w-]*[\s>]/i.test(s)) return false;
  // Текст между тегами или содержимое стиля/скрипта — иначе это голый каркас без ничего.
  const inner = s.replace(/<[^>]*>/g, '').trim();
  return inner.length > 0 || /<(style|script|svg|canvas|img)\b/i.test(s);
}

/**
 * Разрешено ли просить у модели свободную разметку.
 *
 * ⚠️ Признак — ОБЛАКО, а не «сильная модель»: узнать силу модели по имени нельзя, а адрес мы
 * знаем точно. Локальная 4B на этот путь не пускается вовсе — именно её провал его и закрыл.
 * Ollama с большой моделью на localhost при этом остаётся «здесь» и тоже не пускается: это
 * осознанная потеря, потому что различить её от 4B нам нечем.
 */
export function freeTierAllowed(routeIsLocal: boolean): boolean {
  return !routeIsLocal;
}

/**
 * Оборвался ли ответ по лимиту токенов.
 *
 * ⚠️ Это ОТДЕЛЬНЫЙ исход от «вернула не разметку», и путать их нельзя: там модель не поняла
 * просьбу, здесь она справилась, но не успела дописать. Человеку нужны разные слова — во втором
 * случае помогает не «опишите проще», а просто повтор.
 *
 * ⚠️ Признак — НЕЗАКРЫТЫЙ <script>, а не «длина у потолка». Обрыв внутри разметки браузер
 * переживёт (незакрытый div он закроет сам), а вот тело скрипта без </script> санитайзер не
 * распознаёт скриптом и оставляет ТЕКСТОМ: на плитке появляется исходный код вместо виджета.
 */
export function freeAnswerTruncated(html: string): boolean {
  const opens = (html.match(/<script\b[^>]*>/gi) ?? []).length;
  const closes = (html.match(/<\/script\s*>/gi) ?? []).length;
  if (opens > closes) return true;
  // Обрыв ровно на открывающем теге: `<scr`, `<div class="` — закрывающей скобки уже нет.
  return /<[a-z][^>]*$/i.test(html.trim());
}

/**
 * Сказал ли сам провайдер, что ответ уперся в лимит токенов.
 *
 * ⚠️ Это ГЛАВНЫЙ признак обрыва, а freeAnswerTruncated — второй эшелон: разметка, оборванная на
 * закрытом теге, выглядит целой и по ней не отличить.
 *
 * ⚠️ Одна проверка на три словаря: 'max_tokens' у Anthropic, 'length' у OpenAI-совместимых,
 * 'MAX_TOKENS' у Gemini (см. electron/ai/providers/*). Держать три отдельных сравнения значило бы
 * ловить забытый четвёртый провайдер молчанием — как раз тем видом молчания, что даёт пустую
 * плитку. Естественный конец ('stop', 'end_turn', 'eogToken') ни одного из корней не содержит.
 */
export function freeStopWasLimit(stopReason: string): boolean {
  return /max|length/i.test(stopReason);
}
