// ── Пресеты генератора промптов для картинок ─────────────────────────────────
//
// Зачем модуль вообще: если просто попросить Qwen «напиши промт для картинки», выходит
// посредственно — модель уходит в пересказ материала прозой, теряет предметность и пишет
// по-русски, хотя генераторы изображений заметно лучше понимают английский. Качество здесь
// делает не модель, а инструкция: жёсткий порядок элементов, запрет на прозу и оценочные
// слова, обязательная конкретика по свету, оптике и материалу.
//
// Структура: общий СКЕЛЕТ задаёт правила вывода и порядок описания (одинаковые для всех),
// а пресет добавляет специфику носителя — оптику для фото, кисть для иллюстрации и т.п.
// Пользовательские пресеты дописывают только эту вторую часть, поэтому испортить формат
// вывода своим текстом нельзя.

export interface ImagePreset {
  id: string
  label: string
  emoji: string
  // Специфика носителя. Дописывается к скелету, формат вывода не переопределяет.
  guidance: string
}

