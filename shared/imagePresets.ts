// Собирает финальный промпт-задание для модели.
// preset — встроенный или пользовательский; extra — свободные пожелания человека
// («вертикально», «добавь снег»); material — то, что пришло на вход узла.
export function buildImagePromptRequest(
  guidance: string,
  extra: string,
  material: string,
): string {
  const parts = [SKELETON, '', guidance.trim()]
  const wish = extra.trim()
  if (wish) {
    // Пожелания человека идут ПОСЛЕ правил стиля, но ДО материала: так они уточняют стиль,
    // но не спорят с форматом вывода, который задан скелетом выше.
    parts.push('', `ДОПОЛНИТЕЛЬНЫЕ ПОЖЕЛАНИЯ (учти обязательно): ${wish}`)
  }
  parts.push('', 'МАТЕРИАЛ, по которому делаем картинку:', material.trim())
  parts.push('', 'Теперь выведи промпт — и больше ничего.')
  return parts.join('\n')
}
