// Единый источник правды по форме данных, которыми обмениваются renderer (хром-UI) и main
// (движок вкладок). Импортируется обеими сторонами как '../shared/ipc' — путь не менялся, эта
// бочка держит его стабильным, поэтому раскол на модули не задел ни одного из ~900 мест вызова.
//
// Почему нарезано ИМЕННО так. Файл дорос до 2575 строк, и резать его по доменам («вкладки»,
// «пароли», «AI») не вышло: область типов упорядочена тематически, а список каналов — нет.
// PASSWORDS_* встречаются в контракте четырьмя разными местами, VPN_* — тремя, и доменная
// нарезка означала бы шесть десятков перемежающихся кусков плюс произвольные решения вроде
// «FIND_SMART — это вкладки или AI?». Поэтому границы взяты те, что в файле УЖЕ были: каждый
// модуль — непрерывная вырезка, ничего не переставлено. Потерянную при таком переносе строку
// ловит арифметика (каждая строка исходника попала ровно в один модуль), а потерянный канал —
// golden-инвентарь в scripts/fixtures/ipc-channels.json.
//
//   core.ts      узлы сайдбара, состояние вкладки, поиск по странице, цели быстрого поиска
//   channels.ts  const IPC — сам список каналов, 360 штук
//   history.ts   история, дайджест, закладки, импорт из браузеров, смысловой поиск
//   security.ts  VPN, пароли
//   omnibox.ts   подсказки омнибокса, загрузки, буфер, отслеживание товаров, адблок
//   ai.ts        перевод, хаб, разрешения, железо, модели, бэнги, обновление, скиллы
//   app.ts       автозаполнение, виджеты, тема, роль окна, перетаскивание
//   api.ts       OblakoApi — поверхность window.oblako целиком
//
// ⚠️ Добавляешь канал — правь ОБЕ стороны (обработчик в electron/ и вызов в preload). Это не
// пожелание: `ipcRenderer.invoke` без парного `ipcMain.handle` собирается зелёным и падает уже
// у человека. Сторож npm test -- contract проверяет это статически.
