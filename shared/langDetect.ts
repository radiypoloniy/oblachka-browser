// Выбор языка текста по кандидатам franc — чистая логика, без Electron и без самой библиотеки.
//
// ⚠️ Вынесено сюда, потому что чинилось уже трижды и каждый раз по живой жалобе: франк путает
// языки, и поверх него стоят точечные эвристики. Держать их непокрытыми — значит однажды починить
// один случай, молча сломав другой. Прогон: scripts/lang-detect-check.mjs (он берёт НАСТОЯЩИЙ
// franc и кормит сюда его настоящие ответы).
//
// ⚠️ Значимых импортов тут быть не должно, только типовые — см. shared/sessionTree.ts.

// franc-min отдаёт ISO 639-3 — переводим в короткие коды. Список ключей заодно передаётся франку
// как `only` — не даём ему распознавать языки, для которых у нас всё равно нет промпт-имени.
// bel (белорусский) добавлен наравне с bul/ukr — тоже кириллица, тоже близок к русскому
// графически, без явного маппинга ушёл бы в FALLBACK_LANG молча.
export const FRANC_TO_CODE: Record<string, string> = {
  rus: 'ru', eng: 'en', fra: 'fr', deu: 'de', spa: 'es', ita: 'it', por: 'pt',
  nld: 'nl', pol: 'pl', ukr: 'uk', ces: 'cs', swe: 'sv', ell: 'el', ron: 'ro',
  hun: 'hu', bul: 'bg', hrv: 'hr', bel: 'be', cmn: 'zh', jpn: 'ja', kor: 'ko', tur: 'tr', arb: 'ar',
};

// Если не совпал ни с одним targetLang — считаем текст «не на целевом», переводим НА targetLang.
// Для этого случая (и как src, когда сам детектор не смог определить язык) нужен нейтральный
// дефолт-язык — английский, самый частый вариант «непонятного» текста.
export const FALLBACK_LANG = 'en';

// ⚠️ Порог НЕ «больше половины», и это выяснилось замером на той самой жалобе. В фразе
// «Adobe запустила единый плагин для ChatGPT… Photoshop, Firefly, Premiere, Acrobat, Lightroom,
// Illustrator, InDesign и Adobe Stock» латинских букв 93, а кириллических 87 — то есть по
// правилу «преимущественно кириллический» она русской НЕ считалась, хотя написана по-русски.
//
// Признак несимметричен, и в этом всё дело: латинские слова внутри русского текста — обычное
// дело (бренды, модели, термины), а кириллические слова внутри английского практически не
// встречаются, кроме коротких цитат. Поэтому достаточно ЗАМЕТНОЙ доли кириллицы, а не
// перевеса: четверть букв — это уже связный русский текст, а не вкрапление. Английская фраза с
// одним русским словом в кавычках (~0.2) под правило не попадает.
export const CYRILLIC_SHARE_MIN = 0.25;

export function hasSubstantialCyrillic(text: string): boolean {
  const letters = text.match(/[a-zA-Zа-яёА-ЯЁ]/g);
  if (!letters || letters.length === 0) return false;
  const cyrillic = text.match(/[а-яёА-ЯЁ]/g)?.length ?? 0;
  return cyrillic / letters.length >= CYRILLIC_SHARE_MIN;
}

// Английские сокращения (that's, let's, don't, we're...) практически не встречаются в других
// языках из FRANC_TO_CODE в этой форме — апостроф ПОСЛЕ слова, не перед, как во французских
// l'/c'/qu'. Эвристика ограничена короткими строками: за их пределами ложной замечена не была,
// но и разрастаться сверх подтверждённой проблемы незачем.
const ENGLISH_CONTRACTION_RE = /\b\w+'(s|t|re|ll|ve|d|m)\b/i;
const SHORT_TEXT_THRESHOLD = 80;

// Живой баг: страница на французском, franc отдал 'en' топ-кандидатом (сбит с толку англицизмами/
// брендами, которых во французских текстах хватает). Направление 'auto' резолвилось в «переводить
// С английского», и Qwen честно переводил только реально английские вкрапления, оставляя весь
// французский текст как есть — не «отказ переводить», а буквальное следование ошибочной инструкции.
// Не диакритика (à/é/ç бывают и в англ. заимствованиях café/résumé/naïve — ложные срабатывания),
// а именно служебные слова: в связном английском они иначе как во французских цитатах не водятся.
const FRENCH_FUNCTION_WORD_RE = /\b(le|la|les|des|une|est|dans|avec|pour|qui|que|vous|nous|être|cette|ces|mais|sont|comme|leur|leurs|entre|sans)\b/gi;
const FRENCH_FUNCTION_WORD_MIN_HITS = 2;

/** Пара [ISO 639-3, score] — ровно то, что отдаёт francAll. */
export type FrancCandidate = readonly [string, number];

export interface LangPick {
  code: string;
  iso3: string;
  /** Какая эвристика перебила ответ franc (для лога). null — взяли ответ как есть. */
  overrode: 'cyrillic' | 'english-contraction' | 'french-function-word' | null;
}

/**
 * Каким языком считать текст.
 *
 * franc путает языки — подтверждено живыми прогонами, и НЕ только на коротких строках: «да блин,
 * опять сроки горят...» (52 симв.) → 'bg', «спасибо огромное...» (47 симв.) → 'uk', "honestly
 * that's a game changer, let's ship it" → 'fr', и целая русская новостная статья (200+ симв.) →
 * 'bg'. Длина не спасает. Общий порог по score тоже не работает — проверено численно: score
 * правильного языка у одних пар пересекается со score ложного срабатывания у других. Поэтому
 * эвристики точечные, каждая на СВОЁМ независимом сигнале, а не на score franc.
 *
 * ⚠️ Правило про кириллицу одно, а не два: ЗАМЕТНАЯ ДОЛЯ КИРИЛЛИЦЫ — ЗНАЧИТ РУССКИЙ. Раньше оно
 * ловило только близкую кириллицу (bg/uk/be), и мимо проходил случай хуже: франк отдавал
 * ЛАТИНОПИСЬМЕННЫЙ язык на русском тексте с латинскими именами собственными, и текст уезжал
 * «переводиться» на русский с русского. Письменность — сигнал твёрже догадки франка: кириллический
 * текст не может быть английским или французским.
 * Выбор «русский, а не украинский/болгарский» осознанный: для этого пользователя русский на
 * порядок вероятнее, а различать близкие славянские франк всё равно не умеет.
 */
export function pickLanguage(candidates: readonly FrancCandidate[], text: string): LangPick {
  const iso3 = candidates[0]?.[0] ?? 'und';
  const code = FRANC_TO_CODE[iso3] ?? FALLBACK_LANG;
  const has = (c: string) => candidates.some(([x]) => x === c);

  if (code !== 'ru' && hasSubstantialCyrillic(text)) {
    return { code: 'ru', iso3: 'rus', overrode: 'cyrillic' };
  }
  if (text.length < SHORT_TEXT_THRESHOLD && code !== 'en' && ENGLISH_CONTRACTION_RE.test(text) && has('eng')) {
    return { code: 'en', iso3: 'eng', overrode: 'english-contraction' };
  }
  // Гейт has('fra') намеренный: французский должен быть хотя бы СРЕДИ кандидатов franc (не
  // обязательно первым) — не подставляем язык, который franc вообще не рассматривал.
  if (code === 'en' && (text.match(FRENCH_FUNCTION_WORD_RE)?.length ?? 0) >= FRENCH_FUNCTION_WORD_MIN_HITS && has('fra')) {
    return { code: 'fr', iso3: 'fra', overrode: 'french-function-word' };
  }
  return { code, iso3, overrode: null };
}
