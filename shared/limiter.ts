// Не больше N задач разом. Крошечный модуль с одной неочевидной строкой.
//
// ⚠️ Зачем в shared/ и под проверкой. Наивный семафор — «свободно? занимай; иначе жди» — содержит
// гонку, которую невозможно увидеть чтением и почти невозможно поймать глазами в работающем
// приложении. Она выглядит так: отпускающий уменьшает счётчик и будит ожидающего, но разбуженный
// продолжится ТОЛЬКО в следующей микрозадаче. В зазоре между этими двумя событиями новый вызов
// видит свободный слот и занимает его, а следом просыпается ожидающий и занимает его же. Предел
// превышен, и никто об этом не узнал.
//
// ⚠️ Для локальной модели это не «чуть больше нагрузки», а невозможное состояние: у node-llama-cpp
// ОДИН контекст на процесс, и второй одновременный запрос не медленнее, а нелегален. Симптом был бы
// из худших — редкий, плавающий, зависящий от того, в какой момент человек нажал вторую кнопку.
//
// Лекарство в одной строке: отпускающий НЕ уменьшает счётчик, если есть ожидающий, а ПЕРЕДАЁТ слот
// ему. Владение переходит из рук в руки, не побывав ничьим.
//
// Значимых импортов нет — модуль под проверкой (scripts/limiter-check.mjs), она гоняется голым node
// (см. правило про shared/ в CLAUDE.md).

export interface Limiter {
  run<T>(fn: () => Promise<T>): Promise<T>;
  /** Сколько задач выполняется прямо сейчас. Нужно проверке и диагностике. */
  active(): number;
  /** Сколько стоит в очереди. */
  queued(): number;
}

export function createLimiter(max: number): Limiter {
  const limit = Math.max(1, Math.floor(max));
  let running = 0;
  const waiting: (() => void)[] = [];

  function acquire(): Promise<void> {
    if (running < limit) {
      running++;
      return Promise.resolve();
    }
    // ⚠️ Слот НЕ занимается здесь после пробуждения — он уже передан нам в release(). Инкремент
    // тут вернул бы ту самую гонку, ради которой всё написано.
    return new Promise<void>((resolve) => waiting.push(resolve));
  }

  function release(): void {
    const next = waiting.shift();
    // Слот переходит следующему, счётчик не трогаем: между уменьшением и пробуждением успел бы
    // влезть новый вызов.
    if (next) next();
    else running--;
  }

  return {
    async run<T>(fn: () => Promise<T>): Promise<T> {
      await acquire();
      try {
        return await fn();
      } finally {
        // ⚠️ Именно finally: отказ задачи обязан освободить слот так же, как успех. Иначе одна
        // ошибка сети навсегда съедает единицу пропускной способности подключения.
        release();
      }
    },
    active: () => running,
    queued: () => waiting.length,
  };
}
