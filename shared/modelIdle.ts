// Политика выгрузки локальной модели из памяти — чистая арифметика, без Electron.
//
// ⚠️ Задача, которой у нас не было вовсе: `unloadModel()` написан и работает, но вызывающих по
// простою у него нет — модель уходит из памяти только при смене модели или закрытии браузера.
// Цена по каталогу: 2B — 1,28 ГБ, 4B — 2,74 ГБ, 9B — 5,68 ГБ. Перевёл человек утром одну
// страницу — и гигабайты висят до вечера.
//
// ⚠️ Значимых импортов тут быть не должно, только типовые — см. shared/sessionTree.ts.
// Правила проверяются scripts/model-idle-check.mjs.

/**
 * Сколько держать модель после последней просьбы ЧЕЛОВЕКА.
 *
 * ⚠️ Порог осторожный, и это осознанно. Цена возврата — повторная загрузка модели: замерено ~30 с
 * на 9B (см. гейт в BookmarkFolderPick.ts). Пять минут означали бы, что человек, читающий длинную
 * статью между двумя переводами, платит эти тридцать секунд регулярно. Сорок минут переживают
 * чтение и не переживают уход от компьютера — а уход и есть главный случай.
 *
 * ⚠️ Порог ОДИН на все модели, хотя 2B грузится за пару секунд, а 9B за тридцать. Формула от
 * размера была бы честнее по смыслу, но её коэффициенты сейчас неоткуда взять: время загрузки
 * каждой ступени не замерено. Делать вид, что замер есть, хуже, чем одна прямая константа.
 */
export const MODEL_IDLE_TIMEOUT = 40 * 60 * 1000;

/** Проверка раз в минуту — тот же ритм, что у политики усыпления вкладок. */
export const MODEL_CHECK_INTERVAL = 60_000;

/**
 * Второй повод выгрузить: ЖЕЛЕЗУ ТЕСНО НЕ ИЗ-ЗА НАС.
 *
 * ⚠️ Случай из жизни: человек не думает про браузер, когда запускает игру или монтаж видео. Он
 * запускает их поверх открытого браузера, и модель в видеопамяти становится тем, что он никак не
 * связывает с тормозами. Освободить её первыми — наша работа, а не его.
 *
 * ⚠️ Не отнимаем модель у того, кто только что её просил: иначе перевод выделения в разгар работы
 * над видео стоил бы человеку тридцати секунд ожидания сразу после того, как он получил ответ.
 */
export const PRESSURE_MIN_IDLE = 5 * 60 * 1000;

/**
 * Сколько проверок подряд должно быть тесно.
 *
 * ⚠️ Один замер ничего не значит: выделение памяти скачет от запуска любой программы, от
 * переключения на другой рабочий стол, от самого Chromium. Игра и рендер держат память минутами —
 * три минуты подряд отличают их от всплеска, а цена ошибки здесь несимметрична: лишняя выгрузка
 * стоит человеку тридцати секунд на ровном месте.
 */
export const TIGHT_STREAK = 3;

/** Доля свободной видеопамяти, ниже которой карта считается забитой. */
export const VRAM_FREE_MIN_SHARE = 0.15;

/**
 * Сколько видеопамяти должны были забрать ПОСЛЕ нас, чтобы это считалось чужим приходом.
 *
 * ⚠️ Одного «свободно мало» недостаточно, и это главная ловушка этого файла: 9B на карте с 8 ГБ
 * сама по себе оставляет меньше 15 % свободными — то есть правило по одной доле срабатывало бы
 * СРАЗУ после загрузки, ещё до всякой игры, и модель выгружалась бы через пять минут после каждой
 * просьбы. Поэтому сравниваем с замером, снятым сразу после загрузки: вопрос не «мало ли
 * свободно», а «пришёл ли кто-то ещё».
 */
export const VRAM_OTHERS_MIN = 1024 * 1024 * 1024;

/**
 * Доля доступной памяти системы, ниже которой машине тесно.
 *
 * ⚠️ Копия SYSTEM_FREE_MIN_SHARE из sleepPolicy.ts, а не импорт: значимых импортов в этом файле
 * быть не должно. Совпадение значений сверяет scripts/model-idle-check.mjs — разъехавшись, эти
 * два числа дали бы браузер, который считает машину тесной для вкладок и просторной для модели.
 */
export const SYSTEM_FREE_MIN_SHARE = 0.2;

/** Состояние видеопамяти. freeAtLoad — сколько было свободно сразу ПОСЛЕ загрузки модели. */
export interface VramState {
  total: number;
  free: number;
  freeAtLoad: number;
}

/** Что известно про память машины на этой проверке. vram === null — модель считается на CPU. */
export interface HardwareState {
  vram: VramState | null;
  ramFree: number;
  ramTotal: number;
}

/**
 * Забита ли видеопамять ЧУЖИМИ.
 *
 * ⚠️ Два условия И, а не ИЛИ: кто-то забрал заметный кусок после нас И свободного осталось мало.
 * Без первого правило срабатывает от нас самих (см. VRAM_OTHERS_MIN), без второго — от любой
 * программы на просторной карте, где выгружаться незачем.
 */
export function isVramTight(v: VramState): boolean {
  if (v.total <= 0) return false;
  const takenAfterUs = v.freeAtLoad - v.free;
  return takenAfterUs >= VRAM_OTHERS_MIN && v.free / v.total < VRAM_FREE_MIN_SHARE;
}

/** Доля доступной памяти системы (os.freemem() / os.totalmem()). */
export function ramFreeShare(free: number, total: number): number {
  return total > 0 ? free / total : 1;
}

/** Тесно ли машине по обычной памяти. */
export function isRamTight(free: number, total: number): boolean {
  return ramFreeShare(free, total) < SYSTEM_FREE_MIN_SHARE;
}

/**
 * Тесно ли железу прямо сейчас.
 *
 * ⚠️ Здесь ИЛИ, и это НЕ противоречит конъюнкции в sleepPolicy.ts, хотя выглядит наоборот. Там
 * первое условие («мы над своим бюджетом») почти всегда истинно, и без второго вкладки выгружались
 * бы постоянно. Здесь оба условия — про МАШИНУ, а не про нас, и каждое честно означает «место
 * кончилось». Тесно на карте и тесно в оперативной — разные беды, и любой из них хватает.
 */
export function isHardwareTight(h: HardwareState): boolean {
  if (h.vram !== null && isVramTight(h.vram)) return true;
  return isRamTight(h.ramFree, h.ramTotal);
}

/** Состояние модели и очереди на момент проверки. */
export interface ModelIdleState {
  /** Модель действительно лежит в памяти (а не «загружается»). */
  loaded: boolean;
  /** Загрузка идёт прямо сейчас — выгружать нечего и незачем. */
  loading: boolean;
  /** Очередь к модели не пуста либо генерация идёт. */
  busy: boolean;
  /** Открыта AI-панель: пауза в диалоге не значит, что диалог кончился. */
  panelOpen: boolean;
  /** Когда человек в последний раз просил модель (фоновые задачи сюда НЕ входят). */
  lastUserRequestAt: number;
  /** Сколько проверок подряд железу было тесно. */
  tightStreak: number;
}

export type UnloadReason = 'idle' | 'pressure';

/**
 * Пора ли выгружать модель и почему. null — держим.
 *
 * ⚠️ Считается только ПОЛЬЗОВАТЕЛЬСКАЯ полоса очереди, и это главное решение этого файла. Фоновые
 * фичи (итоги дня, «ты это уже читал», разбор полей формы, выбор папки закладки) запускаются
 * только на ТЁПЛОЙ модели — гейт isModelWarm(). Считай мы их активностью, вышел бы замкнутый круг:
 * фон работает, потому что модель тёплая, и держит её тёплой тем, что работает. Выгрузка не
 * наступила бы никогда. Модель греется по просьбе человека и остывает без него; фон ездит на
 * тёплой, но своего времени ей не покупает.
 */
export function shouldUnloadModel(s: ModelIdleState, now: number): UnloadReason | null {
  if (!s.loaded || s.loading || s.busy || s.panelOpen) return null;
  const idleMs = now - s.lastUserRequestAt;
  if (idleMs >= MODEL_IDLE_TIMEOUT) return 'idle';
  // Давление проверяем ПОСЛЕ простоя: если сработали оба, честнее назвать причиной простой —
  // модель ушла бы и без чужой программы.
  if (s.tightStreak >= TIGHT_STREAK && idleMs >= PRESSURE_MIN_IDLE) return 'pressure';
  return null;
}
