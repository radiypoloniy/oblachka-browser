// Какую строку омнибокса выделить после ПЕРЕСБОРКИ списка подсказок.
//
// ⚠️ Задача существует потому, что список собирается ДВАЖДЫ на одно нажатие клавиши: сразу —
// история и вкладки, и повторно — когда доедут живые подсказки поисковика, а им отведено до трёх
// секунд (см. useOmniboxSuggestions::triggerSuggest и SearchSuggestFetcher). Раньше вторая сборка
// безусловно выставляла предвыбор и слала его в нативную вью — то есть ЗАБИРАЛА У ЧЕЛОВЕКА ЕГО
// ВЫБОР: он ушёл стрелками на третью строку, через две секунды приехала сеть, и подсветка сама
// прыгнула обратно. Снаружи это выглядит как «стрелки живут своей жизнью».
//
// ⚠️ ВЫБОР ДЕРЖИТСЯ ЗА СТРОКУ, А НЕ ЗА НОМЕР. Пересборка не дописывает список в конец, а собирает
// его заново: сетевые подсказки встают между историей и поиском, порядок меняется. Сохранив
// НОМЕР, мы оставили бы человека на месте, где теперь стоит другая строка, — и Enter увёл бы не
// туда. Это хуже сброса: сброс хотя бы видно.
//
// ⚠️ Привязка к ПОКОЛЕНИЮ запроса (seq). Человек набрал ещё букву — список стал про другое, и
// держаться за прежнюю строку незачем: там начинается новый выбор с предвыбором героя.
//
// Значимых импортов нет — модуль под проверкой (scripts/omnibox-selection-check.mjs), она гоняется
// голым node (см. правило про shared/ в CLAUDE.md).

/** Строка, на которую человек встал сам. Пустой url — «выбрана набранная строка» (позиция -1). */
export interface HeldSelection {
  /** Поколение запроса, в котором человек сделал выбор. */
  seq: number;
  url: string;
}

/** Позиция «выбрана сама набранная строка»: Enter ведёт по набранному. */
export const TYPED_ROW = -1;

/**
 * @param items      новый список подсказок
 * @param preselect  что выделить, если человек выбор не делал (герой или TYPED_ROW)
 * @param held       выбор человека, если он был
 * @param seq        поколение, для которого собран новый список
 */
export function selectionAfterRebuild(
  items: readonly { url: string }[],
  preselect: number,
  held: HeldSelection | null,
  seq: number,
): number {
  // Человек выбор не делал — работает предвыбор, как и раньше.
  if (held === null || held.seq !== seq) return clamp(preselect, items.length);

  // Он стоял на набранной строке и остаётся на ней: приезд подсказок не повод уводить его оттуда.
  if (held.url === '') return TYPED_ROW;

  const at = items.findIndex((i) => i.url === held.url);
  if (at >= 0) return at;

  // ⚠️ Строки, на которой он стоял, в новом списке нет. Уводим на НАБРАННОЕ, а не на предвыбор:
  // предвыбор — это «мы за вас решили, что Enter пойдёт сюда», и делать это молча в момент, когда
  // у человека из-под курсора убрали строку, нельзя. Набранное — единственный безопасный исход.
  return TYPED_ROW;
}

/**
 * ⚠️ Предвыбор тоже зажимаем. Он приходит из другой части кода и рассчитан на список, который к
 * этому моменту уже сменился; номер за пределами списка дал бы подсветку на строке, которой нет.
 */
function clamp(idx: number, length: number): number {
  if (idx < 0 || length === 0) return TYPED_ROW;
  return idx < length ? idx : TYPED_ROW;
}
