// Геометрия якорных поповеров-оверлеев: буфер обмена, загрузки, автозаполнение, пароли,
// карточка сайта под щитом. Один источник правды для ГЛАВНОГО процесса (он ставит bounds вью) и
// для РЕНДЕРЕРА (он рисует внутри неё карточку с тенью).
//
// ⚠️ Раньше обе константы были продублированы в каждом менеджере и в каждом .tsx с припиской
// «держать в синхроне» — и разъехались ровно так, как такие приписки и разъезжаются: запас под
// тень стоял 16 у пяти поповеров, 20 у трёх, 24 у одного и 40 у двух, при ОДНОЙ общей тени на
// всех. Тень с вылетом 38 px в запасе 16 обрезается рамкой вью по нижней кромке, и глаз читает
// это как «тень грубая и резкая» — та же поломка, что закрывали в истории, только там резал
// overflow, а здесь режет граница самой вью.
//
// ⚠️ ЗАПАС ХИТ-ТЕСТИТСЯ. Прозрачное поле под тень ловит клики всем прямоугольником вью, а не
// видимой карточкой, поэтому ЗАЗОР ОТ ЯКОРЯ ОБЯЗАН БЫТЬ НЕ МЕНЬШЕ ЗАПАСА: иначе верхний край вью
// встаёт выше низа кнопки-якоря и её нижняя часть перестаёт нажиматься, пока поповер открыт.
// Живой случай: при зазоре 6 и запасе 16 поповер не закрывался повторным кликом по своей же
// кнопке — «как повезёт попасть выше кромки». Тот же просчёт на дропдауне омнибокса накрывал
// адресную строку целиком и месяц выглядел как проблема фокуса.
//
// Отсюда правило, которое стережёт scripts/overlay-shadow-check.mjs: вылет тени ≤ запас ≤ зазор.

/** Прозрачное поле вокруг карточки, в котором живёт её тень. */
export const OVERLAY_SHADOW_MARGIN = 24;

/** Зазор между якорем (кнопкой) и верхом карточки. Не меньше запаса — см. разбор про хит-тест. */
export const OVERLAY_GAP = 24;

/**
 * Насколько карточка, заякоренная на ПОЛЕ ФОРМЫ, вправе уехать вправо от начала поля.
 *
 * ⚠️ Ограничение существует потому, что честное центрирование на ШИРОКОМ поле (а поле ввода на
 * сайте бывает во всю колонку) уводит карточку на сотни пикселей от места, куда человек кликнул,
 * — она читается как «прилетела ниоткуда». У Chrome та же оговорка: карточка центрируется на
 * поле, но на широких полях центрирование применяется не строго.
 */
export const OVERLAY_FIELD_MAX_SHIFT = 48;

/**
 * Левый край карточки, заякоренной на ПОЛЕ ФОРМЫ.
 *
 * ⚠️ Карточка центрируется на поле, а НЕ прижимается к его краю, и это решение Chrome, принятое
 * по измеренной причине: прижатая к левому краю карточка накрывает подписи полей (они тоже
 * прижаты влево), и человек перестаёт видеть, что за поле идёт следующим. Chrome 97–101 переехал
 * с левого края на центр поля ровно из-за этого.
 *
 * Для КНОПКИ в тулбаре правило другое (там карточка прижимается к кнопке) — см. вызывающие
 * менеджеры: у них два вида якоря, и путать их нельзя.
 */
export function anchoredCardX(
  anchorX: number,
  anchorWidth: number,
  cardWidth: number,
  winWidth: number,
  margin: number,
): number {
  const shift = Math.min(anchorWidth / 2 - cardWidth / 2, OVERLAY_FIELD_MAX_SHIFT);
  const maxX = Math.max(margin, winWidth - cardWidth - margin);
  return Math.min(Math.max(margin, anchorX + shift), maxX);
}
