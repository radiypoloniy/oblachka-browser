// Ключ страницы — ответ на вопрос «это тот же самый адрес или другой».
//
// ⚠️ Заведён по живому багу (25.08.2026): человек сохранял страницу Ozon в закладки, открывал её
// из панели — звезда не горела, повторное нажатие плодило дубль, и только тогда звезда
// загоралась. Причина: Ozon дописывает в адрес метки шаринга (`at`, `sh`), которые МЕНЯЮТСЯ при
// каждом открытии. Сохранён был один адрес, открылся другой, а сравнение шло точной строкой.
//
// ⚠️ Это НЕ «очистка ссылки» и не приватность: мы не переписываем адрес, по которому ходит
// человек, и не отрезаем параметры от запроса. Функция считает КЛЮЧ для сравнения — и только.
//
// ⚠️ Список имён, а не список сайтов, — и это принципиально: параметр `utm_source` шумный везде,
// где встречается. Доменная таблица внизу — вынужденное исключение для площадок, которые кладут
// в адрес уникальную метку сессии; там признака нет, есть только знание. Она растёт по мере
// встреч, а не «на вырост».
//
// ⚠️ Значимых импортов нет — проверка scripts/page-key-check.mjs гоняется голым node.

/**
 * Параметры, которые заведомо не влияют на содержимое страницы.
 *
 * ⚠️ Сюда попадает только то, что безопасно выкинуть ВЕЗДЕ. `q`, `text`, `v`, `id`, `page` и
 * прочее содержательное здесь появиться не может: схлопнув их, мы объявили бы две разные
 * страницы поиска одной и той же — а это хуже исходного бага, потому что звезда начнёт врать.
 */
const NOISE_PARAMS: readonly string[] = [
  'gclid', 'yclid', 'ysclid', 'fbclid', 'msclkid', 'dclid', 'twclid',
  '_openstat', 'igshid', 'mc_cid', 'mc_eid', 'vero_id', 'oly_enc_id',
  'utm_source', 'utm_medium', 'utm_campaign', 'utm_term', 'utm_content', 'utm_referrer',
];

/**
 * Метки, шумные ТОЛЬКО на конкретных площадках.
 *
 * ⚠️ Ozon: `at` и `sh` — метки шаринга, они разные при каждом открытии одной и той же карточки
 * товара. Именно этот случай и был в жалобе. В общий список их класть нельзя: `at` вполне может
 * означать «время» или «аккаунт» на другом сайте.
 */
const NOISE_BY_HOST: Readonly<Record<string, readonly string[]>> = {
  'ozon.ru': ['at', 'sh', 'advert_id', 'miniapp'],
  'aliexpress.com': ['spm', 'aff_fcid', 'aff_fsk', 'aff_platform', 'terminal_id'],
  'avito.ru': ['context'],
};

/** Хост без `www.` и в нижнем регистре — по нему ищется доменная таблица. */
function baseHost(hostname: string): string {
  const h = hostname.toLowerCase().replace(/^www\./, '');
  // Поддомены наследуют правила площадки: m.ozon.ru — тот же Ozon.
  for (const known of Object.keys(NOISE_BY_HOST)) {
    if (h === known || h.endsWith(`.${known}`)) return known;
  }
  return h;
}

/**
 * Ключ, по которому две ссылки считаются одной страницей.
 *
 * Убирает: фрагмент, шумные параметры, завершающий слэш. Приводит схему и хост к нижнему
 * регистру. Всё остальное — включая порядок значимых параметров — сохраняется как есть.
 *
 * ⚠️ Порядок параметров НЕ сортируется намеренно. Соблазн велик («?a=1&b=2» и «?b=2&a=1» это одна
 * страница), но на части сайтов порядок значим, а выигрыш здесь нулевой: адрес одной и той же
 * страницы у одного человека не меняет порядок параметров сам по себе.
 *
 * Неразбираемая строка возвращается как есть: ключ обязан существовать всегда, иначе сравнение
 * молча превратится в «ничего не совпадает».
 */
export function pageKey(url: string): string {
  try {
    const u = new URL(url);
    u.hash = '';
    u.protocol = u.protocol.toLowerCase();
    u.hostname = u.hostname.toLowerCase();

    const hostNoise = NOISE_BY_HOST[baseHost(u.hostname)] ?? [];
    for (const key of [...u.searchParams.keys()]) {
      const lower = key.toLowerCase();
      if (NOISE_PARAMS.includes(lower) || hostNoise.includes(lower)) u.searchParams.delete(key);
    }

    let result = u.toString();
    // Завершающий слэш убирается для ЛЮБОГО пути: /article/ и /article — одна страница. Query
    // всегда идёт последней, поэтому срез не заденет её.
    if (result.length > 1 && result.endsWith('/')) result = result.slice(0, -1);
    return result;
  } catch {
    return url;
  }
}

/** Две ссылки указывают на одну и ту же страницу. */
export function samePage(a: string, b: string): boolean {
  return pageKey(a) === pageKey(b);
}
