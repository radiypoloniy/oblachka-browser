// Склейка скриптлетов адблока в один скрипт — с двумя взаимно противоположными требованиями.
//
// Ghostery отдаёт каждый скриптлет САМОДОСТАТОЧНЫМ скриптом: со своей копией обвязки uBO
// (safeSelf, proxyApplyFn, scriptletGlobals и прочее). Выполнять их по одному, как делает
// оригинальная библиотека, нельзя, и склеивать наивно — тоже. Оба провала пойманы на живых
// сайтах, и оба чинятся одной строкой ниже.
//
// ⚠️ Требование 1 — ОБЩИЙ скоуп. Два скриптлета, оборачивающих одну функцию, из РАЗНЫХ копий
// обвязки зацикливаются друг в друге: chatgpt.com отдаёт два prevent-fetch на window.fetch, и
// страница падала с «Maximum call stack size exceeded», SPA не открывалась вовсе. Лечится тем,
// что `var scriptletGlobals` и объявления функций видны всем скриптлетам сразу — обвязка одна.
//
// ⚠️ Требование 2 — РАЗДЕЛЬНЫЕ лексические объявления. Простая склейка через '\n;\n' даёт
// SyntaxError на первом же сайте, где два скриптлета объявляют одно имя: youtube.com/watch отдаёт
// 30 скриптлетов, из них ЧЕТЫРЕ json-prune объявляют `class JSONPath` — «Identifier 'JSONPath' has
// already been declared». Ошибка разбора, поэтому не выполняется НИ ОДНА строка пачки: адблок
// молча переставал резать рекламу в видео, хотя движок исправно отдавал все 30 скриптлетов с
// нужными правилами. Симптом выглядел как «фильтры не те», а дело было в склейке.
//
// Решение — блок `{ … }` вокруг каждого скриптлета. `class`, `const` и `let` блочные и больше не
// сталкиваются; `var` и объявления функций всплывают в общий скоуп скрипта (Annex B) и остаются
// общими. Проверено сквозным стендом на настоящих 30 скриптлетах YouTube: пачка выполняется
// целиком и раньше инлайн-скриптов страницы, adPlacements и playerAds гасятся.
export function joinScriptlets(scripts: readonly string[]): string {
  return scripts.map((s) => `{\n${s}\n}`).join('\n;\n');
}
