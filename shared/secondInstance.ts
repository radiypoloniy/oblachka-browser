// Что делать с повторным запуском (клик по ярлыку или ссылка из другой программы), когда браузер
// уже запущен. Чистая логика: решение принимается по трём фактам, исполняет его
// electron/secondInstance.ts.
//
// ⚠️ Модуль под проверкой голым node (scripts/second-instance-check.mjs) — значимых импортов нет.

export type SecondInstanceAction =
  /** Окно есть — поднять его (и открыть адрес, если пришёл). */
  | 'focus'
  /** Сессия ещё восстанавливается — окна появятся сами, адрес отложить до них. */
  | 'defer'
  /** Процесс доигрывает выход — перезапуститься после него. */
  | 'relaunch'
  /** Окон нет, а процесс живёт штатно (macOS) — поднять новое окно. */
  | 'revive';

/**
 * ⚠️ Прежде «окон нет» означало одно: создать окно. А пустое окно без сессии — это ровно то, что
 * человек видел после «закрыл и тут же открыл заново»: старый процесс ещё несколько секунд
 * останавливает VPN и модель и чистит куки (AppShutdown.ts), держит замок одного экземпляра, и
 * новый запуск прилетал в него. Вкладки при этом целы на диске — их просто не читали, потому что
 * сессия восстанавливается только на старте процесса.
 *
 * ⚠️ «Окон нет после восстановления» на Windows и Linux ВСЕГДА значит выход: закрытие последнего
 * окна само зовёт app.quit() (см. win.on('closed') в main.ts). На macOS процесс без окон — штатное
 * состояние, там прежнее поведение.
 *
 * ⚠️ Пока сессия не восстановлена, окон тоже нет, но перезапуск здесь был бы бедой: выход
 * посреди старта. Повторный клик по ярлыку на медленном старте — обычное дело, и раньше он давал
 * лишнее пустое окно рядом с восстановленными.
 */
export function secondInstanceAction(s: { hasWindow: boolean; restored: boolean; platform: string }): SecondInstanceAction {
  if (s.hasWindow) return 'focus';
  if (!s.restored) return 'defer';
  return s.platform === 'darwin' ? 'revive' : 'relaunch';
}
