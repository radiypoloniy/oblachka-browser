// Сборка финального списка подсказок омнибокса из готовых частей.
//
// ⚠️ Порядок секций — по образцу Яндекс.Браузера (живое сравнение): самый релевантный результат
// наверху, СРАЗУ за ним «искать в вебе» — это всегда доступный, надёжный вариант, и ждать, пока
// человек долистает историю до него, незачем. Дальше менее уверенные совпадения из истории и
// вкладок, и в конце живые подсказки поисковика: у них сигнал слабее всех, они не привязаны к
// посещённым страницам вообще.
//
// ⚠️ Здесь только СБОРКА. Поиск по истории, живые подсказки, дедупликация вкладок — снаружи:
// они ходят к main и в сеть, а это место должно оставаться проверяемым голым node.
//
// Значимых импортов нет — проверка scripts/suggest-list-check.mjs гоняется голым node.
import type { SuggestDropdownItem } from './ipc';

export type SuggestItem = SuggestDropdownItem;

/**
 * Похоже ли на адрес, а не на запрос.
 *
 * ⚠️ Правило нарочно грубое — точка или двоеточие. Разбор адреса живёт в main
 * (AddressParser.ts), и повторять его здесь значило бы завести вторую правду; здесь нужен только
 * ответ на вопрос «человек печатал адрес или слова».
 *
 * ⚠️ На выбор «дубль или переход» это БОЛЬШЕ НЕ ВЛИЯЕТ (см. composeSuggestions): подсказка всегда
 * открывает страницу. Признак остался ради предвыбора первой строки — там он про другое.
 */
export function looksLikeAddress(query: string): boolean {
  return /[.:]/.test(query.trim());
}

export interface ComposeInput {
  /** Лучшее совпадение из истории и вкладок. Рисуется отдельной карточкой, без подписи секции. */
  topItem?: SuggestItem;
  /** «Искать: …» — всегда второй, сразу за героем. */
  searchItem: SuggestItem;
  /** Остальные совпадения из истории и открытых вкладок. */
  restItems: SuggestItem[];
  /** Живые подсказки поисковика. */
  suggestItems: SuggestItem[];
  /** Что человек набрал — от этого зависит правило вкладок ниже. */
  query: string;
  /** Имя поисковика для подписи секции («Предложения Google»). */
  engineName: string;
}

/**
 * Собрать список для дропдауна.
 *
 * ⚠️ ГЛАВНОЕ ПРАВИЛО ЗДЕСЬ — про вкладки, и оно одно на все запросы: подсказка ВСЕГДА ОТКРЫВАЕТ
 * страницу, даже если она уже открыта в другой вкладке. Прежде правило зависело от того, похоже
 * ли набранное на адрес: адрес открывал дублем, а имя телепортировало к старой вкладке. Разницу
 * приходилось угадывать по тексту в строке, и она удивляла ровно тогда, когда человек её не ждал.
 *
 * ⚠️ Переход никуда не делся — он стал ОТДЕЛЬНЫМ действием: у строки появляется пометка «уже
 * открыта», по которой можно кликнуть (см. openTab и вью дропдауна). Так основное действие
 * предсказуемо, а второе — доступно и видимо.
 *
 * ⚠️ `kind: 'tab'` при этом сохраняется у СМЫСЛОВОГО поиска вкладок: он добавляет свои строки
 * мимо этой функции, и там переключение — то, за чем пришли.
 *
 * ⚠️ Подпись секции ставится ТОЛЬКО на первый элемент группы: вью рисует то, что получила, и
 * сама ничего не группирует (см. sectionHeader в shared/ipc.ts). У героя подписи нет вовсе — он
 * и так выделен отдельной карточкой, подпись над одной строкой была бы шумом.
 */
export function composeSuggestions(input: ComposeInput): SuggestItem[] {
  const { topItem, searchItem, restItems, suggestItems, engineName } = input;

  const rest = [...restItems];
  if (rest[0]) rest[0] = { ...rest[0], sectionHeader: 'История и вкладки' };

  const suggests = [...suggestItems];
  if (suggests[0]) suggests[0] = { ...suggests[0], sectionHeader: `Предложения ${engineName}` };

  // Вкладка → обычная навигация, а привязка переезжает в openTab: строка откроет страницу, но
  // покажет, что она уже где-то есть.
  const asNav = (i: SuggestItem): SuggestItem => (
    i.kind === 'tab' && i.tabId
      ? {
        ...i,
        kind: 'history',
        tabId: undefined,
        windowId: undefined,
        openTab: { tabId: i.tabId, windowId: i.windowId },
      }
      : i
  );

  return (topItem
    ? [topItem, searchItem, ...rest, ...suggests]
    : [searchItem, ...suggests]
  ).map(asNav);
}
