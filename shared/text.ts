// Живой баг: remark серверов подписки (VpnParser.ts) часто несёт emoji-флаг (🇳🇱, 🇩🇪…).
// Windows не всегда рендерит парный regional-indicator как флаг — иногда это два отдельных
// глифа, которые в узкой капсуле/поповере налезают на соседний текст. Не полагаемся на
// поддержку эмодзи конкретным шрифтом/ОС в тесных местах — просто убираем их из отображаемого
// текста. \p{Extended_Pictographic} — большинство эмодзи; regional indicators (флаги) в этот
// класс не входят, добавлены отдельным диапазоном; ‍ (ZWJ) и ️ (variation selector-16)
// склеивают составные эмодзи и сами по себе иногда рендерятся как «мусорный» символ.
export function stripEmoji(text: string): string {
  return text
    .replace(/[\u{1F1E6}-\u{1F1FF}]|\p{Extended_Pictographic}|\u{200D}|\u{FE0F}/gu, '')
    .replace(/\s+/g, ' ')
    .trim();
}
