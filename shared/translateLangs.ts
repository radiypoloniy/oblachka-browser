// Языки, на которые предлагаем перевести СВОЙ текст (кнопка «Перевести на…» в правке текста поля).
//
// ⚠️ Живёт в shared, потому что нужен ОБОИМ берегам: main строит по нему подменю ПКМ (TabManager),
// renderer поповера показывает по коду человеческое имя («Перевожу на английский…»). Держать два
// списка в синхроне руками — ровно тот класс расхождений, от которого CLAUDE.md предостерегает.
//
// Коды — те же короткие ISO, что понимает TranslationService.LANG_NAME (он переводит их в
// английские имена для промпта). Набор — популярные европейские плюс несколько мировых; порядок
// от самого частого запроса. Русский тоже здесь: человек может писать по-английски и хотеть на
// русский — resolveDirection сам разберётся, что переводить, а что уже на целевом.
export interface TranslateLang {
  code: string;  // 'en' — уходит в TranslationService как цель ('auto->en')
  label: string; // 'Английский' — подпись в меню и в поповере
}

export const TRANSLATE_TARGETS: TranslateLang[] = [
  { code: 'en', label: 'Английский' },
  { code: 'de', label: 'Немецкий' },
  { code: 'fr', label: 'Французский' },
  { code: 'es', label: 'Испанский' },
  { code: 'it', label: 'Итальянский' },
  { code: 'pt', label: 'Португальский' },
  { code: 'zh', label: 'Китайский' },
  { code: 'ru', label: 'Русский' },
];

// Имя языка по коду — для подписи в поповере. Неизвестный код (теоретически) отдаём как есть,
// а не роняем интерфейс.
export function translateLangLabel(code: string): string {
  return TRANSLATE_TARGETS.find((l) => l.code === code)?.label ?? code;
}
