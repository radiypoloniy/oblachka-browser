// Сопоставление запроса со строкой по СЛОВАМ, с поправкой на русские склонения.
//
// ⚠️ Живёт ОТДЕЛЬНО и БЕЗ импортов — под прогон обычным node (npm run word-match-check).
//
// Зачем отдельный модуль. Поиск по истории переживает склонения сам: там FTS5 со стеммером
// (см. textStemming.ts). А закладки и загрузки ищутся по обычной строке — и на живом профиле это
// провалилось: файл «отчет по исследованию.docx» не находился ни по «исследования», ни по
// «исследование», потому что подстроки там действительно нет. Стеммер из main сюда тащить нельзя
// (он живёт ради FTS5 и в renderer не ходит), поэтому здесь тот же приём, что в поиске по
// настройкам: сравнение по началу слова с защитой от ложных совпадений.

/** ⚠️ «ё» → «е»: иначе «ёлка» и «елка» разные слова, а человек набирает как придётся. */
function normalize(s: string): string {
  return s.toLowerCase().replace(/ё/g, 'е');
}

function wordsOf(s: string): string[] {
  return normalize(s).split(/[^a-zа-я0-9]+/).filter(Boolean);
}

/** Слова короче трёх букв («на», «до», «по») совпадают со всем подряд — в запрос не берём. */
export function queryTokens(query: string): string[] {
  return wordsOf(query).filter((t) => t.length >= 3);
}

// ⚠️ Те же два условия, что в поиске по настройкам, и по той же причине: совпадение по началу
// слова — это про СКЛОНЕНИЕ, а не про «слово начинается так же». Без них короткое слово цепляется
// за длинное чужое («вид» находится внутри «видеопамяти»).
const MIN_PREFIX_TOKEN = 4;
const MAX_TAIL_GROWTH = 3;

function wordMatches(token: string, word: string): boolean {
  if (word === token) return true;
  if (token.length < MIN_PREFIX_TOKEN) return false;
  // Корень — слово без двух последних букв: ровно столько меняет русское окончание
  // («исследования» → «исследован», и «исследованию» с него начинается).
  const stem = token.slice(0, Math.max(3, token.length - 2));
  return word.startsWith(stem) && word.length - token.length <= MAX_TAIL_GROWTH;
}

/**
 * Сколько слов запроса нашлось в строке.
 *
 * ⚠️ Считаем именно КОЛИЧЕСТВО, а не «да/нет»: на запросе из двух слов вещь, совпавшая обоими,
 * почти всегда и есть искомая, а совпавшая одним частым словом («документ») — случайный сосед.
 * Прежний ответ «да/нет» это различие терял, и на живом профиле закладка «Новости 2001 — Google
 * Документы» оказывалась выше файла, который человек искал.
 */
export function countMatches(haystack: string, tokens: string[]): number {
  const words = wordsOf(haystack);
  let n = 0;
  for (const token of tokens) {
    if (words.some((w) => wordMatches(token, w))) n++;
  }
  return n;
}
