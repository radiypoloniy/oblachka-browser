import { siteHue } from './desktop/siteTint';

// Значок папки в духе iOS Files: объёмная папка с задней стенкой, передней панелью, градиентом
// и бликом — а не однотонный контурный глиф из набора иконок.
//
// ⚠️ Почему своей отрисовкой, а не lucide. Контурная иконка на 18 px в сетке сайдбара
// превращалась в неразличимую закорючку: у всех папок она одинаковая, отличить одну от другой
// нельзя вообще. Здесь цвет выводится из НАЗВАНИЯ папки, поэтому «Работа» и «Рецепты» — разные
// значки, и человек узнаёт нужный, не читая подпись. Тот же приём, что у своих глифов приложений
// (см. appGlyphs.tsx): рисуем предмет, а не его силуэт.
//
// ⚠️ Оттенок берётся из ТОГО ЖЕ фиксированного набора, что и подложки иконок сайтов
// (siteTint.ts): в нём нет сиреневого сектора — фиолетового в системе нет вовсе.
//
// ⚠️ id градиентов выводятся из оттенка, а не из случайного значения: одинаковые папки делят
// одно определение, а разные не сталкиваются. Случайные id ломались бы при повторном
// монтировании, а фиксированный один — при двух папках разного цвета на экране.

export default function FolderGlyph({ title, size = 44 }: { title: string; size?: number }) {
  const h = siteHue(title || 'папка');
  const id = `fg${h}`;

  return (
    <svg width={size} height={size} viewBox="0 0 48 48" aria-hidden style={{ display: 'block', flexShrink: 0 }}>
      <defs>
        {/* Передняя панель: светлее сверху — свет падает сверху, как у всех иконок системы. */}
        <linearGradient id={`${id}f`} x1="0" y1="0" x2="0" y2="1">
          <stop offset="0" stopColor={`hsl(${h} 82% 68%)`} />
          <stop offset="1" stopColor={`hsl(${h} 72% 52%)`} />
        </linearGradient>
        {/* Задняя стенка — темнее передней, иначе объём не читается. */}
        <linearGradient id={`${id}b`} x1="0" y1="0" x2="0" y2="1">
          <stop offset="0" stopColor={`hsl(${h} 70% 58%)`} />
          <stop offset="1" stopColor={`hsl(${h} 66% 46%)`} />
        </linearGradient>
      </defs>

      {/* Задняя стенка с язычком */}
      <path
        fill={`url(#${id}b)`}
        d="M4 13.5A4.5 4.5 0 0 1 8.5 9h10.2c1.2 0 2.3.5 3.1 1.3l3.1 3.2h16.6A4.5 4.5 0 0 1 46 18v18.5a4.5 4.5 0 0 1-4.5 4.5h-33A4.5 4.5 0 0 1 4 36.5z"
      />
      {/* Тонкая тень под кромкой передней панели — она и делает папку объёмной. */}
      <path fill="rgba(0,0,0,0.16)" d="M4 20h42v3H4z" />
      {/* Передняя панель */}
      <path
        fill={`url(#${id}f)`}
        d="M2.5 24.5A4.5 4.5 0 0 1 7 20h36a4.5 4.5 0 0 1 4.5 4.5v12A4.5 4.5 0 0 1 43 41H7a4.5 4.5 0 0 1-4.5-4.5z"
      />
      {/* Блик по верхней кромке — та же роль, что у specular edge у стеклянных плиток. */}
      <path
        fill="rgba(255,255,255,0.34)"
        d="M7 20h36a4.5 4.5 0 0 1 4.4 3.6H2.6A4.5 4.5 0 0 1 7 20z"
      />
    </svg>
  );
}
