import { siteHue } from './desktop/siteTint';

// Значок папки в языке macOS Finder: приземистая папка, светлая задняя стенка, насыщенная
// передняя панель, крупное скругление, светлая кромка сверху.
//
// ⚠️ Своя отрисовка, а не готовый файл. Иконка папки Finder — художество Apple, и класть её в
// продукт нельзя; в проекте уже есть такой отказ (логотипа Яндекса нет в наборе браузеров, и
// вместо перерисовки чужого знака там буквенная плашка). Повторяем ЯЗЫК — пропорции, свет,
// скругления, — а не файл.
//
// ⚠️ Четыре вещи, из-за которых прошлая версия читалась как «папка вообще», а не как Apple:
//  • ЗАДНЯЯ стенка была ТЕМНЕЕ передней. У Apple наоборот: зад светлый и приглушённый, перёд
//    насыщенный — именно это и создаёт впечатление, что папка открыта к зрителю, а не сложена
//    из двух картонок. Одна эта инверсия давала весь эффект «не то».
//  • Папка была слишком высокой. У Finder она ПРИЗЕМИСТАЯ: передняя панель занимает около
//    четырёх пятых высоты, а сам значок заметно шире, чем высок.
//  • Мелкое скругление. У Apple радиус крупный, порядка десятой доли ширины, — от этого силуэт
//    мягкий; острые углы моментально выдают самоделку (тот же довод, что у squircle в aiApps).
//  • Не было тени. Значок лежал плоско на подложке, а у Apple он всегда чуть приподнят.
//
// ⚠️ Цвет по-прежнему выводится из НАЗВАНИЯ: у Finder все папки синие, но там их различает
// имя под значком в широком окне, а у нас колонка 256 px с обрезанными подписями — цвет остаётся
// единственным, что позволяет узнать папку не читая. Оттенки — из того же фиксированного набора,
// что подложки иконок сайтов (siteTint.ts), там нет сиреневого сектора.
//
// ⚠️ id градиентов выводятся из оттенка: одинаковые папки делят одно определение, разные не
// сталкиваются. Случайные id ломались бы при повторном монтировании.

export default function FolderGlyph({ title, size = 44 }: { title: string; size?: number }) {
  const h = siteHue(title || 'папка');
  const id = `fg${h}`;

  return (
    <svg
      width={size} height={size} viewBox="0 0 48 48" aria-hidden
      style={{
        display: 'block', flexShrink: 0,
        // Тень на самом значке, а не на плитке под ним: она должна повторять силуэт папки, а
        // box-shadow повторил бы прямоугольник svg.
        // ⚠️ ОДНА и плотная, а не две мягкие. Две размытые тени (радиус 5 при 40 px значка)
        // расползались тёмным ореолом вокруг всей папки — именно это читалось как «в тумане».
        // Дальняя тень уместна на иконке 90 px домашнего экрана, а на 40 px она крупнее самой
        // детали, которую подсвечивает.
        filter: 'drop-shadow(0 1px 1.5px rgba(16,20,32,0.28))',
      }}
    >
      <defs>
        {/* ⚠️ Разрыв светлоты между задом и передом РАЗВЁДЕН шире (было 78→71 против 68→56, то
            есть панели почти сливались). Когда две поверхности отличаются на несколько процентов,
            силуэт перестаёт читаться и значок выглядит размытым, даже будучи идеально резким. */}
        <linearGradient id={`${id}b`} x1="0" y1="0" x2="0" y2="1">
          <stop offset="0" stopColor={`hsl(${h} 70% 82%)`} />
          <stop offset="1" stopColor={`hsl(${h} 66% 76%)`} />
        </linearGradient>
        {/* Передняя панель — заметно насыщеннее и темнее задней, свет сверху. */}
        <linearGradient id={`${id}f`} x1="0" y1="0" x2="0" y2="1">
          <stop offset="0" stopColor={`hsl(${h} 76% 63%)`} />
          <stop offset="1" stopColor={`hsl(${h} 74% 49%)`} />
        </linearGradient>
      </defs>

      {/* Задняя стенка с язычком слева. Язычок пологий и небольшой — у Finder он именно намёк
          на вкладку, а не выступающая «ступенька», как на офисных иконках. */}
      <path
        fill={`url(#${id}b)`}
        d="M3.5 15.4a4.4 4.4 0 0 1 4.4-4.4h9.9c1 0 2 .4 2.7 1.1l2.4 2.5c.7.7 1.7 1.1 2.7 1.1h14.5a4.4 4.4 0 0 1 4.4 4.4v14.5a4.4 4.4 0 0 1-4.4 4.4H7.9a4.4 4.4 0 0 1-4.4-4.4z"
      />

      {/* Передняя панель. Начинается ниже верха задней — ровно этот зазор и показывает, что
          папка объёмная; больше ничего для этого не нужно. */}
      <path
        fill={`url(#${id}f)`}
        d="M2.6 21.6a4.6 4.6 0 0 1 4.6-4.6h33.6a4.6 4.6 0 0 1 4.6 4.6v12.4a4.6 4.6 0 0 1-4.6 4.6H7.2a4.6 4.6 0 0 1-4.6-4.6z"
      />

      {/* Светлая кромка по верху передней панели — тот же приём, что specular edge у стеклянных
          плиток: она делает поверхность материальной, а не залитой цветом.
          ⚠️ ТОНКАЯ линия, а не полоса в четверть панели. Прежняя заливка высотой 3.7 единицы
          при панели в 21 — это шестая часть её высоты белым по всей ширине; на 40 px она
          сливалась с фоном плитки и мылила верхнюю кромку вместо того, чтобы её очертить. */}
      <path
        fill="rgba(255,255,255,0.55)"
        d="M7.2 17h33.6a4.6 4.6 0 0 1 3.3 1.4H3.9A4.6 4.6 0 0 1 7.2 17z"
      />
    </svg>
  );
}
