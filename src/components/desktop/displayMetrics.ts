// Сколько места займёт строка дисплейной гарнитурой — в единицах кегля.
//
// ⚠️ Отдельным модулем, а не строчкой в виджетах: числа тут ЗАМЕРЕНЫ В БРАУЗЕРЕ, и способ замера
// важнее самих чисел — на нём здесь дважды ошиблись, и оба раза время вылезало за правый край
// плитки. Такому разбору нужно место, где его прочитают раньше, чем поправят число.

// ⚠️ ЧИСЛА ЗАМЕРЕНЫ В БРАУЗЕРЕ, И СПОСОБ ЗАМЕРА ВАЖНЕЕ САМИХ ЧИСЕЛ — на нём тут уже дважды
// ошиблись, и оба раза время вылезало за правый край плитки.
//
// ⚠️ ГЛАВНАЯ ЛОВУШКА: `canvas.measureText` НЕ ПРИМЕНЯЕТ `font-variant-numeric: tabular-nums`, а
// роль DISPLAY его включает. В Unbounded цифры пропорциональные и очень разные — «0» это 0.917 em,
// «8» — 0.883, «1» — всего 0.507. Канва честно меряет пропорциональные, интерфейс рисует
// табличные, и замер получается заниженным почти вдвое. Ровно так здесь появилось DIGIT_EM = 0.50
// (с комментарием «замерено по факту»), после чего «14:34» кеглем 68 заняло 223.7 px в поле
// шириной 193 — вылезло на 14.7 px.
//
// ⚠️ ПРАВИЛЬНЫЙ ЗАМЕР — ПО DOM, а не по канве: поставить строку тем же кеглем, весом и трекингом,
// снять getBoundingClientRect и вычесть трекинг (letterSpacing добавляется ПОСЛЕ каждого знака,
// включая последний). Так получено: «14:34» = 3.44 em при весе 600, откуда табличная цифра 0.78,
// а двоеточие 0.32. Сторож scripts/clock-fit-drive.mjs проверяет результат на живой плитке.
//
// ⚠️ Вес влияет слабо (700 шире 600 примерно на 2 %), гарнитура — сильно. Меняется дисплейная
// гарнитура — числа пересчитываются заново, тем же способом.
export const DIGIT_EM = 0.78;
const COLON_EM = 0.32;
const SPACE_EM = 0.28;
// Всё прочее (знаки валют, °, буквы) — с запасом: они шире цифр, и лучше недобрать кегль,
// чем обрезать строку краем плитки.
// ⚠️ Замерено: ₽ = 0.50, ° = 0.46 — оба УЖЕ 0.60, то есть для тех строк, что сюда реально
// попадают (время и цена), запас настоящий. Буквы шире (1.22), но через эту формулу не проходят:
// оба вызывающих подставляют только цифры, пробелы, двоеточие и знак валюты.
export const WIDE_EM = 0.60;

/** Ширина строки в единицах кегля: сколько em займёт текст дисплейной гарнитурой. */
export function displayEm(text: string): number {
  let em = 0;
  for (const ch of text) {
    if (ch >= '0' && ch <= '9') em += DIGIT_EM;
    else if (ch === ':') em += COLON_EM;
    else if (ch === ' ' || ch === ' ' || ch === ' ') em += SPACE_EM;
    else em += WIDE_EM;
  }
  return em;
}
