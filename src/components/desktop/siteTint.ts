// Цвет подложки под иконку сайта, выведенный из имени домена: две разные плитки не сливаются
// в одинаковые серые квадраты, а цвет у сайта всегда один и тот же — от запуска к запуску.
//
// ⚠️ Оттенок берётся из ФИКСИРОВАННОГО набора, а не как `hash % 360`. Прежний код раздавал весь
// цветовой круг, включая сиреневый сектор (250–330°), — и это был последний генератор
// фиолетового в интерфейсе: translate.yandex.ru попадал ровно на 272°, t.me на 282°,
// translate.google.com на 316°. Значок самого сайта при этом прозрачный, так что весь квадрат
// светил нашим сиреневым, хотя у сайта в логотипе его нет вовсе. Сгенерированный цвет — такой
// же наш цвет, как токен, и правило «фиолетового в системе нет» распространяется и на него
// (см. --tile-* в colors.css).
//
// Набор идёт по кругу от красного к синему и обрывается перед фиолетовым; 348° — розово-красный
// хвост, он замыкает круг, не заходя в сиреневое.
const TILE_HUES = [8, 22, 36, 48, 96, 140, 168, 190, 210, 232, 348];

export function siteHue(host: string): number {
  let hash = 0;
  for (let i = 0; i < host.length; i++) hash = (hash * 31 + host.charCodeAt(i)) | 0;
  return TILE_HUES[Math.abs(hash) % TILE_HUES.length];
}

/** Готовый градиент подложки — светлее сверху, как у плиток приложений. */
export function siteTint(host: string): string {
  const hue = siteHue(host);
  return `linear-gradient(180deg, hsl(${hue} 62% 62%), hsl(${hue} 58% 48%))`;
}
