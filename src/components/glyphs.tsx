// вырезанные трекеры, VPN, — а замок обещает только первое (см. Toolbar.tsx).
const SHIELD = 'M12 3.2l7.2 2.9v5.6c0 4.3-2.9 7.9-7.2 9.3-4.3-1.4-7.2-5-7.2-9.3V6.1z';
