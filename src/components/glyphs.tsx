// ── Собственные глифы Oblako ──────────────────────────────────────────────────────────────────
//
// ⚠️ Это НЕ замена lucide целиком. Своими рисуются только те значки, которые человек видит
// каждую минуту: щит в адресной строке, звезда, часы, панель, настройки, AI, загрузки, VPN,
// навигация. В глубине настроек характер никто не заметит, а перерисовка всего набора стоила бы
// правки импортов в 64 файлах ради того же результата.
//
// ⚠️ Приём набора — ШТРИХ ПЛЮС ТЕЛО. Контур рисует currentColor, а внутрь кладётся полупрозрачная
// заливка тем же цветом: форма держится площадью, а не толщиной линии. Отсюда два следствия,
// ради которых всё и затевалось:
//   • на мелких размерах глиф не превращается в пятно — у lucide штрих фиксированные 2 px, то
//     есть 16,7 % размера при 12 px против 8,3 % задуманных рисовальщиком (разбор — glyph() в
//     src/styles/system.ts);
//   • значок читается как знак, а не как проволочная схема, — то самое «ярче и дерзче».
//
// ⚠️ Заливка выводится из currentColor через color-mix, а не задаётся цветом. Поэтому глиф
// автоматически прав в шести палитрах и обеих темах: покрасили родителя — покрасился и он.
import React from 'react';
import { glyph } from '../styles/system';

/** Доля тела в цвете контура. Выше — глиф читается плашкой, ниже — тело пропадает на светлом. */
const BODY_MIX = '22%';

interface GlyphProps {
  size?: number;
  /** Заполненное состояние: активная вкладка, включённый VPN, добавленная закладка. */
  filled?: boolean;
  className?: string;
  style?: React.CSSProperties;
}

/**
 * Общая обвязка. Толщина штриха приходит из шкалы (glyph), тело — из currentColor.
 *
 * ⚠️ vectorEffect здесь намеренно НЕ используется: он держит штрих постоянным в пикселях при
 * любом масштабе, а нам нужно ровно обратное — толщина обязана следовать размеру.
 */
function Glyph({ size = 16, filled, className, style, children }: GlyphProps & { children: React.ReactNode }) {
  const { strokeWidth } = glyph(size);
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      className={className}
      style={{
        display: 'block', flex: 'none',
        // Тело глифа. Заполненное состояние делает его заметно плотнее — это и есть «включено».
        ['--glyph-body' as string]: filled
          ? 'color-mix(in srgb, currentColor 62%, transparent)'
          : `color-mix(in srgb, currentColor ${BODY_MIX}, transparent)`,
        ...style,
      }}
      aria-hidden="true"
      focusable="false"
    >
      {children}
    </svg>
  );
}

/** Тело фигуры: та же геометрия, что у контура, но залитая и без штриха. */
const body = (d: string) => <path d={d} fill="var(--glyph-body)" stroke="none" />;

// ── Защита ────────────────────────────────────────────────────────────────────────────────────
