// Последний показанный список раздела библиотеки — чтобы возврат в раздел не начинался с пустого
// экрана и повторного ожидания IPC.
//
// ⚠️ Зачем вообще. Разделы (История, Закладки, Загрузки, Отслеживание) рисуются условно: ушёл на
// соседний — этот размонтирован целиком вместе со своим состоянием. Возврат каждый раз начинался
// с нуля, хотя данные не менялись, — именно это и читается как «переходы стали задумываться».
//
// ⚠️ Кэш, а не keep-alive через display:none. Держать все четыре раздела живыми означало бы
// держать и их подписки, и их DOM-деревья (у истории это до 500 строк) ради одного кадра.
//
// ⚠️ ГЛАВНОЕ ПРАВИЛО ЭТОГО ФАЙЛА: КЭШ ЗАБЫВАЕТСЯ ПРИ СМЕНЕ ПРОФИЛЯ. История, закладки и
// отслеживание живут НА ПРОФИЛЬ (electron/ProfileData.ts), а переключение профиля не
// перезагружает интерфейс — main просто рассылает «перечитайтесь» (см. PROFILES_SWITCH в
// electron/ipc/profiles.ts). Без сброса человек, переключившийся при закрытой библиотеке, увидел
// бы при следующем открытии закладки и покупки ЧУЖОГО профиля — ровно та утечка, ради ухода от
// которой данные и разводили по профилям.

/** Ячейка кэша: держит последнее значение и сама забывает его при смене профиля. */
export interface SectionCache<T> {
  get(): T;
  set(value: T): void;
}

// Подписка одна на модуль, а не на ячейку: ячеек несколько (у отслеживания их три), и вешать
// по слушателю на каждую значило бы плодить их на ровном месте.
const cells: { reset: () => void }[] = [];
let subscribed = false;

function subscribeOnce(): void {
  if (subscribed) return;
  subscribed = true;
  // ⚠️ Отписки нет намеренно: подписка живёт столько же, сколько сам документ чрома. Снимать её
  // было бы некому — модуль не размонтируется.
  try {
    window.oblako.onProfilesChanged(() => { for (const c of cells) c.reset(); });
  } catch {
    // В изолированных вью (поповеры) боевого window.oblako нет. Кэш там просто не переживает
    // смену профиля сам по себе — вью пересоздаётся вместе с содержимым.
  }
}

export function sectionCache<T>(empty: T): SectionCache<T> {
  let value = empty;
  cells.push({ reset: () => { value = empty; } });
  subscribeOnce();
  return {
    get: () => value,
    set: (next: T) => { value = next; },
  };
}
