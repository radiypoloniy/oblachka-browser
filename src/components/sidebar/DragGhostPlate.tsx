import type { ReactNode } from 'react';

/**
 * Плашка под призраком, который несут в руке НАД САЙДБАРОМ. Над областью контента ту же роль
 * играет карточка оверлея (см. src/dropzones.tsx): чром там не виден в принципе, поэтому рук две,
 * а язык у них обязан быть один.
 *
 * ⚠️ Классы те же, что у карточки половины сплита — `.oblako-drag-card` + `.oblako-drag-card-in`,
 * разбор кадров в `src/styles/global.css`. «Нечто в руке» в браузере одно, и говорить о нём двумя
 * разными способами незачем; заодно приезжает готовая ветка `prefers-reduced-motion`.
 *
 * ⚠️ Подъём здесь УМЕСТЕН — в отличие от чромовой карточки сплита, которой он намеренно не
 * достаётся. Разница в моменте появления: та возникает ПОСРЕДИ движения, когда курсор уходит с
 * области контента, и подъём читался бы как подпрыгивание на границе. Этот призрак появляется в
 * САМОМ НАЧАЛЕ жеста — вкладку берут именно в сайдбаре, и «взял в руку» здесь и происходит.
 *
 * ⚠️ `inline` — не косметика. DragOverlay у dnd-kit меряет призрак по несомому элементу, и у
 * ячеек свёрнутой полосы плашка обязана сжаться по содержимому, а у строки развёрнутой панели —
 * наоборот, занять её ширину. Раньше это жило восемью копиями одного inline-стиля, и разница
 * между ними была не записана нигде.
 */
export function DragGhostPlate({ children, inline = false, padding }: {
  children: ReactNode;
  inline?: boolean;
  padding?: number;
}) {
  return (
    <div
      className="oblako-drag-card oblako-drag-card-in"
      style={{
        boxShadow: 'var(--shadow-card)',
        borderRadius: 'var(--radius-sm)',
        background: 'var(--surface)',
        opacity: 0.95,
        ...(inline ? { display: 'inline-flex' } : null),
        ...(padding === undefined ? null : { padding }),
      }}
    >
      {children}
    </div>
  );
}
