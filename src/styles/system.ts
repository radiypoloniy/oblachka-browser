import type { CSSProperties } from 'react';

// ── ДИЗАЙН-СИСТЕМА OBLAKO: единственный файл, где живут ЧИСЛА ──────────────────
//
// Зачем он есть. Токены-переменные в `tokens/*.css` описывают ЦВЕТ и работают в CSS, но весь
// интерфейс проекта собран инлайновыми стилями в TSX — и числа туда попадали руками. Замер перед
// этой правкой: 20 разных значений `padding` и 18 разных `gap` только в компонентах. Глаз читает
// это как небрежность, даже не умея её назвать: строки не встают на общую невидимую сетку.
//
// Правило пользования: **в компонентах не должно быть цифр размера, только вызовы отсюда.**
// Хочется поменять плотность всего интерфейса — правится одна строка здесь, а не сорок мест.
// Сторож `scripts/conventions-check.mjs` следит за этим в области настроек.
//
// ⚠️ Порядок разделов ниже — это порядок, в котором дизайн обычно и правят: сначала воздух,
// потом форма, потом текст, потом движение, и только в конце — фирменный жест.

// ── 1. Воздух ─────────────────────────────────────────────────────────────────
// Шесть ступеней, других значений нет. Больше ступеней = снова двадцать отступов.
//   1 — внутри контрола (значок к тексту)
//   2 — между родственными строками
//   3 — вертикальный отступ строки списка
//   4 — горизонтальный отступ строки, зазор между контролами
//   6 — между блоками раздела, внутренний отступ панели
//   8 — между разделами
export const SPACE = { 1: 4, 2: 8, 3: 12, 4: 16, 6: 24, 8: 32 } as const;
export type SpaceStep = keyof typeof SPACE;

/** Отступ по шкале: sp(3) === 12. Иначе число в компоненте — это отступ «на глаз». */
export const sp = (step: SpaceStep): number => SPACE[step];

/** Пара «вертикаль горизонталь» для padding: pad(3, 4) === '12px 16px'. */
export const pad = (v: SpaceStep, h: SpaceStep = v): string => `${SPACE[v]}px ${SPACE[h]}px`;

// ── 2. Форма ──────────────────────────────────────────────────────────────────
// Три радиуса и пилюля. ⚠️ Правило вложенности: ВНЕШНИЙ = ВНУТРЕННИЙ + ОТСТУП. Контрол r8
// внутри коробки с полем 12 требует внешнего r20 — иначе скругления вложены неточно, и глаз
// ловит это даже на два пикселя. Прежний набор был 20 / 13 / 8: тринадцать не согласовано ни с
// чем и появилось «чтобы было помягче».
export const RADIUS = {
  control: 8,   // кнопка, поле ввода, строка списка, сегмент
  box: 12,      // коробка: список, панель статуса, форма
  island: 20,   // острова оболочки: сайдбар, тулбар, сцена
  pill: 999,    // чипы и круглые кнопки
} as const;

// ── 3. Текст ──────────────────────────────────────────────────────────────────
// Четыре роли вместо семи ступеней «на выбор». ⚠️ Разница между ролями обязана быть ЗАМЕТНОЙ:
// до этой правки заголовок блока (14/600) и его описание (12,5) отличались на полтора пункта,
// иерархии не возникало и экран читался серой массой.
export const TEXT: Record<'title' | 'section' | 'body' | 'caption', CSSProperties> = {
  // Заголовок раздела: «Локальные модели», «Тема».
  title: { fontSize: 22, fontWeight: 600, letterSpacing: '-0.01em', lineHeight: 1.25, color: 'var(--text-strong)' },
  // Заголовок блока внутри раздела: «Поиск по умолчанию», «Тема».
  section: { fontSize: 16, fontWeight: 600, lineHeight: 1.35, color: 'var(--text-strong)' },
  // Обычный текст, описания.
  body: { fontSize: 14, lineHeight: 1.5, color: 'var(--text-body)' },
  // Подписи, единицы, «2.7 ГБ · в памяти».
  caption: { fontSize: 12.5, lineHeight: 1.45, color: 'var(--text-faint)' },
};

/** Название строки списка: тело с усилением, а не отдельная ступень. */
export const ROW_TITLE: CSSProperties = { ...TEXT.body, fontWeight: 600, color: 'var(--text-strong)' };

/** Надпись группы капсом («УСТАНОВЛЕННЫЕ МОДЕЛИ»). Отдельно от TEXT: это не роль, а приём. */
export const CAPS: CSSProperties = {
  fontSize: 12.5, fontWeight: 600, letterSpacing: 'var(--ls-caps)',
  textTransform: 'uppercase', color: 'var(--text-faint)',
};

// ── 4. Движение ───────────────────────────────────────────────────────────────
// ⚠️ Токены движения в проекте были и раньше (120/180/260 мс, две кривые), но на весь
// компонентный слой приходилось 25 переходов: интерфейс переключался мгновенно и читался дёшево.
// Дорогая оболочка ОТВЕЧАЕТ на касание, а не перерисовывается.
//
// Пользоваться так: `transition: motion.hover('background', 'transform')`.
export const motion = {
  /** Отклик на наведение и нажатие — самое частое. */
  hover: (...props: string[]) => props.map((p) => `${p} var(--dur-fast) var(--ease-standard)`).join(', '),
  /** Смена состояния: раскрытие блока, переключение сегмента. */
  state: (...props: string[]) => props.map((p) => `${p} var(--dur-base) var(--ease-out)`).join(', '),
  /** Появление слоя: панель, поповер, смена палитры. */
  enter: (...props: string[]) => props.map((p) => `${p} var(--dur-slow) var(--ease-out)`).join(', '),
  /** Подъём под курсором. Один пиксель — этого достаточно, больше читается как прыжок. */
  lift: 'translateY(-1px)',
};

// ── 5. Фирменный жест: ореол ──────────────────────────────────────────────────
//
// Мягкое свечение тона палитры за тем островом, на который человек смотрит: «облако» под
// активным элементом. У Arc роль такого жеста играет цвет пространства, у Dia — пустота, у Zen —
// стекло; у нас образ уже есть в названии.
//
// ⚠️ ОДИН НА ЭКРАН. Два ореола гасят друг друга и превращаются в общий туман.
//
// ⚠️ ВЫКЛЮЧАТЕЛЬ ЗДЕСЬ. Жест экспериментальный, и откат обязан быть в одну строку: поставьте
// HALO_ENABLED = false — и `halo()` начнёт возвращать пустой стиль, ничего больше править не
// нужно. Так же настраивается сила: HALO_STRENGTH — доля тона в свечении.
export const HALO_ENABLED = true;
const HALO_STRENGTH = 0.28;   // 0 — нет свечения, 1 — тон в полную силу
const HALO_SPREAD = 22;       // радиус растекания, px

/**
 * Стиль ореола для активного острова.
 * Свечение строится тенью БЕЗ смещения: это не «тень предмета», а свет за ним.
 */
export function halo(active: boolean): CSSProperties {
  if (!HALO_ENABLED || !active) return {};
  return {
    boxShadow: `0 0 ${HALO_SPREAD}px color-mix(in srgb, var(--accent) ${Math.round(HALO_STRENGTH * 100)}%, transparent)`,
    transition: motion.enter('box-shadow'),
  };
}
