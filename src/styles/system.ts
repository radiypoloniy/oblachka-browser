// ── 7. Высоты ─────────────────────────────────────────────────────────────────
//
// Дизайн-система «Высота» (утверждена 18.08.2026). Элемент не выбирает оформление — он выбирает
// ВЫСОТУ, а материал, тень и радиус выводятся из неё. Это и лечит главную беду прежней системы:
// панель, карточка, строка и кнопка отличались только рамкой, всё лежало на одной плоскости, и
// поэтому интерфейс читался плоским листом.
//
//   0 · ЗЕМЛЯ   — фон окна. Теней нет вовсе.
//   1 · ТУМАН   — стекло: только там, где под слоем есть что размывать (виджет над фото).
//   2 · ОСТРОВ  — плотная поверхность: тень + внутренний свет по верхней кромке.
//   3 · ГЕРОЙ   — цвет в полную силу: градиент акцента со спутником. ОДИН НА ЭКРАН.
//
// ⚠️ «Один герой» — не пожелание, а условие, при котором ему разрешено быть ярким. Кого делать
// героем, решает ЧЕЛОВЕК (набор виджетов у каждого свой), поэтому флаг живёт в раскладке стола, а
// не в коде; переключение снимает флаг с прежнего героя — см. setHero в newtab/desktop.ts.
export const ALTITUDE = { ground: 0, mist: 1, island: 2, hero: 3 } as const;
export type Altitude = typeof ALTITUDE[keyof typeof ALTITUDE];

/** Выключатели уровней: каждый гасится отдельно, интерфейс при этом остаётся рабочим. */
export const GLASS_ENABLED = true;
export const HERO_ENABLED = true;

/**
 * Материал по высоте. Всё, что отличает уровни, собрано здесь — правится в одном месте.
 *
 * ⚠️ Радиус тоже приходит отсюда: у содержимого он крупнее, чем у хрома, и это читается раньше
 * цвета (см. RADIUS.content).
 */
export function altitude(level: Altitude, opts: { content?: boolean } = {}): CSSProperties {
  const radius = opts.content ? RADIUS.content : RADIUS.box;
  switch (level) {
    case ALTITUDE.ground:
      return { background: 'var(--app-bg)', borderRadius: radius };
    case ALTITUDE.mist:
      return GLASS_ENABLED ? { ...cardGlass(), borderRadius: radius, boxShadow: 'var(--shadow-lvl1)' }
        : { ...card(), borderRadius: radius, boxShadow: 'var(--shadow-lvl2)' };
    case ALTITUDE.island:
      return {
        background: 'var(--surface)', borderRadius: radius,
        boxShadow: 'var(--shadow-lvl2), var(--inner-light)',
        border: '1px solid var(--divider)',
      };
    case ALTITUDE.hero:
      return HERO_ENABLED ? {
        // ⚠️ Единственное место, где цвет звучит в полную силу. Спутник выводится из акцента
        // палитры формулой, поэтому шесть палитр остаются шестью.
        background: 'linear-gradient(150deg, color-mix(in srgb, var(--accent) 92%, #000) 0%, var(--companion) 100%)',
        color: 'var(--on-accent)',
        borderRadius: radius,
        boxShadow: 'var(--shadow-lvl3)',
      } : { background: 'var(--surface)', borderRadius: radius, boxShadow: 'var(--shadow-lvl2), var(--inner-light)' };
  }
}

/**
 * Углубление — ступень НИЖЕ земли: дорожка сегментов, поле ввода, трек ползунка.
 *
 * ⚠️ «Высота» до этого умела только подниматься (туман → остров → герой), и всё, чему полагалось
 * быть утопленным, каждый компонент решал сам: где --surface-sunken, где ничего. Отсюда и жалоба,
 * что переключатель в сайдбаре «не имеет выраженного углубления», — там дорожку просто убрали,
 * потому что на земле её не было видно.
 *
 * Заливка ЗДЕСЬ ВТОРИЧНА и выводится из чернил палитры, поэтому на цветной земле выемка остаётся
 * своей, а не серой полосой из другой темы. Основную работу делает свет (--inner-well).
 */
export function well(radius: number = RADIUS.control): CSSProperties {
  return {
    background: 'color-mix(in srgb, var(--text-strong) 6%, transparent)',
    borderRadius: radius,
    boxShadow: 'var(--inner-well)',
  };
}

// ── 7б. Иконки ────────────────────────────────────────────────────────────────
//
// ⚠️ ШТРИХ ОБЯЗАН СЛЕДОВАТЬ РАЗМЕРУ. Иконки lucide нарисованы для 24 px и несут штрих 2 px; в
// интерфейсе они стоят пятнадцати разных размеров, а толщина оставалась той же. В долях от размера
// это значит: 8,3 % при 24 px (как задумал рисовальщик), 12,5 % при 16 и 16,7 % при 12 — на мелких
// размерах штрих затягивает внутренние просветы, и глиф превращается в пятно. Именно это читается
// как «иконки старые», хотя набор современный.
//
// ⚠️ Толщина растёт МЕДЛЕННЕЕ размера, а не пропорционально ему. Честная пропорция (size/12) дала
// бы 1,17 при 14 px — оптически это уже хилая паутина: тонкая линия на мелком кегле теряется раньше,
// чем толстая начинает мешать. Поэтому доля плавно падает с 11,9 % до 8,3 %, как в наборах, где
// начертания рисуют под каждый размер отдельно.
export const ICON = { sm: 14, md: 16, lg: 18, xl: 22 } as const;
export type IconSize = typeof ICON[keyof typeof ICON];

/** Пропсы для иконки: размер из шкалы плюс выведенная из него толщина штриха. */
export function glyph(size: number): { size: number; strokeWidth: number } {
  return { size, strokeWidth: Math.round((1.2 + size * 0.033) * 20) / 20 };
}

// ── 8. Панель-остров ──────────────────────────────────────────────────────────
//
// ⚠️ ОДИН рецепт на все полноэкранные панели: настройки, история, закладки, загрузки,
// отслеживание. Заведён после того, как одинаковые с виду панели повели себя по-разному: у
// настроек тень была, у истории — только угол. Разбор через DOM показал, что дело не в рецепте
// (он совпадал до пикселя), а в ОКРУЖЕНИИ: настройки лежат в родителе с полем 12 px и
// `overflow: visible`, а история — внутри прокрутки `overflow: hidden auto` ровно своей ширины,
// которая срезала тень по бокам.
//
// Отсюда правило: тень — это не только рецепт панели, но и МЕСТО под неё. Панель, попавшая в
// клиппинг-родителя, обязана получить `panelRoom` — поле, в которое тени есть куда лечь.
export const SHADOW_ROOM = 16;

/** Материал панели: поверхность, скругление, лестница теней, внутренний свет. */
export function panelIsland(): CSSProperties {
  return {
    background: 'var(--surface-solid)',
    borderRadius: RADIUS.island,
    // ⚠️ border: none — кромку рисует КОЛЬЦО первой ступени лестницы. Рамка поверх кольца давала
    // вторую жёсткую линию по тому же периметру, и тень читалась «угловатой».
    border: 'none',
    boxShadow: 'var(--shadow-lvl3), var(--inner-light)',
  };
}

/** Поле вокруг панели — чтобы тень не срезал клиппинг-родитель. */
export const panelRoom: CSSProperties = { padding: SHADOW_ROOM, boxSizing: 'border-box' };
