// ── 4. Движение ───────────────────────────────────────────────────────────────
// ⚠️ Токены движения в проекте были и раньше (120/180/260 мс, две кривые), но на весь
// компонентный слой приходилось 25 переходов: интерфейс переключался мгновенно и читался дёшево.
// Дорогая оболочка ОТВЕЧАЕТ на касание, а не перерисовывается.
//
// Пользоваться так: `transition: motion.hover('background', 'transform')`.
export const motion = {
  /** Отклик на наведение и нажатие — самое частое. */
  hover: (...props: string[]) => props.map((p) => `${p} var(--dur-fast) var(--ease-standard)`).join(', '),
  /** Смена состояния: раскрытие блока, переключение сегмента. */
  state: (...props: string[]) => props.map((p) => `${p} var(--dur-base) var(--ease-out)`).join(', '),
  /** Появление слоя: панель, поповер, смена палитры. */
  enter: (...props: string[]) => props.map((p) => `${p} var(--dur-slow) var(--ease-out)`).join(', '),
  /** Подъём под курсором. Один пиксель — этого достаточно, больше читается как прыжок. */
  lift: 'translateY(-1px)',
};

// ── 5. Фирменный жест: ореол ──────────────────────────────────────────────────
//
// Мягкое свечение тона палитры за тем островом, на который человек смотрит: «облако» под
// активным элементом. У Arc роль такого жеста играет цвет пространства, у Dia — пустота, у Zen —
// стекло; у нас образ уже есть в названии.
//
// ⚠️ ОДИН НА ЭКРАН. Два ореола гасят друг друга и превращаются в общий туман.
//
// ⚠️ СЕЙЧАС ВЫКЛЮЧЕН. Живой отзыв: «не нравится идея с облаком, очень плохо видно активную
// строку» — свечение расплывалось по краю и вместо того, чтобы указывать на выбранное, размывало
// его границу. Выделение теперь делает selected() ниже: заливка и полоса, а не свет.
// Код оставлен и работает — вернуть можно одной строкой, если найдётся место, где ореол уместен
// (например, за одной крупной карточкой, а не за строкой списка).
//
// ⚠️ ВЫКЛЮЧАТЕЛЬ ЗДЕСЬ. Жест экспериментальный, и откат обязан быть в одну строку: поставьте
// HALO_ENABLED = false — и `halo()` начнёт возвращать пустой стиль, ничего больше править не
// нужно. Так же настраивается сила: HALO_STRENGTH — доля тона в свечении.
export const HALO_ENABLED = false;
const HALO_STRENGTH = 0.28;   // 0 — нет свечения, 1 — тон в полную силу
const HALO_SPREAD = 22;       // радиус растекания, px

/**
 * Выделение выбранной строки: заливка акцентом плюс полоса у левого края.
 *
 * ⚠️ Полоса появилась потому, что одной заливки в 10% не хватало — на цветной земле она почти
 * сливалась с фоном («очень плохо видно активную строку»). Поднимать процент нельзя: заливка
 * начинает спорить с текстом. Полоса даёт опору краю, не трогая читаемость.
 */
export function selected(active: boolean): CSSProperties {
  if (!active) return {};
  return {
    background: 'var(--accent-soft)',
    boxShadow: 'inset 3px 0 0 var(--accent)',
  };
}

/**
 * Стиль ореола для активного острова.
 * Свечение строится тенью БЕЗ смещения: это не «тень предмета», а свет за ним.
 */
export function halo(active: boolean): CSSProperties {
  if (!HALO_ENABLED || !active) return {};
  return {
    boxShadow: `0 0 ${HALO_SPREAD}px color-mix(in srgb, var(--accent) ${Math.round(HALO_STRENGTH * 100)}%, transparent)`,
    transition: motion.enter('box-shadow'),
  };
}

// ── 6. Поверхности содержимого (модель Material) ──────────────────────────────
//
// ⚠️ ПЕРЕПИСАНО после живой жалобы: «перекрасить виджет — это полдела, выглядит уродливо, будто
// обоссали». Первая версия раздавала каждой теме свой пастельный фон (погода — голубой, деньги —
// песочный), и шесть заливок рядом читались винегретом, а бежевая на большой площади — грязью.
//
// Как цветные виджеты устроены в Android (проверено по документации Glance, а не по памяти):
//   • фон виджета — `surfaceContainer`: НЕЙТРАЛЬ с намёком тона, а не пастель;
//   • цвет живёт в ЭЛЕМЕНТАХ внутри — чип, ключевое число, график (`primaryContainer`);
//   • всё выведено из ОДНОГО семени темы, поэтому экран остаётся одноцветным.
//
// У нас семя — акцент палитры. Отсюда два следствия: карточки автоматически следуют выбору
// человека (сменил палитру — сменился весь стол), и «перекрасить продукт» по-прежнему стоит одну
// строку — только теперь в palettes.css, а не в таблице тем.
//
// ⚠️ ВЫКЛЮЧАТЕЛЬ на месте: false — и карточки возвращаются к нейтральной поверхности темы.
export const CARD_COLOR_ENABLED = true;

/** Фон карточки содержимого. `high` — для той, что должна выделиться (одна на экран). */
export function card(high = false): CSSProperties {
  if (!CARD_COLOR_ENABLED) return { background: 'var(--surface)', color: 'var(--text-body)' };
  return { background: high ? 'var(--card-high)' : 'var(--card)', color: 'var(--text-body)' };
}

/**
 * Материал карточки НАД КАРТИНКОЙ — стекло.
 *
 * ⚠️ Это не украшение, а единственный способ не испортить обои. Непрозрачная плитка поверх фото
 * работает как заплатка: она закрывает то, ради чего человек фото и поставил, и читается нелепо
 * (живая жалоба: «картинка сломана, выглядит нелепо»). И iOS, и Android над обоями дают виджетам
 * именно стекло: полупрозрачная подложка, размытие того, что под ней, и волосяная кромка.
 *
 * ⚠️ Над РОВНЫМ фоном (цвет, градиент) стекло бессмысленно — размывать нечего, а расход есть.
 * Поэтому материал выбирается по виду фона, а не ставится всюду.
 */
export function cardGlass(): CSSProperties {
  return {
    background: 'color-mix(in srgb, var(--surface) 62%, transparent)',
    backdropFilter: 'blur(24px) saturate(140%)',
    WebkitBackdropFilter: 'blur(24px) saturate(140%)',
    border: '1px solid color-mix(in srgb, var(--surface) 55%, transparent)',
    color: 'var(--text-body)',
    // ⚠️ Три строки против артефактов композитинга, а не ради красоты. Живая жалоба: «багуется
    // стекло в виджетах AI-панели, какая-то полоса, которая исчезает по клику» — это классика
    // backdrop-filter в Chromium: элемент без собственного слоя берёт подложку из устаревшего
    // кадра, и полоса живёт до следующей перерисовки (клик её и вызывает).
    //   • translateZ(0) — поднимаем стекло на свой слой;
    //   • willChange — говорим компоситору, что фильтр будет меняться;
    //   • isolation — свой контекст наложения, чтобы фон брался из-под элемента, а не из-под
    //     соседей по общему слою.
    transform: 'translateZ(0)',
    willChange: 'backdrop-filter',
    isolation: 'isolate',
  };
}

/**
 * Чип: цветной элемент ВНУТРИ карточки — подложка значка, метка, выделенное значение.
 * Это и есть место, где в модели Material живёт цвет.
 */
export function chip(): CSSProperties {
  if (!CARD_COLOR_ENABLED) return { background: 'var(--surface-sunken)', color: 'var(--text-body)' };
  return { background: 'var(--card-chip)', color: 'var(--text-strong)' };
}

