import type { CSSProperties } from 'react';

// ── ДИЗАЙН-СИСТЕМА OBLAKO: единственный файл, где живут ЧИСЛА ──────────────────
//
// Зачем он есть. Токены-переменные в `tokens/*.css` описывают ЦВЕТ и работают в CSS, но весь
// интерфейс проекта собран инлайновыми стилями в TSX — и числа туда попадали руками. Замер перед
// этой правкой: 20 разных значений `padding` и 18 разных `gap` только в компонентах. Глаз читает
// это как небрежность, даже не умея её назвать: строки не встают на общую невидимую сетку.
//
// Правило пользования: **в компонентах не должно быть цифр размера, только вызовы отсюда.**
// Хочется поменять плотность всего интерфейса — правится одна строка здесь, а не сорок мест.
// Сторож `scripts/conventions-check.mjs` следит за этим в области настроек.
//
// ⚠️ Порядок разделов ниже — это порядок, в котором дизайн обычно и правят: сначала воздух,
// потом форма, потом текст, потом движение, и только в конце — фирменный жест.

// ── 1. Воздух ─────────────────────────────────────────────────────────────────
// Шесть ступеней, других значений нет. Больше ступеней = снова двадцать отступов.
//   1 — внутри контрола (значок к тексту)
//   2 — между родственными строками
//   3 — вертикальный отступ строки списка
//   4 — горизонтальный отступ строки, зазор между контролами
//   6 — между блоками раздела, внутренний отступ панели
//   8 — между разделами
export const SPACE = { 1: 4, 2: 8, 3: 12, 4: 16, 6: 24, 8: 32 } as const;
export type SpaceStep = keyof typeof SPACE;

/** Отступ по шкале: sp(3) === 12. Иначе число в компоненте — это отступ «на глаз». */
export const sp = (step: SpaceStep): number => SPACE[step];

/** Пара «вертикаль горизонталь» для padding: pad(3, 4) === '12px 16px'. */
export const pad = (v: SpaceStep, h: SpaceStep = v): string => `${SPACE[v]}px ${SPACE[h]}px`;

// ── 2. Форма ──────────────────────────────────────────────────────────────────
// Три радиуса и пилюля. ⚠️ Правило вложенности: ВНЕШНИЙ = ВНУТРЕННИЙ + ОТСТУП. Контрол r8
// внутри коробки с полем 12 требует внешнего r20 — иначе скругления вложены неточно, и глаз
// ловит это даже на два пикселя. Прежний набор был 20 / 13 / 8: тринадцать не согласовано ни с
// чем и появилось «чтобы было помягче».
export const RADIUS = {
  control: 8,   // кнопка, поле ввода, строка списка, сегмент
  box: 12,      // коробка: список, панель статуса, форма
  island: 20,   // острова оболочки: сайдбар, тулбар, сцена
  // ⚠️ У СОДЕРЖИМОГО геометрия своя и крупнее, чем у хрома: два мира — разная форма, и это
  // читается раньше, чем цвет. Карточки стола, плитки хаба, приложения AI.
  content: 22,
  pill: 999,    // чипы и круглые кнопки
} as const;

